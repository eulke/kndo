/// Swift's access levels as reaches: `fileprivate` is the file's; `private`
/// is the file's on a top-level declaration and the owner's on a member
/// (extensions in the same file included, which the file pool holds); NO
/// modifier and `internal` are the module boundary → the unit's reach (the
/// default rung), which a `@testable import` widens to the test target the
/// manifest made its friend; `package` is the group of targets one package
/// aggregates; `public`/`open` → Exported.
fn reach_of(item: Node<'_>, source: &[u8]) -> Reach {
    declared_reach(item, source).unwrap_or(Reach::Unit { up: 0 })
}

/// The same, for a member whose owner hands something down when the source
/// spells nothing: a protocol requirement, a member of a `public extension`.
fn member_reach(item: Node<'_>, source: &[u8], inherits: Option<Reach>) -> Reach {
    declared_reach(item, source)
        .or(inherits)
        .unwrap_or(Reach::Unit { up: 0 })
}

/// What the source SPELLS, or `None` where it spells nothing.
fn declared_reach(item: Node<'_>, source: &[u8]) -> Option<Reach> {
    let modifiers = tk::child_of_kind(item, "modifiers")?;
    let mut c = modifiers.walk();
    for m in modifiers.named_children(&mut c) {
        if m.kind() == "visibility_modifier" {
            return Some(
                match tk::text(m, source)
                    .split('(')
                    .next()
                    .unwrap_or_default()
                    .trim()
                {
                    "fileprivate" => Reach::File,
                    "private" => {
                        if item.parent().is_none_or(|p| p.kind() == "source_file") {
                            Reach::File
                        } else {
                            Reach::Owner
                        }
                    }
                    "package" => Reach::Unit { up: 1 },
                    "public" | "open" => Reach::Exported,
                    // `internal`, or a form we do not know — the default rung.
                    _ => Reach::Unit { up: 0 },
                },
            );
        }
    }
    None
}

fn has_modifier(item: Node<'_>, source: &[u8], word: &str) -> bool {
    let Some(modifiers) = tk::child_of_kind(item, "modifiers") else {
        return false;
    };
    let mut found = false;
    tk::walk(modifiers, &mut |n| {
        if n.child_count() == 0 && tk::text(n, source) == word {
            found = true;
        }
    });
    found
}

fn has_attribute(item: Node<'_>, source: &[u8], name: &str) -> bool {
    let Some(modifiers) = tk::child_of_kind(item, "modifiers") else {
        return false;
    };
    let mut c = modifiers.walk();
    modifiers
        .named_children(&mut c)
        .filter(|n| n.kind() == "attribute")
        .any(|attr| {
            let mut ac = attr.walk();
            attr.named_children(&mut ac)
                .any(|n| n.kind() == "user_type" && tk::text(n, source) == name)
        })
}

/// Every attribute a declaration carries, as a MARKER: its path as written
/// (`main`, `objc`, `Test`, `IBAction`, `propertyWrapper`) and its arguments.
/// Structural, never a table of names — what an attribute MEANS is a dispatch
/// rule's to say, this adapter's job is to report that it is there.
///
/// `override` rides here too. The glossary counts a MODIFIER as a marker, and
/// this is the one Swift modifier a rule reads: an overriding member is
/// invoked through the superclass, so no source line names it. The rest of
/// Swift's modifiers are read where they belong — visibility as `Reach` — or
/// have no consumer, and a marker no rule reads is noise in the evidence.
fn markers_of(item: Node<'_>, source: &[u8], id: DeclarationId, out: &mut EvidenceSink) {
    let Some(modifiers) = tk::child_of_kind(item, "modifiers") else {
        return;
    };
    let mut c = modifiers.walk();
    for m in modifiers.named_children(&mut c) {
        match m.kind() {
            "attribute" => {
                let mut ac = m.walk();
                let children: Vec<Node<'_>> = m.named_children(&mut ac).collect();
                let Some(name) = children.iter().find(|n| n.kind() == "user_type") else {
                    continue;
                };
                let args = children
                    .iter()
                    .filter(|n| n.kind() == "value_argument")
                    .map(|n| SmolStr::new(tk::text(*n, source).trim_matches('"')))
                    .collect();
                out.marker(
                    MarkerTarget::Declaration(id),
                    tk::text(*name, source),
                    args,
                    tk::span(m),
                );
            }
            _ if tk::text(m, source) == "override" => {
                out.marker(
                    MarkerTarget::Declaration(id),
                    "override",
                    Vec::new(),
                    tk::span(m),
                );
            }
            _ => {}
        }
    }
}

/// Every type this declaration promises the surface of, as a RELATION.
///
/// Swift writes one list after the colon and its grammar does not tell a
/// superclass from a protocol — `class A: B, C` is legal with B a class or a
/// protocol, and only the whole program knows which. So one kind is emitted,
/// and it is the true sentence for both: `Implements` is the contract's word
/// for "promises another type's surface", which a subclass does as much as a
/// conformer. Nothing in the engine reads the kind — it reaches a
/// `Trigger::Relation` and the supertype edges, and both compare NAMES.
fn relations_of(item: Node<'_>, source: &[u8], id: DeclarationId, out: &mut EvidenceSink) {
    let mut c = item.walk();
    for spec in item
        .named_children(&mut c)
        .filter(|n| n.kind() == "inheritance_specifier")
    {
        // `: XCTestCase`, `: Encodable`, `: Collection where …` — the name is
        // the specifier's own type, and a generic argument list is not it.
        let mut sc = spec.walk();
        let named: Vec<Node<'_>> = spec.named_children(&mut sc).collect();
        let Some(ty) = named
            .iter()
            .find(|n| matches!(n.kind(), "user_type" | "type_identifier"))
        else {
            continue;
        };
        // `Swift.Codable` and `Codable` are the same promise; the last
        // segment is the name every rule and every supertype edge compares.
        let mut tc = ty.walk();
        let name = ty
            .named_children(&mut tc)
            .filter(|n| n.kind() == "type_identifier")
            .last()
            .map(|n| tk::text(n, source))
            .unwrap_or_else(|| tk::text(*ty, source));
        out.relation(id, RelationKind::Implements, name, tk::span(spec));
    }
}

/// The operator a `func` declares, where the grammar leaves it an anonymous
/// token: the child right after `func`, when nothing named took the name seat.
fn operator_name<'a>(item: Node<'_>, source: &'a [u8]) -> Option<&'a str> {
    let mut c = item.walk();
    let children: Vec<Node<'_>> = item.children(&mut c).collect();
    let at = children.iter().position(|n| n.kind() == "func")?;
    let token = children.get(at + 1)?;
    (!token.is_named() && token.kind() != "(").then(|| tk::text(*token, source))
}

fn has_conformances(item: Node<'_>) -> bool {
    let mut c = item.walk();
    item.named_children(&mut c)
        .any(|ch| ch.kind() == "inheritance_specifier")
}

// ---------------------------------------------------------------- references

/// The expression kinds whose operator token is a NAME a declaration can
/// match. Not every anonymous token is one: `->`, `?` and `!` are syntax, and
/// only these seats hold an operator the source could have written a `func`
/// for.
const OPERATOR_EXPRESSIONS: &[&str] = &[
    "additive_expression",
    "multiplicative_expression",
    "equality_expression",
    "comparison_expression",
    "conjunction_expression",
    "disjunction_expression",
    "nil_coalescing_expression",
    "range_expression",
    "bitwise_operation",
    "prefix_expression",
    "postfix_expression",
];

/// One flat pass for references and comments: identifiers classify by their
/// syntactic seat; binder positions (declaration names, parameter names,
/// argument labels, import segments) never become references. Enum-case
/// dot-shorthand (`.retry`) lands as a Read of the bare name — the pool-side
/// counterpart of never declaring the cases.
fn references_and_comments(root: Node<'_>, source: &[u8], out: &mut EvidenceSink) {
    tk::walk_pruned(root, &["import_declaration"], &mut |n| match n.kind() {
        "comment" | "multiline_comment" => {
            tk::comment_evidence(n, source, &COMMENTS, out);
        }
        // An operator APPLICATION: `a == b` names `==`, which some type in
        // the project may declare (`static func == (l:r:)`). The grammar
        // leaves the operator an anonymous token on both sides — the
        // declaration and the use — so the two join by the same spelling.
        k if !k.is_empty()
            && n.parent()
                .is_some_and(|p| OPERATOR_EXPRESSIONS.contains(&p.kind()))
            && !n.is_named() =>
        {
            out.reference_on(k, RefKind::Call, None, tk::span(n));
        }
        "simple_identifier" | "type_identifier" => {
            if let Some(parent) = n.parent() {
                if is_binder_seat(n, parent) {
                    return;
                }
                out.reference_on(
                    bare(tk::text(n, source)),
                    classify(n, parent),
                    receiver_of(parent, source),
                    tk::span(n),
                );
            }
        }
        _ => {}
    });
}

/// What `expr.member` was read FROM, where the source spells it as a name:
/// the `target` of the navigation this identifier is the suffix of. A target
/// that is itself an expression (`a.b.c`, `f().x`) names nothing the pool can
/// use, and absence is the honest answer there.
fn receiver_of(parent: Node<'_>, source: &[u8]) -> Option<SmolStr> {
    if parent.kind() != "navigation_suffix" {
        return None;
    }
    let target = parent.parent()?.child_by_field_name("target")?;
    matches!(target.kind(), "simple_identifier" | "type_identifier")
        .then(|| SmolStr::new(bare(tk::text(target, source))))
}

/// Identifier positions that BIND a new name rather than use one.
fn is_binder_seat(n: Node<'_>, parent: Node<'_>) -> bool {
    match parent.kind() {
        "class_declaration"
        | "protocol_declaration"
        | "function_declaration"
        | "protocol_function_declaration"
        | "typealias_declaration"
        | "init_declaration" => parent.child_by_field_name("name") == Some(n),
        // `case fast, slow` — every identifier seat in an entry binds a case.
        "enum_entry" => true,
        // Parameter external/internal names and argument labels.
        "parameter" => true,
        "value_argument" => parent.child_by_field_name("name") == Some(n),
        // Property and switch binding patterns (`let (a, b)` included). NOT
        // `property_declaration` itself: its `name` field IS a `pattern`, so
        // every bound name is already covered here, and the only other
        // identifier directly under it is the `value` — `let alpha = beta`
        // reads `beta`, which naming the parent kind used to throw away.
        //
        // A pattern that starts with `.` binds nothing: `case .space` USES an
        // enum case by dot-shorthand, which is the pervasive form and the
        // pool-side counterpart of never declaring the cases.
        "pattern" => !dot_shorthand(n),
        "value_binding_pattern" => true,
        "type_parameter" => true,
        _ => false,
    }
}

/// Is this identifier the member half of a leading-dot shorthand — `.space`
/// in a pattern, where the type is inferred and only the name is written?
fn dot_shorthand(n: Node<'_>) -> bool {
    n.prev_sibling().is_some_and(|s| s.kind() == ".")
}

fn classify(n: Node<'_>, parent: Node<'_>) -> RefKind {
    match parent.kind() {
        // Callee position: `foo(...)` — the call's first child.
        "call_expression" if parent.child(0) == Some(n) => RefKind::Call,
        // Member seat: `expr.member` — a call when the navigation itself is a
        // call's callee.
        "navigation_suffix" => {
            let called = parent.parent().is_some_and(|nav| {
                nav.parent()
                    .is_some_and(|gp| gp.kind() == "call_expression" && gp.child(0) == Some(nav))
            });
            if called { RefKind::Call } else { RefKind::Read }
        }
        "user_type" => {
            let in_inheritance = {
                let mut a = parent.parent();
                let mut hit = false;
                while let Some(node) = a {
                    if node.kind() == "inheritance_specifier" {
                        hit = true;
                        break;
                    }
                    a = node.parent();
                }
                hit
            };
            if in_inheritance {
                RefKind::Extend
            } else {
                RefKind::TypeUse
            }
        }
        _ => RefKind::Read,
    }
}
