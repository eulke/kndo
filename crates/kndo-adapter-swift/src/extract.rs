//! Extraction against tree-sitter-swift 0.7.3, every node kind verified in its
//! `node-types.json`. Members attribute to their enclosing type; an
//! `extension Foo` block declares nothing itself and hands `Foo` to its
//! members (a `class_declaration` whose `declaration_kind` is `extension`,
//! named by a possibly-qualified `user_type` — the last segment is the bare
//! name). Initializers, deinitializers and enum cases are never declared (the
//! shared constructor posture, and `.case` dot-shorthand resolves by type, not
//! name); their bodies still contribute references.

use kndo_contract::evidence::{
    Attachment, DeclarationId, EvidenceSink, MarkerTarget, Reach, RefKind, RelationKind, RootKind,
    RootTarget, SymbolKind,
};
use kndo_contract::vocab::{Confidence, ProjectPath};
use kndo_toolkit as tk;
use smol_str::SmolStr;
use tree_sitter::Node;

/// The Swift ecosystem's generated-file needles: the shared convention plus
/// `Generated by` (Sourcery, protoc-gen-swift stamp it).
const GENERATED_NEEDLES: &[&str] = &[
    "@generated",
    "Code generated",
    "DO NOT EDIT",
    "Generated by",
];

const COMMENTS: tk::CommentMarkers<'static> = tk::CommentMarkers {
    line: &["//"],
    block: &[("/*", "*/")],
    line_doc: b"/",
    block_doc: b"*",
};

const METRICS: tk::MetricsSpec = tk::MetricsSpec {
    is_branch: |n, _| match n.kind() {
        // A `switch` arm counts unless it is the default — the catch-the-rest,
        // not a new predicate (the shared rule); `guard` is an early-return
        // conditional, counted like `if`.
        "switch_entry" => {
            let mut c = n.walk();
            !n.children(&mut c).any(|ch| ch.kind() == "default_keyword")
        }
        "if_statement"
        | "guard_statement"
        | "for_statement"
        | "while_statement"
        | "repeat_while_statement"
        | "catch_block" => true,
        "&&" | "||" => true,
        _ => false,
    },
    token_class: |n| match n.kind() {
        "simple_identifier" | "type_identifier" => Some("id"),
        "line_str_text" | "multi_line_str_text" => Some("str"),
        "integer_literal" | "hex_literal" | "oct_literal" | "bin_literal" | "real_literal" => {
            Some("num")
        }
        "comment" | "multiline_comment" => None,
        other => Some(other),
    },
};

type TypeIds = std::collections::BTreeMap<SmolStr, kndo_contract::evidence::DeclarationId>;

pub fn extract(
    path: &ProjectPath,
    source: &[u8],
    tree: &tree_sitter::Tree,
    out: &mut EvidenceSink,
) {
    let p = path.as_str();
    let file_name = p.rsplit('/').next().unwrap_or(p);

    // `Package.swift` IS the manifest — Swift source by format: it declares
    // nothing accusable, and its structure is read by `extract_manifest`. What
    // role it plays is the spec's `file_roles` to say, like every other
    // path convention this language keeps.
    let is_manifest = file_name == "Package.swift"
        || (file_name.starts_with("Package@swift-") && file_name.ends_with(".swift"));
    if is_manifest {
        return;
    }

    // The namespace IS the SwiftPM target: `internal` — the language's default
    // — reaches every file the module compiles and stops there, so one clause
    // per file is the whole of Swift's scope shape. The target is spelled by
    // the layout, never by the bytes, which is why `resolve` and this agree by
    // sharing one function.
    let target = crate::resolve::target_of(p);
    if let Some((name, _)) = target {
        out.namespace([SmolStr::new(name)]);
    }
    // A test target is its own module: what it declares belongs to the
    // package in test builds alone. The test-shaped NAME is not that — a
    // `LoadTests.swift` in a library target is compiled into it like any
    // other file, and says nothing here.
    let in_test_target = target.is_some_and(|(_, test)| test);
    if in_test_target {
        out.attachment(Attachment::TestOnly);
    }

    tk::mark_generated(source, GENERATED_NEEDLES, &["//", "/*", "*"], out);

    let root = tree.root_node();
    let mut cursor = root.walk();
    let children: Vec<Node<'_>> = root.named_children(&mut cursor).collect();
    // Two passes: types declare first, so a same-file `extension Foo` can
    // attach its members to Foo's id (a cross-file extension's members stay
    // ownerless — the method pool is name-global either way).
    let mut type_ids = TypeIds::new();
    let cx = FileCx { in_test_target };
    for item in &children {
        if matches!(item.kind(), "class_declaration" | "protocol_declaration")
            && !is_extension(*item, source)
        {
            top_level_item(*item, source, &cx, &mut type_ids, out);
        }
    }
    for item in children {
        if matches!(item.kind(), "class_declaration" | "protocol_declaration")
            && !is_extension(item, source)
        {
            continue;
        }
        top_level_item(item, source, &cx, &mut type_ids, out);
    }

    references_and_comments(root, source, out);
}

/// `` `default` `` and `default` are ONE identifier: Swift requires the
/// backticks only where the word would otherwise be a keyword, and permits
/// them anywhere. The quotes are spelling, never name, so they come off on
/// both sides — a declaration and the reference that reaches it.
fn bare(name: &str) -> &str {
    name.strip_prefix('`')
        .and_then(|n| n.strip_suffix('`'))
        .unwrap_or(name)
}

fn is_extension(item: Node<'_>, source: &[u8]) -> bool {
    item.kind() == "class_declaration"
        && item
            .child_by_field_name("declaration_kind")
            .is_some_and(|k| tk::text(k, source) == "extension")
}

/// Per-file facts every declaration handler needs.
#[derive(Clone, Copy)]
struct FileCx {
    /// Under `Tests/`: the toolchain's own runners (XCTest by `test*` name,
    /// swift-testing by `@Test`) dispatch on declarations no source line names.
    in_test_target: bool,
}

fn top_level_item(
    item: Node<'_>,
    source: &[u8],
    cx: &FileCx,
    type_ids: &mut TypeIds,
    out: &mut EvidenceSink,
) {
    match item.kind() {
        "import_declaration" => import(item, source, out),
        "class_declaration" => class_like(item, source, cx, type_ids, out),
        "protocol_declaration" => protocol(item, source, cx, type_ids, out),
        "function_declaration" => {
            function(item, source, None, false, None, cx, out);
        }
        "property_declaration" => property(item, source, None, None, out),
        "typealias_declaration" => {
            if let Some(n) = item.child_by_field_name("name") {
                out.declaration(
                    bare(tk::text(n, source)),
                    SymbolKind::Type,
                    tk::span(item),
                    reach_of(item, source),
                );
            }
        }
        _ => {}
    }
}

/// `import Foo` (or `@testable import Foo`): the module's whole top-level
/// surface lands in bare scope — no per-name binding syntax exists, so the
/// namespace shape is the truthful one (it keeps the target's surface alive
/// and marks this file an importer for region checks).
fn import(item: Node<'_>, source: &[u8], out: &mut EvidenceSink) {
    let mut c = item.walk();
    let Some(module) = item
        .named_children(&mut c)
        .find(|n| n.kind() == "identifier")
    else {
        return;
    };
    // `import Foo.Bar` — the module is the first segment.
    let name = tk::text(module, source);
    let module_name = name.split('.').next().unwrap_or(name);
    out.import(
        kndo_contract::evidence::ImportTarget::Package(SmolStr::new(module_name)),
        kndo_contract::evidence::ImportShape::Namespace {
            local: SmolStr::new(module_name),
        },
        tk::span(item),
        Confidence::Certain,
    );
}

/// class / struct / enum / actor / extension — one grammar node, told apart by
/// `declaration_kind`. An extension declares nothing; everything else is a
/// Type. Bodies dispatch members with the owner's bare name.
fn class_like(
    item: Node<'_>,
    source: &[u8],
    cx: &FileCx,
    type_ids: &mut TypeIds,
    out: &mut EvidenceSink,
) {
    let Some(kind_node) = item.child_by_field_name("declaration_kind") else {
        return;
    };
    let decl_kind = tk::text(kind_node, source);
    let Some(name_node) = item.child_by_field_name("name") else {
        return;
    };
    // An extension's name is a (possibly qualified) `user_type`; a declaration's
    // is a plain `type_identifier`.
    let name: SmolStr = if name_node.kind() == "user_type" {
        let mut c = name_node.walk();
        match name_node
            .named_children(&mut c)
            .filter(|n| n.kind() == "type_identifier")
            .last()
        {
            Some(last) => SmolStr::new(bare(tk::text(last, source))),
            None => return,
        }
    } else {
        SmolStr::new(bare(tk::text(name_node, source)))
    };

    let conforms = has_conformances(item);
    let owner_id = if decl_kind == "extension" {
        // A same-file extension attaches its members to the extended type.
        let existing = type_ids.get(&name).copied();
        // `extension Foo: Codable` is FOO's promise: retroactive conformance
        // is the idiom, and a rule asking whether `Foo` conforms must see it
        // wherever it was written.
        if let Some(owner) = existing {
            relations_of(item, source, owner, out);
        }
        existing
    } else {
        let id = out.declaration(
            name.clone(),
            SymbolKind::Type,
            tk::span(item),
            reach_of(item, source),
        );
        markers_of(item, source, id, out);
        relations_of(item, source, id, out);
        // `@main` — SwiftPM resolves the attributed type's `static main()` as
        // the executable entry; the type itself is the anchor we can name.
        if has_attribute(item, source, "main") {
            out.root(
                RootTarget::Declaration(id),
                RootKind::Production,
                Confidence::Certain,
            );
        }
        type_ids.insert(name.clone(), id);
        Some(id)
    };

    if let Some(body) =
        tk::child_of_kind(item, "class_body").or_else(|| tk::child_of_kind(item, "enum_class_body"))
    {
        let mut c = body.walk();
        let members: Vec<Node<'_>> = body.named_children(&mut c).collect();
        let owner = Owner {
            name: &name,
            id: owner_id,
            conforms,
            // `public extension Foo { func bar() }` makes `bar` public; the
            // engine caps the effective reach by Foo's own, so stating the
            // extension's modifier here is both simpler and correct.
            inherits: (decl_kind == "extension")
                .then(|| declared_reach(item, source))
                .flatten(),
        };
        for m in members {
            member(m, source, &owner, cx, type_ids, out);
        }
    }
}

fn protocol(
    item: Node<'_>,
    source: &[u8],
    cx: &FileCx,
    type_ids: &mut TypeIds,
    out: &mut EvidenceSink,
) {
    let Some(name_node) = item.child_by_field_name("name") else {
        return;
    };
    let name = SmolStr::new(bare(tk::text(name_node, source)));
    let owner_id = out.declaration(
        name.clone(),
        SymbolKind::Type,
        tk::span(item),
        reach_of(item, source),
    );
    markers_of(item, source, owner_id, out);
    relations_of(item, source, owner_id, out);
    type_ids.insert(name.clone(), owner_id);
    if let Some(body) = tk::child_of_kind(item, "protocol_body") {
        let mut c = body.walk();
        let members: Vec<Node<'_>> = body.named_children(&mut c).collect();
        let owner = Owner {
            name: &name,
            id: Some(owner_id),
            conforms: false,
            inherits: Some(Reach::Inherited),
        };
        for m in members {
            member(m, source, &owner, cx, type_ids, out);
        }
    }
}

/// The enclosing type as its members see it: the bare name, the id when it
/// was declared in THIS file (a cross-file extension's members stay
/// ownerless), and whether it declares conformances.
struct Owner<'a> {
    name: &'a str,
    id: Option<kndo_contract::evidence::DeclarationId>,
    conforms: bool,
    /// What a member with NO visibility modifier of its own reaches. A
    /// protocol REQUIREMENT is exactly as visible as its protocol — there is
    /// no narrower thing for it to be — and `Inherited` is that sentence; a
    /// `public extension` likewise hands its own modifier down. Everywhere
    /// else the member takes the language default, which is the module.
    inherits: Option<Reach>,
}

fn member(
    m: Node<'_>,
    source: &[u8],
    owner: &Owner<'_>,
    cx: &FileCx,
    type_ids: &mut TypeIds,
    out: &mut EvidenceSink,
) {
    match m.kind() {
        "function_declaration" | "protocol_function_declaration" => {
            let id = function(
                m,
                source,
                Some(owner.name),
                owner.conforms,
                owner.inherits.clone(),
                cx,
                out,
            );
            if let (Some(id), Some(owner)) = (id, owner.id) {
                out.member_of(id, owner);
            }
        }
        "property_declaration" => property(m, source, owner.id, owner.inherits.clone(), out),
        // A protocol's `var v: Int { get }` is its own node kind. Its name sits
        // under the same `pattern`, and it was never declared at all.
        "protocol_property_declaration" => {
            let Some(pattern) = tk::child_of_kind(m, "pattern") else {
                return;
            };
            let Some(ident) = tk::child_of_kind(pattern, "simple_identifier") else {
                return;
            };
            let id = out.declaration(
                bare(tk::text(ident, source)),
                SymbolKind::Variable,
                tk::span(m),
                Reach::Inherited,
            );
            markers_of(m, source, id, out);
            if let Some(owner) = owner.id {
                out.member_of(id, owner);
            }
        }
        "class_declaration" => class_like(m, source, cx, type_ids, out),
        "protocol_declaration" => protocol(m, source, cx, type_ids, out),
        "typealias_declaration" => {
            if let Some(n) = m.child_by_field_name("name") {
                let id = out.declaration(
                    bare(tk::text(n, source)),
                    SymbolKind::Type,
                    tk::span(m),
                    member_reach(m, source, owner.inherits.clone()),
                );
                if let Some(owner) = owner.id {
                    out.member_of(id, owner);
                }
            }
        }
        // init/deinit/enum_entry: never declared; their reference evidence
        // arrives through the file-wide walk.
        _ => {}
    }
}

fn function(
    item: Node<'_>,
    source: &[u8],
    owner: Option<&str>,
    owner_conforms: bool,
    inherits: Option<Reach>,
    cx: &FileCx,
    out: &mut EvidenceSink,
) -> Option<kndo_contract::evidence::DeclarationId> {
    let reach = member_reach(item, source, inherits);
    let fn_name = match item.child_by_field_name("name") {
        Some(n) => tk::text(n, source),
        // `static func == (l: S, r: S)` has no `name` field at all: the
        // operator is an anonymous token, and without this the declaration was
        // dropped whole. It is a name like any other — the call sites spell it
        // `a == b`, which the reference pass reports.
        None => operator_name(item, source)?,
    };
    let kind = if owner.is_some() {
        SymbolKind::Method
    } else {
        SymbolKind::Function
    };
    let scoped_or_wider = !matches!(reach, Reach::Owner | Reach::File);
    let id = out.declaration(bare(fn_name), kind, tk::span(item), reach);
    markers_of(item, source, id, out);

    // The toolchain's own test runners dispatch on declarations no source line
    // names: XCTest finds `test*` methods by name, swift-testing anything
    // carrying `@Test`. Both are toolchain-enforced in a Tests/ target —
    // Certain, the same tier as the layout root itself.
    if cx.in_test_target && (fn_name.starts_with("test") || has_attribute(item, source, "Test")) {
        out.root(
            RootTarget::Declaration(id),
            RootKind::Test,
            Confidence::Certain,
        );
    }

    // `override`: invoked through the superclass — the source never names the
    // call. Probable, the dispatch tier.
    if has_modifier(item, source, "override") {
        out.root(
            RootTarget::Declaration(id),
            RootKind::Production,
            Confidence::Probable,
        );
    }
    // A conforming type's non-private methods may witness protocol
    // requirements invoked entirely outside the repo (Codable synthesis,
    // delegate protocols) — requirements of external protocols are not
    // statically enumerable, so the keep is Possible: degrading toward
    // silence on exactly the fact we cannot enumerate.
    if owner_conforms && scoped_or_wider {
        out.root(
            RootTarget::Declaration(id),
            RootKind::Production,
            Confidence::Possible,
        );
    }

    if let Some(body) = item.child_by_field_name("body") {
        out.metrics(id, tk::function_metrics(item, &METRICS, source));
        let _ = body;
    }
    Some(id)
}

/// `let`/`var`, top-level or member: the bound names come from the `name`
/// field's pattern (possibly several in one declaration). Computed properties
/// are Variables too.
fn property(
    item: Node<'_>,
    source: &[u8],
    owner_id: Option<kndo_contract::evidence::DeclarationId>,
    inherits: Option<Reach>,
    out: &mut EvidenceSink,
) {
    let reach = member_reach(item, source, inherits);
    let is_let = {
        let mut found = false;
        tk::walk(item, &mut |n| {
            if n.kind() == "value_binding_pattern" {
                let mut c = n.walk();
                if n.children(&mut c).any(|ch| ch.kind() == "let") {
                    found = true;
                }
            }
        });
        found
    };
    let kind = if is_let {
        SymbolKind::Constant
    } else {
        SymbolKind::Variable
    };
    let mut c = item.walk();
    let names: Vec<Node<'_>> = item.children_by_field_name("name", &mut c).collect();
    for n in names {
        let ident = if n.kind() == "simple_identifier" {
            Some(n)
        } else {
            tk::child_of_kind(n, "simple_identifier")
        };
        if let Some(ident) = ident {
            let id = out.declaration(
                bare(tk::text(ident, source)),
                kind.clone(),
                tk::span(item),
                reach.clone(),
            );
            markers_of(item, source, id, out);
            if let Some(owner) = owner_id {
                out.member_of(id, owner);
            }
        }
    }
}

