    #[test]
    fn nil_coalescing_and_force_unwrap_are_not_branches() {
        let f = facts(
            "class C {\n\
             \x20   func m(n: Int?) -> Int {\n\
             \x20       let a = n ?? 0\n\
             \x20       return a + n!\n\
             \x20   }\n\
             }\n",
        );
        let fm = f.functions.iter().find(|f| f.symbol == "C.m").unwrap();
        assert_eq!(fm.cyclomatic, 1);
    }

    #[test]
    fn catch_block_counts_not_do_statement() {
        let f = facts(
            "class C {\n\
             \x20   func m() {\n\
             \x20       do { try risky() } catch { handle() }\n\
             \x20   }\n\
             \x20   func risky() throws {}\n\
             \x20   func handle() {}\n\
             }\n",
        );
        let fm = f.functions.iter().find(|f| f.symbol == "C.m").unwrap();
        assert_eq!(fm.cyclomatic, 2); // base 1 + one catch_block
    }
