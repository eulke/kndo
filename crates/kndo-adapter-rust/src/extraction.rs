/// Attributes seen since the last item — applied to the next non-attribute sibling.
#[derive(Default)]
struct PendingAttrs {
    test: bool,
    bench: bool,
    ffi_export: bool,
    cfg_test: bool,
    macro_use: bool,
    mod_path: Option<String>,
    derives: Vec<(SmolStr, Span)>,
    /// Start of the first attribute in this pending run — a test region's extent covers the
    /// attributes that gate it (`FileFacts::test_spans` records `#[cfg(test)]`'s own line).
    attr_start: Option<(u32, u32)>,
}

pub(crate) fn extract(_path: &str, content: &[u8]) -> FileFacts {
    let mut out = FileFacts::default();
    if GENERATED_MARKERS.detect_generated(content) {
        out.detected_origin = Some(kndo_core::vocab::FileOrigin::Generated);
    }

    let Some(tree) = crate::parsing::parse(content) else {
        out.diagnostics.push(Diagnostic {
            level: DiagnosticLevel::Warn,
            path: None,
            message: "failed to initialize the Rust parser".to_string(),
            span: None,
        });
        return out;
    };
    let root = tree.root_node();
    if root.has_error() {
        out.diagnostics.push(Diagnostic {
            level: DiagnosticLevel::Warn,
            path: None,
            message: "parse errors — extraction is partial for this file".to_string(),
            span: None,
        });
    }

    // `#![cfg(test)]` at the top gates the WHOLE file (a test-helper file compiled only
    // under test, without any `mod` wrapper): one region covering everything, and the walk
    // runs in cfg-test context so every declaration roots as test infrastructure — the same
    // treatment an inline `#[cfg(test)] mod` body gets.
    let mut whole_file_test = false;
    let mut cursor = root.walk();
    for child in root.children(&mut cursor) {
        if child.kind() == "inner_attribute_item" {
            let t = text(child, content);
            if t.starts_with("#![cfg") && t.contains("test") {
                whole_file_test = true;
            }
        }
    }
    drop(cursor);
    if whole_file_test {
        out.test_spans.push(span(root));
    }

    let local_qualifiers = collect_local_qualifiers(root, content);
    let inline_mod_names = collect_inline_mod_names(root, content);
    // Field facts pre-pass (RFC 0012 §3-bis): the single source for struct/union field
    // types — the contract's member_types AND the TypeEnv's `self.field` resolution.
    let field_facts = collect_field_facts(root, content);
    let field_types = field_type_map(&field_facts);
    out.member_types.extend(field_facts);
    walk_items(
        root,
        content,
        &Ctx {
            owner: None,
            in_cfg_test: whole_file_test,
            local_qualifiers: &local_qualifiers,
            inline_mod_names: &inline_mod_names,
            field_types: &field_types,
        },
        &mut out,
    );
    expand_pathed_mod_specifiers(&collect_pathed_mod_paths(root, content), &mut out);
    collect_suppressions(root, content, &mut out);
    out
}

/// `#[path = "…"]`-remapped `mod name;` declarations, name → every declared location — a
/// name maps to SEVERAL when cfg-alternated (`#[cfg(feature)] #[path = "enabled.rs"] mod
/// imp;` / `#[cfg(not(...))] #[path = "disabled.rs"] mod imp;`): under kndo's
/// whole-source view every alternate exists in some configuration, so all of them count.
fn collect_pathed_mod_paths(
    root: Node,
    src: &[u8],
) -> std::collections::HashMap<String, Vec<String>> {
    let mut out = std::collections::HashMap::new();
    walk_pathed_mods(root, src, &mut out);
    out
}

/// `collect_pathed_mod_paths`'s recursive walk: `#[path]` attributes are pending state
/// consumed by the next item, exactly like `walk_items`' attribute handling.
fn walk_pathed_mods(
    node: Node,
    src: &[u8],
    out: &mut std::collections::HashMap<String, Vec<String>>,
) {
    let mut pending_path: Option<String> = None;
    let mut cursor = node.walk();
    for child in node.children(&mut cursor) {
        match child.kind() {
            "attribute_item" => pending_path = path_attr_literal(child, src).or(pending_path),
            "line_comment" | "block_comment" => {}
            _ => {
                record_pathed_mod(child, src, pending_path.take(), out);
                walk_pathed_mods(child, src, out);
            }
        }
    }
}

/// One item in `collect_pathed_mod_paths`'s walk: a body-less `mod name;` preceded by a
/// `#[path]` attribute records its declared location (anything else consumes the pending
/// attribute silently — attributes bind to the next item only).
fn record_pathed_mod(
    item: Node,
    src: &[u8],
    pending_path: Option<String>,
    out: &mut std::collections::HashMap<String, Vec<String>>,
) {
    if item.kind() != "mod_item" || item.child_by_field_name("body").is_some() {
        return;
    }
    if let (Some(name), Some(p)) = (item.child_by_field_name("name"), pending_path) {
        out.entry(text(name, src).to_string()).or_default().push(p);
    }
}

/// The string literal of a `#[path = "…"]` attribute item, if that's what this is.
fn path_attr_literal(item: Node, src: &[u8]) -> Option<String> {
    let attr = item.named_child(0)?;
    if text(attr.child(0)?, src) != "path" {
        return None;
    }
    let value = attr.child_by_field_name("value")?;
    Some(text(value, src).trim_matches('"').to_string())
}

/// Post-walk rewrite: a specifier that is exactly `self::<mod>` where `<mod>` is a
/// `#[path]`-remapped file mod re-derives the child's location by convention and misses —
/// the mod declaration IS the location of record. Each such import expands to one
/// `file:`-anchored clone per declared alternate (ripgrep's `pub(crate) use self::imp::*`
/// over cfg-alternated `#[path]` mods — without this the glob resolved to nothing and the
/// alternates' whole surface read as dead).
fn expand_pathed_mod_specifiers(
    pathed: &std::collections::HashMap<String, Vec<String>>,
    out: &mut FileFacts,
) {
    if pathed.is_empty() {
        return;
    }
    let mut expanded = Vec::with_capacity(out.imports.len());
    for imp in std::mem::take(&mut out.imports) {
        match pathed_alternates(&imp.specifier, pathed) {
            Some(paths) => push_located_clones(imp, paths, &mut expanded),
            None => expanded.push(imp),
        }
    }
    out.imports = expanded;
}

/// One `file:`-anchored clone of the import per declared alternate location.
fn push_located_clones(imp: RawImport, paths: &[String], expanded: &mut Vec<RawImport>) {
    for p in paths {
        let mut clone = imp.clone();
        clone.specifier = SmolStr::new(format!("file:{p}"));
        expanded.push(clone);
    }
}

/// The declared locations a specifier of exactly `self::<pathed-mod>` expands to, if any.
fn pathed_alternates<'a>(
    specifier: &str,
    pathed: &'a std::collections::HashMap<String, Vec<String>>,
) -> Option<&'a Vec<String>> {
    specifier
        .strip_prefix("self::")
        .filter(|rest| !rest.contains("::"))
        .and_then(|name| pathed.get(name))
}

/// Names that qualify paths locally — `use` tails/aliases and `mod` names, anywhere in the
/// file. A bare body path rooted at one of these (`fs::read` after `use std::fs`) is already
/// covered by that import's alias; emitting a root import for it would fabricate a phantom
/// dependency.
fn collect_local_qualifiers(root: Node, src: &[u8]) -> std::collections::HashSet<String> {
    let mut out = std::collections::HashSet::new();
    fn walk(node: Node, src: &[u8], out: &mut std::collections::HashSet<String>) {
        match node.kind() {
            "mod_item" => {
                if let Some(name) = node.child_by_field_name("name") {
                    out.insert(text(name, src).to_string());
                }
            }
            "use_as_clause" => {
                if let Some(alias) = node.child_by_field_name("alias") {
                    out.insert(text(alias, src).to_string());
                }
            }
            // The bound tail of a full-path use OR of a scoped item inside a use list
            // (`use a::{doc::version}` binds `version`) — the latter shape fabricated
            // phantom `version::…` package references before (M6 FP hunt, ripgrep corpus).
            "scoped_identifier" | "identifier"
                if node
                    .parent()
                    .is_some_and(|p| matches!(p.kind(), "use_declaration" | "use_list")) =>
            {
                let t = text(node, src);
                out.insert(t.rsplit("::").next().unwrap_or(t).to_string());
            }
            "scoped_use_list" => {
                // `use a::{x, y};` — the simple list items are local names too.
                if let Some(list) = node.child_by_field_name("list") {
                    let mut c = list.walk();
                    for el in list.children(&mut c) {
                        if el.kind() == "identifier" {
                            out.insert(text(el, src).to_string());
                        }
                    }
                }
                if let Some(path) = node.child_by_field_name("path") {
                    let t = text(path, src);
                    out.insert(t.rsplit("::").next().unwrap_or(t).to_string());
                }
            }
            _ => {}
        }
        let mut cursor = node.walk();
        for child in node.children(&mut cursor) {
            walk(child, src, out);
        }
    }
    walk(root, src, &mut out);
    out
}

/// Names of *inline* `mod name { .. }` blocks in this file — as opposed to file-linking
/// `mod name;` — collected so `handle_use` can recognize a `use` path rooted at one: spec §2's
/// flatten model already merged that module's contents into this same file's declarations, so
/// the path names nothing outside it. Left unresolved, such a root looks exactly like an
/// unknown external crate to `resolve_bare` (no `name.rs`/`name/mod.rs` file exists to find),
/// fabricating an `undeclared`-dependency finding for what is really a same-file reference.
/// The name environment body-path emission resolves against — `locals` (use tails/aliases and
/// mod names: names that already have an import or declaration, so no root import should be
/// fabricated for them) and, separately, the file's *inline* `mod` names: extraction flattens
/// inline-mod bodies into the file (spec §2), so a qualified `convert::usize(..)` is really a
/// same-file bare reference — resolving it as a member/package path lost the binding and
/// false-positived the target as `unused` (M6 residuals, ripgrep corpus).
#[derive(Clone, Copy)]
struct PathEnv<'a> {
    locals: &'a std::collections::HashSet<String>,
    inline_mods: &'a std::collections::HashSet<String>,
    /// Receiver-type environment of the enclosing function ([`TypeEnv`]) — empty outside
    /// function bodies (const initializers, macro templates).
    types: &'a TypeEnv<'a>,
}

/// Local receiver types, from language FACTS visible in this file (RFC 0012 §3-bis): the
/// `impl` owner (`self`/`Self`), typed parameters (fn and closure), annotated `let`s, and
/// initializer shapes that name their type (`T { .. }` struct literals, `T::assoc(…)`
/// calls). A name bound to CONFLICTING types anywhere in the function is dropped outright —
/// ambiguity degrades to the duck-typed fallback, never to a guess. With a known receiver
/// type, `args.matcher()` emits qualifier `HiArgs` instead of the opaque `args`, and the
/// core resolves the member in the type's home file at Certain (the same qualified path
/// `HiArgs::matcher` would take). A wrong inference can only miss (→ duck fallback, today's
/// behavior) or hit a member the type genuinely declares — both degrade toward silence.
type FieldTypes = std::collections::HashMap<(String, String), String>;

struct TypeEnv<'a> {
    /// The enclosing `impl` block's self type — what `self.method()` and `Self::assoc()`
    /// resolve their qualifier to.
    owner: Option<String>,
    /// Simple identifier → base type name OR dotted pointer, conflict-free by construction.
    bindings: std::collections::HashMap<String, String>,
    /// The file's declared field/return types ((owner, member) → base type) — what lets
    /// `self.config` type as `Config` when the struct is declared in this same file.
    file_members: &'a FieldTypes,
}

impl TypeEnv<'_> {
    /// The environment for one function: owner + every conflict-free typed binding in it.
    fn for_function<'a>(
        item: Node,
        src: &[u8],
        owner: Option<&str>,
        file_members: &'a FieldTypes,
    ) -> TypeEnv<'a> {
        let mut bindings = std::collections::HashMap::new();
        let mut conflicted = std::collections::HashSet::new();
        let init = InitCtx {
            owner,
            file_members,
        };
        collect_typed_bindings(item, src, &init, &mut bindings, &mut conflicted);
        for name in &conflicted {
            bindings.remove(name);
        }
        resolve_self_bindings(&mut bindings, owner);
        TypeEnv {
            owner: owner.map(str::to_string),
            bindings,
            file_members,
        }
    }

    fn empty() -> &'static TypeEnv<'static> {
        static EMPTY_MAP: std::sync::OnceLock<FieldTypes> = std::sync::OnceLock::new();
        static EMPTY: std::sync::OnceLock<TypeEnv<'static>> = std::sync::OnceLock::new();
        EMPTY.get_or_init(|| TypeEnv {
            owner: None,
            bindings: std::collections::HashMap::new(),
            file_members: EMPTY_MAP.get_or_init(std::collections::HashMap::new),
        })
    }
}

/// What the binding collector can resolve initializers against: the impl owner and the
/// file's declared member types — both available before any [`TypeEnv`] exists.
#[derive(Clone, Copy)]
struct InitCtx<'a> {
    owner: Option<&'a str>,
    file_members: &'a FieldTypes,
}

/// `let x = Self::new()` / `x: Self` — the alias resolves through the impl owner; with no
/// owner in scope the binding says nothing.
fn resolve_self_bindings(
    bindings: &mut std::collections::HashMap<String, String>,
    owner: Option<&str>,
) {
    match owner {
        Some(owner_name) => {
            for ty in bindings.values_mut() {
                if ty == "Self" {
                    *ty = owner_name.to_string();
                }
            }
        }
        None => bindings.retain(|_, ty| ty != "Self"),
    }
}

/// One binding candidate into the [`TypeEnv`]: same name + same type is idempotent, same
/// name + different type poisons the name (shadowing across branches is not tracked — the
/// reliable answer for a name that isn't consistently one type is "unknown").
fn bind_type(
    name: &str,
    ty: String,
    bindings: &mut std::collections::HashMap<String, String>,
    conflicted: &mut std::collections::HashSet<String>,
) {
    match bindings.get(name) {
        Some(prior) if *prior != ty => {
            conflicted.insert(name.to_string());
        }
        Some(_) => {}
        None => {
            bindings.insert(name.to_string(), ty);
        }
    }
}

/// Every typed simple binding under `node`: fn/closure `parameter`s with a type, annotated
/// `let`s, and un-annotated `let`s whose initializer names its type. Nested functions are
/// not descended into — their bodies build their own environment.
fn collect_typed_bindings(
    node: Node,
    src: &[u8],
    init: &InitCtx<'_>,
    bindings: &mut std::collections::HashMap<String, String>,
    conflicted: &mut std::collections::HashSet<String>,
) {
    let mut cursor = node.walk();
    for child in node.children(&mut cursor) {
        match child.kind() {
            "function_item" if child.id() != node.id() => continue, // own env
            "parameter" | "let_declaration" => {
                record_typed_binding(child, src, init, bindings, conflicted);
                collect_typed_bindings(child, src, init, bindings, conflicted);
            }
            _ => collect_typed_bindings(child, src, init, bindings, conflicted),
        }
    }
}

/// A `parameter`/`let_declaration` with a simple identifier pattern: the annotated type
/// wins; an un-annotated `let` falls back to what its initializer names.
fn record_typed_binding(
    item: Node,
    src: &[u8],
    init: &InitCtx<'_>,
    bindings: &mut std::collections::HashMap<String, String>,
    conflicted: &mut std::collections::HashSet<String>,
) {
    let Some(name) = item
        .child_by_field_name("pattern")
        .and_then(|pattern| simple_pattern_name(pattern, src))
    else {
        return; // destructuring binds parts of a type, not the type
    };
    let ty = match item.child_by_field_name("type") {
        Some(ty) => base_type_name(ty, src),
        None => item
            .child_by_field_name("value")
            .and_then(|value| init_qualifier(value, init, src)),
    };
    if let Some(ty) = ty {
        bind_type(name, ty, bindings, conflicted);
    }
}

/// The bound identifier of a simple (possibly `mut`) pattern — destructuring yields none.
fn simple_pattern_name<'a>(pattern: Node, src: &'a [u8]) -> Option<&'a str> {
    let node = match pattern.kind() {
        "identifier" => pattern,
        "mut_pattern" => pattern.named_child(0)?,
        _ => return None,
    };
    (node.kind() == "identifier").then(|| text(node, src))
}

/// The base type a receiver of this declared type dispatches methods on: strips references
/// and the std pointer wrappers that auto-deref (`&`, `&mut`, `Box/Rc/Arc`), takes the
/// bound of `impl Trait`/`dyn Trait`, and the path's last segment. Shapes with no single
/// base (tuples, fn pointers, slices) yield nothing.
fn base_type_name(ty: Node, src: &[u8]) -> Option<String> {
    match ty.kind() {
        "generic_type" => generic_base_type(ty, src),
        "type_identifier" | "scoped_type_identifier" => {
            let t = text(ty, src);
            Some(t.rsplit("::").next().unwrap_or(t).to_string())
        }
        _ => unwrapped_type(ty).and_then(|inner| base_type_name(inner, src)),
    }
}

/// Transparent type wrappers around a dispatch base: references (`&T`, `&mut T`) and
/// `impl Trait` / `dyn Trait` (a single-trait bound IS the dispatch surface).
fn unwrapped_type(ty: Node) -> Option<Node> {
    match ty.kind() {
        "reference_type" => ty.child_by_field_name("type"),
        "abstract_type" | "dynamic_type" => ty.named_child(0),
        _ => None,
    }
}

/// A generic type's dispatch base: `Vec<T>` is `Vec`, but the auto-deref pointer wrappers
/// (`Box/Rc/Arc<T>`) dispatch methods on the pointee.
fn generic_base_type(ty: Node, src: &[u8]) -> Option<String> {
    let base = ty.child_by_field_name("type")?;
    let base_name = text(base, src);
    if matches!(base_name, "Box" | "Rc" | "Arc") {
        let args = ty.child_by_field_name("type_arguments")?;
        base_type_name(args.named_child(0)?, src)
    } else {
        Some(base_name.to_string())
    }
}

/// The QUALIFIER an initializer binds its name to: a plain type for `T { .. }` struct
/// literals, a dotted POINTER for calls (`T::assoc(…)` → `T.assoc`;
/// `self.config.build_many(…)` → `Config.build_many` through the file's member types),
/// `?`-marked when a try expression unwraps the value — `let chir =
/// self.config.build_many(x)?` binds `chir` to `Config.build_many?`, and the core takes
/// the return's payload parameter.
fn init_qualifier(value: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    match value.kind() {
        "struct_expression" => value
            .child_by_field_name("name")
            .and_then(|n| base_type_name(n, src)),
        "call_expression" => value
            .child_by_field_name("function")
            .and_then(|f| init_callee_pointer(f, init, src)),
        _ => init_wrapped_qualifier(value, init, src),
    }
}

/// Wrapper initializers: `expr?` appends the unwrap marker; `&expr` / `(expr)` pass
/// through.
fn init_wrapped_qualifier(value: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    let inner = value.named_child(0)?;
    match value.kind() {
        "try_expression" => init_qualifier(inner, init, src).map(|q| format!("{q}?")),
        "reference_expression" | "parenthesized_expression" => init_qualifier(inner, init, src),
        _ => None,
    }
}

/// A call initializer's pointer: `T::assoc`/`Self::assoc` scoped callees, or a member
/// callee whose base resolves through `self` and the file's declared field types
/// (`self.config.build_many` → `Config.build_many`).
fn init_callee_pointer(function: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    match function.kind() {
        "scoped_identifier" | "generic_function" => init_scoped_pointer(function, init, src),
        "field_expression" => init_field_pointer(function, init, src),
        _ => None,
    }
}

/// `T::assoc` / `Self::assoc` scoped callee → `"T.assoc"` (owner-resolved).
fn init_scoped_pointer(function: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    let root = scoped_call_type_root(function, src)?;
    let root = if root == "Self" {
        init.owner?.to_string()
    } else {
        root
    };
    let path = scoped_callee_text(function, src)?;
    let assoc = path.rsplit("::").next().unwrap_or(path);
    Some(format!("{root}.{assoc}"))
}

/// `self.field.method` member callee → `"FieldType.method"`.
fn init_field_pointer(function: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    let base = function.child_by_field_name("value")?;
    let field = function.child_by_field_name("field")?;
    let base_type = init_base_type(base, init, src)?;
    Some(format!("{base_type}.{}", text(field, src)))
}

/// The collector's mini receiver chain: `self` → the impl owner; `self.field` → the file's
/// declared field type. Two levels — enough for the idiomatic `self.field.method(…)` shape.
fn init_base_type(base: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    match base.kind() {
        "self" => init.owner.map(str::to_string),
        "field_expression" => init_field_base(base, init, src),
        _ => None,
    }
}

/// One `base.field` level of the collector's mini chain, through the file's field facts.
fn init_field_base(base: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    let inner = base.child_by_field_name("value")?;
    let field = base.child_by_field_name("field")?;
    let owner_type = init_base_type(inner, init, src)?;
    init.file_members
        .get(&(owner_type, text(field, src).to_string()))
        .cloned()
}

/// The textual path of a scoped callee (`T::assoc`, turbofish stripped via the inner
/// function of a `generic_function`).
fn scoped_callee_text<'a>(function: Node, src: &'a [u8]) -> Option<&'a str> {
    match function.kind() {
        "generic_function" => Some(text(function.child_by_field_name("function")?, src)),
        _ => Some(text(function, src)),
    }
}

/// The qualifier for a member access on `value` (RFC 0012 §3-bis), fact-first:
/// a one-hop dotted POINTER (`LowArgs.context_separator`, `Builder.new`) that the core
/// resolves through declared member-type facts, else the receiver's directly-pinned TYPE,
/// else nothing (the caller keeps the opaque receiver → duck fallback).
fn receiver_qualifier(value: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    receiver_pointer(value, types, src).or_else(|| receiver_type(value, types, src))
}

/// The one-hop pointer for a member/call receiver whose BASE is typed: `x.field` → `T.field`
/// (the field's declared type is the owner file's fact), `x.m(…)` → `T.m` and `T::assoc(…)`
/// → `T.assoc` (the return type is the fact). One hop only — a deeper chain's base falls
/// back to [`receiver_type`]'s convention flow.
fn receiver_pointer(value: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    match value.kind() {
        "field_expression" => member_pointer(value, types, src),
        "call_expression" => value
            .child_by_field_name("function")
            .and_then(|f| callee_pointer(f, types, src)),
        // `foo()?.method()` — the try operator unwraps: mark the hop so the core takes
        // the payload parameter instead of the wrapper.
        "try_expression" => value
            .named_child(0)
            .and_then(|inner| receiver_pointer(inner, types, src))
            .map(|p| format!("{p}?")),
        _ => None,
    }
}

/// The pointer for a call's callee: `x.m` (member call) or `T::assoc` (scoped call).
fn callee_pointer(function: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    match function.kind() {
        "field_expression" => member_pointer(function, types, src),
        "scoped_identifier" | "generic_function" => scoped_pointer(function, types, src),
        _ => None,
    }
}

/// `base.member` where `base`'s type is pinned → pointer `"Type.member"`. Pointer depth is
/// capped: a base already three hops deep stops extending (duck fallback instead) — chains
/// that long carry too little signal to be worth unbounded strings.
fn member_pointer(field_expr: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    let base = field_expr.child_by_field_name("value")?;
    let field = field_expr.child_by_field_name("field")?;
    let base_type = receiver_type(base, types, src)?;
    if base_type.matches('.').count() >= 3 {
        return None;
    }
    Some(format!("{base_type}.{}", text(field, src)))
}

/// A field access resolved through the file's own declared member types: base type pinned
/// (not a pointer — pointers can't key the local map), field looked up on it.
fn local_field_type(field_expr: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    let base = field_expr.child_by_field_name("value")?;
    let field = field_expr.child_by_field_name("field")?;
    let base_type = receiver_type(base, types, src)?;
    if base_type.contains('.') {
        return None;
    }
    types
        .file_members
        .get(&(base_type, text(field, src).to_string()))
        .cloned()
}

/// `T::assoc` / `Self::assoc` as a callee → pointer `"T.assoc"` (owner-resolved).
fn scoped_pointer(function: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    let root = scoped_call_type_root(function, src).and_then(|r| resolve_self_type(r, types))?;
    let path = match function.kind() {
        "generic_function" => text(function.child_by_field_name("function")?, src),
        _ => text(function, src),
    };
    let assoc = path.rsplit("::").next().unwrap_or(path);
    Some(format!("{root}.{assoc}"))
}

/// The receiver expression's type, when the file's facts pin one ([`TypeEnv`] doc):
/// a typed identifier, `self` (→ owner), or a call chain rooted at a type
/// (`SearchWorkerBuilder::new().opt(x).build()` — every link's receiver types as the root;
/// a link returning something else can only miss into the duck fallback or hit a member
/// the root genuinely declares, both silence-direction).
fn receiver_type(value: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    match value.kind() {
        "identifier" => types.bindings.get(text(value, src)).cloned(),
        "self" => types.owner.clone(),
        // `self.config` (and deeper) through the file's OWN declared field types — a local
        // fact; cross-file fields go through the pointer machinery instead.
        "field_expression" => local_field_type(value, types, src),
        _ => indirect_receiver_type(value, types, src),
    }
}

/// Call and wrapper receiver shapes, split from [`receiver_type`]'s direct lookups.
fn indirect_receiver_type(value: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    match value.kind() {
        "call_expression" => value
            .child_by_field_name("function")
            .and_then(|f| call_chain_type(f, types, src)),
        _ => unwrapped_receiver(value).and_then(|inner| receiver_type(inner, types, src)),
    }
}

/// Transparent expression wrappers around a receiver (`(&x)`, `&x`) — anything else ends
/// the walk.
fn unwrapped_receiver(value: Node) -> Option<Node> {
    matches!(
        value.kind(),
        "parenthesized_expression" | "reference_expression"
    )
    .then(|| value.named_child(0))
    .flatten()
}

/// A call's result type as a chain link: `T::assoc(…)` / `Self::assoc(…)` name the root
/// type; `x.method(…)` flows the receiver's own type through (hit-gated — see
/// [`receiver_type`]'s reliability note).
fn call_chain_type(function: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    match function.kind() {
        "scoped_identifier" | "generic_function" => {
            scoped_call_type_root(function, src).and_then(|root| resolve_self_type(root, types))
        }
        "field_expression" => function
            .child_by_field_name("value")
            .and_then(|v| receiver_type(v, types, src)),
        _ => None,
    }
}

/// `Self` resolves through the impl owner; any other root stands as-is.
fn resolve_self_type(root: String, types: &TypeEnv) -> Option<String> {
    if root != "Self" {
        return Some(root);
    }
    types.owner.clone()
}

/// The uppercase root type of a `T::assoc` / `T::assoc::<X>` callee path, if that is the
/// shape (`Self` resolves through the caller's owner before this is consulted).
fn scoped_call_type_root(function: Node, src: &[u8]) -> Option<String> {
    let path = match function.kind() {
        "scoped_identifier" => text(function, src),
        "generic_function" => text(function.child_by_field_name("function")?, src),
        _ => return None,
    };
    let root = path.split("::").next().unwrap_or("");
    root.chars()
        .next()
        .is_some_and(char::is_uppercase)
        .then(|| root.to_string())
}

fn collect_inline_mod_names(root: Node, src: &[u8]) -> std::collections::HashSet<String> {
    let mut out = std::collections::HashSet::new();
    fn walk(node: Node, src: &[u8], out: &mut std::collections::HashSet<String>) {
        if node.kind() == "mod_item" && node.child_by_field_name("body").is_some() {
            if let Some(name) = node.child_by_field_name("name") {
                out.insert(text(name, src).to_string());
            }
        }
        let mut cursor = node.walk();
        for child in node.children(&mut cursor) {
            walk(child, src, out);
        }
    }
    walk(root, src, &mut out);
    out
}

/// Item-walk context: the member owner, whether we're under a `#[cfg(test)]` module (its
/// declarations become test roots — inline test infrastructure, spec §1), and the file's
/// local qualifier names.
struct Ctx<'a> {
    owner: Option<&'a str>,
    in_cfg_test: bool,
    local_qualifiers: &'a std::collections::HashSet<String>,
    inline_mod_names: &'a std::collections::HashSet<String>,
    /// The file's declared field types (pre-pass) — [`TypeEnv`]s resolve `self.field`
    /// through these.
    field_types: &'a FieldTypes,
}

fn span(node: Node) -> Span {
    Span {
        start: (
            node.start_position().row as u32 + 1,
            node.start_position().column as u32 + 1,
        ),
        end: (
            node.end_position().row as u32 + 1,
            node.end_position().column as u32 + 1,
        ),
    }
}

fn text<'a>(node: Node, src: &'a [u8]) -> &'a str {
    std::str::from_utf8(&src[node.byte_range()]).unwrap_or("")
}

/// `(level, exported)` per the ladder [File "private", Package "pub(crate)", Public "pub"].
/// Rungs are relative to the FILE's module (inline mods are flattened, spec §2):
/// `pub(crate)`/`pub(in …)` map to the crate rung; `pub(self)` is private; `pub(super)`
/// reaches the file's parent module — the crate rung — unless the item sits inside an
/// inline mod, where `super` is a module within this same file and the item is file-scoped.
fn visibility(node: Node) -> (u8, bool) {
    let mut cursor = node.walk();
    let modifier = node
        .children(&mut cursor)
        .find(|child| child.kind() == "visibility_modifier");
    match modifier {
        Some(m) => visibility_of_modifier(m, node),
        None => (0, false),
    }
}

/// One `pub…` modifier mapped to the ladder: bare `pub` is the top rung; `pub(self)` is
/// private everywhere; `pub(super)` is private only when `super` stays inside the file.
fn visibility_of_modifier(modifier: Node, item: Node) -> (u8, bool) {
    if modifier.child_count() <= 1 {
        return (2, true); // bare `pub`
    }
    let mut cursor = modifier.walk();
    let level = modifier
        .children(&mut cursor)
        .find_map(|c| restriction_level(c, item))
        .unwrap_or(1); // pub(crate), pub(in …), top-level pub(super)
    (level, level > 0)
}

fn restriction_level(restriction: Node, item: Node) -> Option<u8> {
    match restriction.kind() {
        "self" => Some(0),
        "super" if inside_inline_mod(item) => Some(0),
        _ => None,
    }
}

/// Whether an item node sits inside an inline `mod … {}` body (any depth).
fn inside_inline_mod(node: Node) -> bool {
    let mut cur = node.parent();
    while let Some(n) = cur {
        if n.kind() == "mod_item" {
            return true;
        }
        cur = n.parent();
    }
    false
}

/// Item-list walker (source_file, inline-mod bodies — flattened, spec §2). Attributes are
/// pending state applied to the next item.
fn walk_items(list: Node, src: &[u8], ctx: &Ctx<'_>, out: &mut FileFacts) {
    let mut pending = PendingAttrs::default();
    let mut cursor = list.walk();
    for item in list.children(&mut cursor) {
        match item.kind() {
            "attribute_item" => collect_attr(item, src, &mut pending, out),
            "line_comment" | "block_comment" => {} // attributes survive doc comments
            _ => {
                let pending = std::mem::take(&mut pending);
                // Test-region extents (FileFacts::test_spans): a `#[cfg(test)]` item —
                // inline `mod tests {}` body included — or a `#[test]`/`#[bench]` fn is a
                // test region, attributes included. Outermost extent only: inside a
                // `#[cfg(test)]` module the enclosing region already covers every item.
                if !ctx.in_cfg_test && (pending.cfg_test || pending.test || pending.bench) {
                    let item_span = span(item);
                    out.test_spans.push(Span {
                        start: pending.attr_start.unwrap_or(item_span.start),
                        end: item_span.end,
                    });
                }
                handle_item(item, src, ctx, pending, out);
            }
        }
    }
}

fn collect_attr(item: Node, src: &[u8], pending: &mut PendingAttrs, out: &mut FileFacts) {
    pending.attr_start.get_or_insert(span(item).start);
    let Some(attr) = item.named_child(0) else {
        return;
    };
    let Some(name_node) = attr.child(0) else {
        return;
    };
    let name = text(name_node, src);
    match name {
        "test" => pending.test = true,
        "bench" => pending.bench = true,
        "macro_use" => pending.macro_use = true,
        // Runtime hooks: the language runtime consumes the item directly — no in-graph
        // reference will ever exist, same externally-invoked semantics as `#[no_mangle]`.
        "global_allocator" | "panic_handler" | "alloc_error_handler" => pending.ffi_export = true,
        "no_mangle" | "export_name" | "unsafe" => {
            // `#[unsafe(no_mangle)]` (Rust 2024) nests the real attribute in a token tree —
            // scan the attribute text for the export markers rather than modeling the nesting.
            let full = text(attr, src);
            if full.contains("no_mangle") || full.contains("export_name") {
                pending.ffi_export = true;
            } else if name == "test" {
                pending.test = true;
            }
        }
        "path" => {
            // #[path = "other/loc.rs"] — the string_literal's content child.
            if let Some(value) = attr.child_by_field_name("value") {
                let lit = text(value, src).trim_matches('"');
                pending.mod_path = Some(lit.to_string());
            }
        }
        "derive" => {
            if let Some(args) = attr.child_by_field_name("arguments") {
                let mut c = args.walk();
                for tok in args.children(&mut c) {
                    if tok.kind() == "identifier" {
                        pending
                            .derives
                            .push((SmolStr::new(text(tok, src)), span(tok)));
                    }
                }
                // Path-shaped derives (`serde::Serialize`) also need their crate's import.
                scan_attr_idents(args, src, out);
            }
        }
        "cfg" | "cfg_attr" => {
            // Both branches kept, always (spec §2) — but `#[cfg(test)]` marks the next item
            // (typically `mod tests`) as inline test infrastructure.
            if text(attr, src).contains("test") {
                pending.cfg_test = true;
            }
        }
        _ => {
            // Unknown attributes (`#[rkyv(with = SmolStrAsString)]`, `#[serde(…)]`) may name
            // real items in their arguments — scan for identifier tokens as TypeUse refs so
            // attr-only consumers stay alive (the M5 dogfood's SmolStrAsString case).
            scan_unknown_attr(attr, name, src, out);
        }
    }
}

/// Attribute names whose arguments are lint paths, doc text, or config keys — never item
/// paths (`#[allow(clippy::x)]` must not invent a `clippy` dependency).
const NON_ITEM_ATTRS: [&str; 8] = [
    "allow", "warn", "deny", "forbid", "expect", "doc", "cfg", "cfg_attr",
];

fn scan_unknown_attr(attr: Node, name: &str, src: &[u8], out: &mut FileFacts) {
    if NON_ITEM_ATTRS.contains(&name) {
        return;
    }
    if let Some(args) = attr.child_by_field_name("arguments") {
        scan_attr_idents(args, src, out);
    }
}

/// Attribute arguments are token soup, not structured paths — reconstruct `a::b::C`
/// sequences and treat them like body paths: rooted → synthetic import + binding; bare
/// multi-segment → the crate probe; lone uppercase identifiers → TypeUse references. This is
/// what keeps `#[rkyv(with = crate::rkyv_support::SmolStrAsString)]`'s target and
/// `#[derive(serde::Serialize)]`'s crate honestly used.
fn scan_attr_idents(node: Node, src: &[u8], out: &mut FileFacts) {
    // Linear token pass over this level: group ident (:: ident)* runs.
    let mut cursor = node.walk();
    let children: Vec<Node> = node.children(&mut cursor).collect();
    let mut i = 0;
    while i < children.len() {
        let tok = children[i];
        if matches!(tok.kind(), "identifier" | "crate" | "self" | "super") {
            let mut segments = vec![text(tok, src)];
            let mut j = i + 1;
            while j + 1 < children.len()
                && children[j].kind() == "::"
                && matches!(
                    children[j + 1].kind(),
                    "identifier" | "crate" | "self" | "super"
                )
            {
                segments.push(text(children[j + 1], src));
                j += 2;
            }
            emit_attr_path(&segments, span(tok), out);
            i = j;
        } else {
            scan_attr_idents(tok, src, out);
            i += 1;
        }
    }
}

fn emit_attr_path(segments: &[&str], at: Span, out: &mut FileFacts) {
    let [rest @ .., last] = segments else { return };
    if rest.is_empty() {
        if last.chars().next().is_some_and(char::is_uppercase) {
            out.references.push(RawReference {
                name: SmolStr::new(*last),
                scope_context: None,
                span: at,
                within: None,
                kind: RefKind::TypeUse,
            });
        }
        return;
    }
    let root = rest[0];
    let rooted = matches!(root, "crate" | "self" | "super");
    if rooted || !PRIMITIVES.contains(&root) {
        out.imports.push(RawImport {
            specifier: SmolStr::new(rest.join("::")),
            kind: if rooted {
                ImportKind::Relative
            } else {
                ImportKind::Package
            },
            span: at,
            side_effect_only: false,
            type_only: true,
            confidence: Confidence::Probable,
            bindings: vec![ImportBinding {
                local: SmolStr::new(*last),
                imported: Some(SmolStr::new(*last)),
            }],
            reexported: false,
            opaque_namespace_use: false,
            local_alias: None,
        });
        out.references.push(RawReference {
            name: SmolStr::new(*last),
            scope_context: None,
            span: at,
            within: None,
            kind: RefKind::TypeUse,
        });
    }
}

fn handle_item(item: Node, src: &[u8], ctx: &Ctx<'_>, pending: PendingAttrs, out: &mut FileFacts) {
    let owner = ctx.owner;
    let decls_before = out.declarations.len();
    // Derive attributes reference their derive macros regardless of what item follows.
    for (name, sp) in &pending.derives {
        out.references.push(RawReference {
            name: name.clone(),
            scope_context: None,
            span: *sp,
            within: None,
            kind: RefKind::TypeUse,
        });
    }

    match item.kind() {
        "function_item" => handle_function(item, src, ctx, owner, &pending, None, out),
        "struct_item" | "union_item" => {
            handle_type_decl(item, src, ctx, SymbolKind::Struct, out);
        }
        "enum_item" => handle_enum(item, src, ctx, out),
        "trait_item" => handle_trait(item, src, ctx, out),
        "impl_item" => handle_impl(item, src, ctx, out),
        "const_item" => handle_simple_decl(item, src, ctx, SymbolKind::Const, owner, &pending, out),
        "static_item" => {
            handle_simple_decl(item, src, ctx, SymbolKind::Static, owner, &pending, out)
        }
        "type_item" => handle_type_decl(item, src, ctx, SymbolKind::TypeAlias, out),
        "macro_definition" => {
            if let Some(name) = item.child_by_field_name("name") {
                let macro_name = text(name, src);
                push_declaration(
                    out,
                    macro_name,
                    SymbolKind::Macro,
                    item,
                    None,
                    None,
                    // macro_rules! has no pub; a #[macro_export] would make it public, but
                    // the common case is crate-visible — Package level, exported.
                    (1, true),
                );
                // The expansion templates reference real code (ripgrep's err_message! calls
                // `crate::messages::set_errored()` — M6 FP hunt): scan each rule's right-hand
                // token tree with the same reconstruction macro *invocations* get, attributed
                // within the macro so a dead macro keeps nothing alive.
                let mut mc = item.walk();
                for rule in item.children(&mut mc).filter(|n| n.kind() == "macro_rule") {
                    if let Some(body) = rule.child_by_field_name("right") {
                        scan_token_tree(
                            body,
                            src,
                            Some(macro_name),
                            PathEnv {
                                locals: ctx.local_qualifiers,
                                inline_mods: ctx.inline_mod_names,
                                types: TypeEnv::empty(),
                            },
                            out,
                        );
                    }
                }
            }
        }
        "mod_item" => handle_mod(item, src, ctx, &pending, out),
        "use_declaration" => handle_use(item, src, ctx, out),
        // A macro invoked as an item, not a statement (`wit_bindgen::generate!({ .. });`,
        // `export!(Guest);`) — the same construct `walk_body` already handles inside function
        // bodies via `handle_macro`, just at item position instead of expression position.
        // Without this arm the macro name and every identifier in its token tree (`Guest` in
        // `export!(Guest)`) were silently invisible: no reference to the macro's own crate, no
        // reference to whatever the macro's arguments name — real gaps a WASM-guest adapter
        // hit immediately (top-level `generate!`/`export!` is exactly how wit-bindgen is used).
        "macro_invocation" => {
            handle_macro(
                item,
                src,
                None,
                PathEnv {
                    locals: ctx.local_qualifiers,
                    inline_mods: ctx.inline_mod_names,
                    types: TypeEnv::empty(),
                },
                out,
            );
        }
        // The grammar always wraps a macro-call-as-item in `expression_statement` (there is
        // no bare item-position `macro_invocation` node in practice) — unwrap one level to
        // reach it. The `"macro_invocation"` arm above stays as a direct-node fallback.
        "expression_statement" => {
            if let Some(inner) = item.named_child(0) {
                if inner.kind() == "macro_invocation" {
                    handle_macro(
                        inner,
                        src,
                        None,
                        PathEnv {
                            locals: ctx.local_qualifiers,
                            inline_mods: ctx.inline_mod_names,
                            types: TypeEnv::empty(),
                        },
                        out,
                    );
                }
            }
        }
        // (declaration-count bookkeeping below skips imports — they add no declarations)
        "extern_crate_declaration" => {
            if let Some(name) = item.child_by_field_name("name") {
                out.imports.push(RawImport {
                    specifier: SmolStr::new(text(name, src)),
                    kind: ImportKind::Package,
                    span: span(item),
                    side_effect_only: true,
                    type_only: false,
                    confidence: Confidence::Certain,
                    bindings: Vec::new(),
                    reexported: false,
                    opaque_namespace_use: false,
                    local_alias: None,
                });
            }
        }
        _ => {}
    }

    // Inside a `#[cfg(test)]` module, every declaration is test infrastructure — a test
    // root, so reachability colors it (and everything only it reaches) test-side, and the
    // core's root-exemption keeps it out of `test-only`/`untested` findings (spec §1: the
    // inline analogue of Go's `_test.go` role).
    // No per-declaration Test rooting here: `test_spans` (recorded by `walk_items`) is the
    // single producer-side declaration of test regions, and assembly derives the in-source
    // Test roots for span-contained declarations (contracts §2) — one fact, one emitter.
    let _ = decls_before;
}

#[allow(clippy::too_many_arguments)]
fn push_declaration(
    out: &mut FileFacts,
    name: &str,
    kind: SymbolKind,
    item: Node,
    signature_span: Option<Span>,
    member_of: Option<&str>,
    (level, exported): (u8, bool),
) {
    out.declarations.push(kndo_core::adapter::Declaration {
        name: SmolStr::new(name),
        kind,
        span: span(item),
        exported,
        visibility: kndo_core::adapter::VisibilityLevel(level),
        member_of: member_of.map(SmolStr::new),
        implicitly_invoked: false,
        signature_span,
    });
}

fn handle_function(
    item: Node,
    src: &[u8],
    ctx: &Ctx<'_>,
    owner: Option<&str>,
    pending: &PendingAttrs,
    vis_override: Option<(u8, bool)>,
    out: &mut FileFacts,
) {
    let Some(name_node) = item.child_by_field_name("name") else {
        return;
    };
    let name = text(name_node, src);
    // Trait items carry no `pub` of their own — they inherit the trait's visibility (the
    // same Rust rule as enum variants), so `handle_trait` passes the override; every other
    // caller reads the item's own modifier.
    let vis = vis_override.unwrap_or_else(|| visibility(item));
    let body = item.child_by_field_name("body");
    // Signature = the item minus its body: what a caller sees (RFC 0012 §5).
    let signature_span = body.map(|b| Span {
        start: span(item).start,
        end: span(b).start,
    });
    let (kind, qualified) = match owner {
        Some(owner) => (SymbolKind::Method, format!("{owner}.{name}")),
        None => (SymbolKind::Function, name.to_string()),
    };
    push_declaration(out, name, kind, item, signature_span, owner, vis);

    // `#[test]`/`#[bench]` fns emit no root here: their extent is already a recorded test
    // region (`walk_items`), and assembly derives the Test root from span containment.
    // Top-level `fn main`: the bin entry point (same unconditional stance as Go's main/init —
    // Probable because only bin targets actually run it; a library's stray `main` over-lives,
    // the safe direction).
    if owner.is_none() && name == "main" {
        out.roots.push(RawRoot {
            kind: RootKind::Production,
            target: RawRootTarget::Declaration(SmolStr::new(&qualified)),
            confidence: Confidence::Probable,
        });
    }
    // FFI export: an attribute says so, or a `pub extern "C" fn` shape does (spec §2).
    let is_extern_fn = {
        let mut c = item.walk();
        let found = item
            .children(&mut c)
            .any(|n| n.kind() == "function_modifiers" && text(n, src).contains("extern"));
        found
    };
    if pending.ffi_export || (vis.1 && is_extern_fn) {
        out.roots.push(RawRoot {
            kind: RootKind::Production,
            target: RawRootTarget::Declaration(SmolStr::new(&qualified)),
            confidence: Confidence::Probable,
        });
    }

    // Signature types are used-when-the-fn-is-used: within = the fn (RFC 0012 §4).
    let mut c = item.walk();
    for child in item.children(&mut c) {
        if child.by_ref_is_body(body) {
            continue;
        }
        walk_type_refs(
            child,
            src,
            Some(&qualified),
            PathEnv {
                locals: ctx.local_qualifiers,
                inline_mods: ctx.inline_mod_names,
                types: TypeEnv::empty(),
            },
            out,
        );
    }
    if let Some(body) = body {
        // Receiver-type environment (RFC 0012 §3-bis): owner + typed bindings, so member
        // accesses on known receivers emit their TYPE as the qualifier.
        let types = TypeEnv::for_function(item, src, owner, ctx.field_types);
        walk_body(
            body,
            src,
            Some(&qualified),
            PathEnv {
                locals: ctx.local_qualifiers,
                inline_mods: ctx.inline_mod_names,
                types: &types,
            },
            out,
        );
        let shape = function_shape(body, &METRICS_SYNTAX, MIN_CLONE_TOKENS);
        out.functions.push(FunctionMetrics {
            symbol: SmolStr::new(&qualified),
            cyclomatic: shape.cyclomatic,
            loc: shape.loc,
            token_count: shape.token_count as u32,
            fingerprints: shape.fingerprints,
        });
    }
}

/// Tiny helper: is `self` the body node? (Option comparison without cloning nodes.)
trait IsBody {
    fn by_ref_is_body(&self, body: Option<Node>) -> bool;
}
impl IsBody for Node<'_> {
    fn by_ref_is_body(&self, body: Option<Node>) -> bool {
        body.is_some_and(|b| b.id() == self.id())
    }
}

fn handle_type_decl(item: Node, src: &[u8], ctx: &Ctx<'_>, kind: SymbolKind, out: &mut FileFacts) {
    let Some(name) = item.child_by_field_name("name") else {
        return;
    };
    let vis = visibility(item);
    push_declaration(out, text(name, src), kind, item, None, None, vis);
    // Field/alias types are load-bearing for the type: TypeUse refs, within = the type.
    let type_name = text(name, src).to_string();
    let mut c = item.walk();
    for child in item.children(&mut c) {
        walk_type_refs(
            child,
            src,
            Some(&type_name),
            PathEnv {
                locals: ctx.local_qualifiers,
                inline_mods: ctx.inline_mod_names,
                types: TypeEnv::empty(),
            },
            out,
        );
    }
}

/// Member-type facts from a struct/union body (RFC 0012 §3-bis): named fields keyed by
/// name, tuple fields by position (`"0"`, `"1"` — `x.0.method()` chains too). Only fields
/// whose annotation reduces to a base type contribute; the rest simply have no fact.
fn collect_field_member_types(
    item: Node,
    src: &[u8],
    owner: &str,
    sink: &mut Vec<kndo_core::adapter::RawMemberType>,
) {
    let Some(body) = item.child_by_field_name("body") else {
        return;
    };
    if body.kind() == "ordered_field_declaration_list" {
        collect_tuple_member_types(body, src, owner, sink);
        return;
    }
    let mut cursor = body.walk();
    for field in body.children(&mut cursor) {
        if field.kind() != "field_declaration" {
            continue;
        }
        if let (Some(n), Some(t)) = (
            field.child_by_field_name("name"),
            field.child_by_field_name("type"),
        ) {
            push_member_type(sink, owner, text(n, src), t, src);
        }
    }
}

/// Pre-pass over the whole file: every struct/union's field facts, collected BEFORE the
/// item walk so [`TypeEnv`]s can resolve `self.field` against them ([`FieldTypes`]).
fn collect_field_facts(root: Node, src: &[u8]) -> Vec<kndo_core::adapter::RawMemberType> {
    let mut sink = Vec::new();
    fn walk(node: Node, src: &[u8], sink: &mut Vec<kndo_core::adapter::RawMemberType>) {
        if matches!(node.kind(), "struct_item" | "union_item") {
            if let Some(name) = node.child_by_field_name("name") {
                collect_field_member_types(node, src, text(name, src), sink);
            }
        }
        let mut cursor = node.walk();
        for child in node.children(&mut cursor) {
            walk(child, src, sink);
        }
    }
    walk(root, src, &mut sink);
    sink
}

/// The [`TypeEnv`] lookup view of the field facts: (owner, member) → base type.
fn field_type_map(facts: &[kndo_core::adapter::RawMemberType]) -> FieldTypes {
    facts
        .iter()
        .map(|m| {
            (
                (m.owner.to_string(), m.member.to_string()),
                m.yields.to_string(),
            )
        })
        .collect()
}

/// Tuple-struct fields, keyed by position.
fn collect_tuple_member_types(
    list: Node,
    src: &[u8],
    owner: &str,
    sink: &mut Vec<kndo_core::adapter::RawMemberType>,
) {
    let mut cursor = list.walk();
    for (position, ty) in list
        .children(&mut cursor)
        .filter(|n| {
            n.is_named() && n.kind() != "visibility_modifier" && n.kind() != "attribute_item"
        })
        .enumerate()
    {
        push_member_type(sink, owner, &position.to_string(), ty, src);
    }
}

/// One member-type fact, when the annotation reduces to a base type. `Self` resolves to
/// the owner — the annotation was written inside the owner's own impl/body. The type
/// parameters (`Result<T, E>` → `[T, E]`) ride along for `?N`-marked pointer hops.
fn push_member_type(
    sink: &mut Vec<kndo_core::adapter::RawMemberType>,
    owner: &str,
    member: &str,
    ty: Node,
    src: &[u8],
) {
    let resolve_self = |name: String| {
        if name == "Self" {
            owner.to_string()
        } else {
            name
        }
    };
    if let Some(yields) = base_type_name(ty, src).map(resolve_self) {
        let yields_params = type_param_names(ty, src)
            .into_iter()
            .map(resolve_self)
            .map(SmolStr::new)
            .collect();
        sink.push(kndo_core::adapter::RawMemberType {
            owner: SmolStr::new(owner),
            member: SmolStr::new(member),
            yields: SmolStr::new(yields),
            yields_params,
        });
    }
}

/// The base names of a parameterized annotation's type arguments, in order —
/// `Result<ConfiguredHIR, Error>` → `["ConfiguredHIR", "Error"]`; an argument with no
/// single base (a lifetime, a fn type) contributes nothing at its position, so consumers
/// see only nameable parameters. References and the auto-deref wrappers are looked
/// through, matching [`base_type_name`]'s reduction.
fn type_param_names(ty: Node, src: &[u8]) -> Vec<String> {
    match ty.kind() {
        "reference_type" => ty
            .child_by_field_name("type")
            .map(|inner| type_param_names(inner, src))
            .unwrap_or_default(),
        "generic_type" => generic_param_names(ty, src),
        _ => Vec::new(),
    }
}

/// A generic annotation's argument bases, looking through the auto-deref wrappers.
fn generic_param_names(ty: Node, src: &[u8]) -> Vec<String> {
    let base = ty.child_by_field_name("type").map(|b| text(b, src));
    let Some(args) = ty.child_by_field_name("type_arguments") else {
        return Vec::new();
    };
    if matches!(base, Some("Box" | "Rc" | "Arc")) {
        return args
            .named_child(0)
            .map(|inner| type_param_names(inner, src))
            .unwrap_or_default();
    }
    let mut cursor = args.walk();
    args.children(&mut cursor)
        .filter(|n| n.is_named())
        .filter_map(|arg| base_type_name(arg, src))
        .collect()
}

/// A member-type fact for an impl item that carries a name field (fn return, const type).
fn push_owner_member_type(out: &mut FileFacts, owner: &str, item: Node, ty: Node, src: &[u8]) {
    if let Some(name) = item.child_by_field_name("name") {
        push_member_type(&mut out.member_types, owner, text(name, src), ty, src);
    }
}

fn handle_enum(item: Node, src: &[u8], ctx: &Ctx<'_>, out: &mut FileFacts) {
    let Some(name_node) = item.child_by_field_name("name") else {
        return;
    };
    let name = text(name_node, src);
    let vis = visibility(item);
    push_declaration(out, name, SymbolKind::Enum, item, None, None, vis);
    if let Some(body) = item.child_by_field_name("body") {
        let mut c = body.walk();
        for variant in body.children(&mut c) {
            if variant.kind() == "enum_variant" {
                if let Some(vname) = variant.child_by_field_name("name") {
                    push_declaration(
                        out,
                        text(vname, src),
                        SymbolKind::EnumMember,
                        variant,
                        None,
                        Some(name),
                        vis, // variants share the enum's visibility (Rust rule)
                    );
                }
                walk_type_refs(
                    variant,
                    src,
                    Some(name),
                    PathEnv {
                        locals: ctx.local_qualifiers,
                        inline_mods: ctx.inline_mod_names,
                        types: TypeEnv::empty(),
                    },
                    out,
                );
            }
        }
    }
}

fn handle_trait(item: Node, src: &[u8], ctx: &Ctx<'_>, out: &mut FileFacts) {
    let Some(name_node) = item.child_by_field_name("name") else {
        return;
    };
    let name = text(name_node, src);
    let vis = visibility(item);
    push_declaration(out, name, SymbolKind::Interface, item, None, None, vis);
    if let Some(body) = item.child_by_field_name("body") {
        let mut members = body.walk();
        let mut pending = PendingAttrs::default();
        for member in body.children(&mut members) {
            match member.kind() {
                "attribute_item" => collect_attr(member, src, &mut pending, out),
                "function_item" | "function_signature_item" => {
                    let p = std::mem::take(&mut pending);
                    handle_function(member, src, ctx, Some(name), &p, Some(vis), out);
                }
                "associated_type" | "const_item" => {
                    let _ = std::mem::take(&mut pending);
                    if let Some(mname) = member.child_by_field_name("name") {
                        push_declaration(
                            out,
                            text(mname, src),
                            if member.kind() == "const_item" {
                                SymbolKind::Const
                            } else {
                                SymbolKind::TypeAlias
                            },
                            member,
                            None,
                            Some(name),
                            vis,
                        );
                    }
                }
                _ => {}
            }
        }
    }
}

/// Stdlib traits whose methods the language machinery invokes **namelessly** — the curated
/// criterion is "the call site never writes the method's name": formatting hooks (`{}`,
/// `{:?}` and the numeric formats), destructors (scope end), comparison and arithmetic
/// operators, indexing/deref sugar, loop and await protocols, `str::parse`'s `from_str`,
/// error-chain reporting, and `Default`'s derive/`unwrap_or_default` machinery. Name-called
/// trait methods (`.clone()`, `.into()`, `.as_ref()`) are deliberately absent — the duck
/// fallback already reaches those from their call sites. Third-party traits (serde et al.)
/// stay unmodeled: a curated fact table beyond the stdlib is the recorded future source.
fn is_machinery_trait(name: &str) -> bool {
    matches!(
        name,
        // fmt hooks
        "Display" | "Debug" | "Octal" | "Binary" | "LowerHex" | "UpperHex" | "LowerExp"
            | "UpperExp" | "Pointer"
            // lifecycle
            | "Drop" | "Default"
            // comparison + hashing machinery
            | "PartialEq" | "Eq" | "PartialOrd" | "Ord" | "Hash"
            // operator overloads
            | "Add" | "Sub" | "Mul" | "Div" | "Rem" | "Neg" | "Not" | "BitAnd" | "BitOr"
            | "BitXor" | "Shl" | "Shr" | "AddAssign" | "SubAssign" | "MulAssign"
            | "DivAssign" | "RemAssign" | "BitAndAssign" | "BitOrAssign" | "BitXorAssign"
            | "ShlAssign" | "ShrAssign"
            // sugar + protocols
            | "Index" | "IndexMut" | "Deref" | "DerefMut" | "Iterator" | "IntoIterator"
            | "DoubleEndedIterator" | "ExactSizeIterator" | "Future" | "FromStr" | "Error"
    )
}

/// Flip [`kndo_core::adapter::Declaration::implicitly_invoked`] on the just-pushed member —
/// searched from the end, where `handle_function` left it.
fn mark_implicitly_invoked(out: &mut FileFacts, owner: &str, name: &str) {
    if let Some(decl) = out
        .declarations
        .iter_mut()
        .rev()
        .find(|d| d.name == name && d.member_of.as_deref() == Some(owner))
    {
        decl.implicitly_invoked = true;
    }
}

fn handle_impl(item: Node, src: &[u8], ctx: &Ctx<'_>, out: &mut FileFacts) {
    // The self type's bare name: `impl S`, `impl S<T>`, `impl a::S` all own members under `S`.
    let Some(type_node) = item.child_by_field_name("type") else {
        return;
    };
    let self_type = last_type_identifier(type_node, src);
    let Some(self_type) = self_type else { return };

    // `impl Trait for T` — the Implement reference that keeps dispatch-aware liveness honest
    // (RFC 0012 §3): using the trait keeps its implementations alive.
    if let Some(trait_node) = item.child_by_field_name("trait") {
        if let Some(trait_name) = last_type_identifier(trait_node, src) {
            out.references.push(RawReference {
                name: SmolStr::new(trait_name),
                scope_context: None,
                span: span(trait_node),
                within: Some(SmolStr::new(&self_type)),
                kind: RefKind::Implement,
            });
        }
    }

    let is_trait_impl = item.child_by_field_name("trait").is_some();
    // Machinery traits (RFC 0005 §1's machinery-dispatch rule): the call site never writes
    // the method's name — an operator, a `{}` hook, a scope end, a `for` loop — so members
    // of these impls are marked `implicitly_invoked` and inherit their owner's colors.
    let is_machinery = item
        .child_by_field_name("trait")
        .and_then(|t| last_type_identifier(t, src))
        .is_some_and(|t| is_machinery_trait(&t));
    if let Some(body) = item.child_by_field_name("body") {
        let mut members = body.walk();
        let mut pending = PendingAttrs::default();
        for member in body.children(&mut members) {
            match member.kind() {
                "attribute_item" => collect_attr(member, src, &mut pending, out),
                "function_item" => {
                    let p = std::mem::take(&mut pending);
                    handle_function(member, src, ctx, Some(&self_type), &p, None, out);
                    // Member-type fact (RFC 0012 §3-bis): what calling this method yields —
                    // its declared return, dispatch-reduced, `Self` resolved to the owner.
                    if let Some(ret) = member.child_by_field_name("return_type") {
                        push_owner_member_type(out, &self_type, member, ret, src);
                    }
                    // Trait-impl methods are called through the trait's dispatch (dyn, generic
                    // bounds, operator/format machinery — `Display::fmt` is never `x.fmt()` in
                    // source), so the name-based member fallback cannot see their call sites:
                    // root them at Probable (the RFC 0012 §3 dispatch rule, made concrete —
                    // over-liveness in the safe direction, spec §6).
                    if is_trait_impl {
                        if let Some(mname) = member.child_by_field_name("name") {
                            out.roots.push(RawRoot {
                                kind: RootKind::Production,
                                target: RawRootTarget::Declaration(SmolStr::new(format!(
                                    "{self_type}.{}",
                                    text(mname, src)
                                ))),
                                confidence: Confidence::Probable,
                            });
                            if is_machinery {
                                mark_implicitly_invoked(out, &self_type, text(mname, src));
                            }
                        }
                    }
                }
                "const_item" | "type_item" | "associated_type" => {
                    let _ = std::mem::take(&mut pending);
                    if member.kind() == "const_item" {
                        if let Some(ty) = member.child_by_field_name("type") {
                            push_owner_member_type(out, &self_type, member, ty, src);
                        }
                    }
                    if let Some(mname) = member.child_by_field_name("name") {
                        push_declaration(
                            out,
                            text(mname, src),
                            if member.kind() == "const_item" {
                                SymbolKind::Const
                            } else {
                                SymbolKind::TypeAlias
                            },
                            member,
                            None,
                            Some(&self_type),
                            visibility(member),
                        );
                        // Same dispatch rule as trait-impl methods: an associated
                        // type/const in `impl Trait for T` (`type Output = …` in an `Add`
                        // impl) is consumed through the trait's machinery, never by name.
                        if is_trait_impl {
                            out.roots.push(RawRoot {
                                kind: RootKind::Production,
                                target: RawRootTarget::Declaration(SmolStr::new(format!(
                                    "{self_type}.{}",
                                    text(mname, src)
                                ))),
                                confidence: Confidence::Probable,
                            });
                        }
                    }
                }
                _ => {}
            }
        }
    }
}

/// The rightmost `type_identifier` under a type node — `S`, `S<T>`, `a::b::S` all yield `S`.
fn last_type_identifier(node: Node, src: &[u8]) -> Option<String> {
    if node.kind() == "type_identifier" {
        return Some(text(node, src).to_string());
    }
    let mut found = None;
    let mut cursor = node.walk();
    for child in node.children(&mut cursor) {
        if let Some(name) = last_type_identifier(child, src) {
            found = Some(name);
        }
    }
    found
}

fn handle_simple_decl(
    item: Node,
    src: &[u8],
    ctx: &Ctx<'_>,
    kind: SymbolKind,
    owner: Option<&str>,
    pending: &PendingAttrs,
    out: &mut FileFacts,
) {
    let Some(name) = item.child_by_field_name("name") else {
        return;
    };
    let vis = visibility(item);
    push_declaration(out, text(name, src), kind, item, None, owner, vis);
    // Runtime-consumed item (`#[global_allocator]` — the runtime is the caller, same
    // reasoning as `#[no_mangle]` on a fn): a root, no in-graph reference will ever exist.
    if pending.ffi_export {
        out.roots.push(RawRoot {
            kind: RootKind::Production,
            target: RawRootTarget::Declaration(SmolStr::new(text(name, src))),
            confidence: Confidence::Probable,
        });
    }
    // Initializer expressions run at load: within = None (RFC 0012 §4's load-time rule).
    if let Some(value) = item.child_by_field_name("value") {
        walk_body(
            value,
            src,
            None,
            PathEnv {
                locals: ctx.local_qualifiers,
                inline_mods: ctx.inline_mod_names,
                types: TypeEnv::empty(),
            },
            out,
        );
    }
    if let Some(ty) = item.child_by_field_name("type") {
        walk_type_refs(
            ty,
            src,
            None,
            PathEnv {
                locals: ctx.local_qualifiers,
                inline_mods: ctx.inline_mod_names,
                types: TypeEnv::empty(),
            },
            out,
        );
    }
}

fn handle_mod(item: Node, src: &[u8], ctx: &Ctx<'_>, pending: &PendingAttrs, out: &mut FileFacts) {
    let Some(name) = item.child_by_field_name("name") else {
        return;
    };
    match item.child_by_field_name("body") {
        // Inline module: flatten (spec §2 — file ≈ module, stated once, leaned on everywhere).
        Some(body) => walk_items(
            body,
            src,
            &Ctx {
                owner: None,
                in_cfg_test: ctx.in_cfg_test || pending.cfg_test,
                local_qualifiers: ctx.local_qualifiers,
                inline_mod_names: ctx.inline_mod_names,
                field_types: ctx.field_types,
            },
            out,
        ),
        // `mod foo;` — THE file-linking import (spec §0). #[path] overrides the location.
        // `pub mod foo;` additionally re-exports the child's whole surface (reexported, no
        // bindings — the shape phase 2.7's library-surface fixpoint expands): a published
        // crate's API lives behind exactly these chains.
        None => {
            let specifier = match &pending.mod_path {
                Some(p) => format!("file:{p}"),
                None => format!("self::{}", text(name, src)),
            };
            let (_, is_pub) = visibility(item);
            out.imports.push(RawImport {
                specifier: SmolStr::new(specifier),
                kind: ImportKind::Relative,
                span: span(item),
                side_effect_only: true,
                type_only: false,
                confidence: Confidence::Certain,
                bindings: Vec::new(),
                reexported: is_pub,
                // The child module's items are addressable through `name::…` qualifiers.
                // `#[macro_use] mod x;` additionally globs the child's macro namespace into
                // crate scope — invocations anywhere reach its `macro_rules!` without an
                // import, which no binding can express (RFC 0005 §1's wildcard rule).
                opaque_namespace_use: pending.macro_use,
                local_alias: Some(SmolStr::new(text(name, src))),
            });
        }
    }
}

