    #[test]
    fn use_shapes_produce_the_contract_emissions() {
        let f = facts(
            "use crate::a::b::Thing;\n\
             use crate::a::{X, Y as Z};\n\
             use crate::deep::*;\n\
             use crate::x as alias;\n\
             pub use crate::a::Reexported;\n\
             use serde::Serialize;\n",
        );
        let single = f
            .imports
            .iter()
            .find(|i| i.specifier == "crate::a::b::Thing")
            .expect("full-path specifier, two-step tail is the resolver's job");
        assert_eq!(single.bindings[0].local.as_str(), "Thing");
        assert_eq!(single.kind, ImportKind::Relative);

        let grouped = f
            .imports
            .iter()
            .find(|i| i.specifier == "crate::a" && !i.bindings.is_empty())
            .unwrap();
        let locals: Vec<&str> = grouped.bindings.iter().map(|b| b.local.as_str()).collect();
        assert_eq!(locals, ["X", "Z"]);
        assert_eq!(grouped.bindings[1].imported.as_deref(), Some("Y"));

        let glob = f
            .imports
            .iter()
            .find(|i| i.specifier == "crate::deep")
            .unwrap();
        assert!(glob.opaque_namespace_use);

        let aliased = f
            .imports
            .iter()
            .find(|i| i.specifier == "crate::x")
            .unwrap();
        assert_eq!(aliased.local_alias.as_deref(), Some("alias"));

        let reexport = f
            .imports
            .iter()
            .find(|i| i.specifier == "crate::a::Reexported")
            .unwrap();
        assert!(reexport.reexported);

        let external = f
            .imports
            .iter()
            .find(|i| i.specifier == "serde::Serialize")
            .unwrap();
        assert_eq!(external.kind, ImportKind::Package);
    }

    #[test]
    fn test_attribute_records_a_region_and_ffi_roots_production() {
        let f = facts(
            "#[test]\nfn a_test() {}\n\
             #[no_mangle]\npub extern \"C\" fn ffi_entry() {}\n\
             fn plain() {}\n",
        );
        // `#[test]` emits no root of its own (assembly derives it from the region); the fn
        // and its attribute must lie inside a recorded test span.
        assert!(!f.roots.iter().any(|r| r.kind == RootKind::Test));
        let a_test = f.declarations.iter().find(|d| d.name == "a_test").unwrap();
        assert!(f
            .test_spans
            .iter()
            .any(|s| s.start.0 == 1 && s.start <= a_test.span.start && a_test.span.end <= s.end));
        // FFI exports still root as production directly — no region is involved.
        let ffi_root = f
            .roots
            .iter()
            .find(|r| r.kind == RootKind::Production)
            .expect("FFI export roots");
        assert!(matches!(&ffi_root.target, RawRootTarget::Declaration(n) if n == "ffi_entry"));
        assert_eq!(ffi_root.confidence, Confidence::Probable);
    }

