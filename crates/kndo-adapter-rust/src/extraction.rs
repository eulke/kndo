pub(crate) fn extract(path: &str, content: &[u8]) -> FileFacts {
    let unit = module_unit(path);
    let mut out = FileFacts {
        unit_parent: unit.as_deref().and_then(module_parent),
        unit,
        ..FileFacts::default()
    };
    if GENERATED_MARKERS.detect_generated(content) {
        out.detected_origin = Some(kndo_core::vocab::FileOrigin::Generated);
    }

    let Some(tree) = crate::parsing::parse(content) else {
        out.diagnostics.push(AdapterDiagnostic {
            level: DiagnosticLevel::Warn,
            message: "failed to initialize the Rust parser".to_string(),
            span: None,
        });
        return out;
    };
    let root = tree.root_node();
    if root.has_error() {
        out.diagnostics.push(AdapterDiagnostic {
            level: DiagnosticLevel::Warn,
            message: "parse errors — extraction is partial for this file".to_string(),
            span: None,
        });
    }

    // `#![cfg(test)]` at the top gates the WHOLE file (a test-helper file compiled only
    // under test, without any `mod` wrapper): one region covering everything, and the walk
    // runs in cfg-test context so every declaration roots as test infrastructure — the same
    // treatment an inline `#[cfg(test)] mod` body gets.
    let mut whole_file_test = false;
    let mut cursor = root.walk();
    for child in root.children(&mut cursor) {
        if child.kind() == "inner_attribute_item" {
            let t = text(child, content);
            if t.starts_with("#![cfg") && t.contains("test") {
                whole_file_test = true;
            }
        }
    }
    drop(cursor);
    if whole_file_test {
        out.test_spans.push(span(root));
    }

    let local_qualifiers = collect_local_qualifiers(root, content);
    let inline_mod_names = collect_inline_mod_names(root, content);
    let file_type_names = collect_file_type_names(root, content);
    let crate_probe = crate_probe_allowed(root);
    let use_bound = collect_use_bound_qualifiers(root, content);
    // Field facts pre-pass: the single source for struct/union field
    // types — the contract's member_types AND the TypeEnv's `self.field` resolution.
    let field_facts = collect_field_facts(root, content);
    let field_types = field_type_map(&field_facts);
    out.member_types.extend(field_facts);
    walk_items(
        root,
        content,
        &Ctx {
            owner: None,
            in_cfg_test: whole_file_test,
            local_qualifiers: &local_qualifiers,
            inline_mod_names: &inline_mod_names,
            field_types: &field_types,
            file_type_names: &file_type_names,
            crate_probe,
            use_bound: &use_bound,
        },
        &mut out,
    );
    // Every declaration on the `pub(super)` rung is visible in the PARENT module's subtree.
    // Setting it here rather than at each `push_declaration` is deliberate: the anchor is a
    // property of the rung, not of the call site, so one pass cannot drift from another.
    // Both Module rungs anchor here rather than at each `push_declaration`: the anchor is a
    // property of the RUNG, not of the call site, so one pass cannot drift from another.
    // `private` is the declaring module and its descendants (Rust's real rule); `pub(super)`
    // is the parent module's subtree.
    for decl in &mut out.declarations {
        decl.visible_in_unit = match decl.visibility.0 {
            VIS_PRIVATE => out.unit.clone(),
            VIS_SUPER => out.unit_parent.clone(),
            _ => None,
        };
    }
    expand_pathed_mod_specifiers(&collect_pathed_mod_paths(root, content), &mut out);
    kndo_adapter_toolkit::suppression::collect_suppressions(
        root,
        content,
        &["line_comment", "block_comment"],
        &mut out.suppressions,
    );
    out
}

/// `#[path = "…"]`-remapped `mod name;` declarations, name → every declared location — a
/// name maps to SEVERAL when cfg-alternated (`#[cfg(feature)] #[path = "enabled.rs"] mod
/// imp;` / `#[cfg(not(...))] #[path = "disabled.rs"] mod imp;`): under kndo's
/// whole-source view every alternate exists in some configuration, so all of them count.
fn collect_pathed_mod_paths(
    root: Node,
    src: &[u8],
) -> std::collections::HashMap<String, Vec<String>> {
    let mut out = std::collections::HashMap::new();
    walk_pathed_mods(root, src, &mut out);
    out
}

/// `collect_pathed_mod_paths`'s recursive walk: `#[path]` attributes are pending state
/// consumed by the next item, exactly like `walk_items`' attribute handling.
fn walk_pathed_mods(
    node: Node,
    src: &[u8],
    out: &mut std::collections::HashMap<String, Vec<String>>,
) {
    // A Vec, not a single slot: ONE `mod` declaration can carry several relocations, one per
    // configuration (`#[cfg_attr(from_git, path = "…")] #[cfg_attr(not(from_git), path = "…")]
    // mod internals;` — serde_derive_internals). Every alternate exists in some configuration,
    // which is the same reason the map's value is a Vec at all.
    let mut pending_paths: Vec<String> = Vec::new();
    let mut cursor = node.walk();
    for child in node.children(&mut cursor) {
        match child.kind() {
            "attribute_item" => pending_paths.extend(path_attr_literal(child, src)),
            "line_comment" | "block_comment" => {}
            _ => {
                record_pathed_mod(child, src, std::mem::take(&mut pending_paths), out);
                walk_pathed_mods(child, src, out);
            }
        }
    }
}

/// One item in `collect_pathed_mod_paths`'s walk: a body-less `mod name;` preceded by a
/// `#[path]` attribute records its declared location (anything else consumes the pending
/// attribute silently — attributes bind to the next item only).
fn record_pathed_mod(
    item: Node,
    src: &[u8],
    pending_paths: Vec<String>,
    out: &mut std::collections::HashMap<String, Vec<String>>,
) {
    if item.kind() != "mod_item" || item.child_by_field_name("body").is_some() {
        return;
    }
    if pending_paths.is_empty() {
        return;
    }
    if let Some(name) = item.child_by_field_name("name") {
        out.entry(text(name, src).to_string())
            .or_default()
            .extend(pending_paths);
    }
}

/// The string literal of a `#[path = "…"]` attribute item, if that's what this is —
/// `#[cfg_attr(cond, path = "…")]` included.
///
/// The conditional spelling is not exotic: serde_derive_internals declares its whole module
/// as `#[cfg_attr(serde_build_from_git, path = "…")] #[cfg_attr(not(serde_build_from_git),
/// path = "src/mod.rs")] mod internals;`. Reading only the bare form left the specifier at
/// `self::internals`, which resolves by convention to an `internals.rs` that does not exist,
/// so the module went dark and the `pub use internals::*;` next to it was accused of
/// importing an undeclared crate. `#[cfg]` alternates are all kept, by the same whole-source
/// policy the caller's doc states — the caller collects a `Vec` per name.
fn path_attr_literal(item: Node, src: &[u8]) -> Option<String> {
    let attr = item.named_child(0)?;
    match text(attr.child(0)?, src) {
        "path" => {
            let value = attr.child_by_field_name("value")?;
            Some(text(value, src).trim_matches('"').to_string())
        }
        // `cfg_attr(cond, path = "…")`: the real attribute is nested inside the arguments,
        // as one of possibly several — take the first `path`, the same "first wins" the bare
        // form gets from its caller's `.or(pending_path)`.
        "cfg_attr" => nested_path_attr_literal(attr.child_by_field_name("arguments")?, src),
        _ => None,
    }
}

/// The first `path = "…"` pair inside a `cfg_attr`'s argument token tree.
fn nested_path_attr_literal(args: Node, src: &[u8]) -> Option<String> {
    let mut cursor = args.walk();
    let children: Vec<Node> = args.children(&mut cursor).collect();
    for (i, child) in children.iter().enumerate() {
        if text(*child, src) == "path" && children.get(i + 1).map(|n| text(*n, src)) == Some("=") {
            let value = children.get(i + 2)?;
            return Some(text(*value, src).trim_matches('"').to_string());
        }
        if let Some(found) = nested_path_attr_literal(*child, src) {
            return Some(found);
        }
    }
    None
}

/// Post-walk rewrite: a specifier that is exactly `self::<mod>` where `<mod>` is a
/// `#[path]`-remapped file mod re-derives the child's location by convention and misses —
/// the mod declaration IS the location of record. Each such import expands to one
/// `file:`-anchored clone per declared alternate (a `pub(crate) use self::imp::*` over
/// cfg-alternated `#[path]` mods: without the expansion the glob resolves to nothing and
/// the alternates' whole surface reads as dead).
fn expand_pathed_mod_specifiers(
    pathed: &std::collections::HashMap<String, Vec<String>>,
    out: &mut FileFacts,
) {
    if pathed.is_empty() {
        return;
    }
    let mut expanded = Vec::with_capacity(out.imports.len());
    for imp in std::mem::take(&mut out.imports) {
        match pathed_alternates(&imp.specifier, pathed) {
            Some(paths) => push_located_clones(imp, paths, &mut expanded),
            None => expanded.push(imp),
        }
    }
    out.imports = expanded;
}

/// One `file:`-anchored clone of the import per declared alternate location.
fn push_located_clones(imp: RawImport, paths: &[String], expanded: &mut Vec<RawImport>) {
    for p in paths {
        let mut clone = imp.clone();
        clone.specifier = SmolStr::new(format!("file:{p}"));
        expanded.push(clone);
    }
}

/// The declared locations a specifier of exactly `self::<pathed-mod>` expands to, if any.
fn pathed_alternates<'a>(
    specifier: &str,
    pathed: &'a std::collections::HashMap<String, Vec<String>>,
) -> Option<&'a Vec<String>> {
    // `self::<mod>` is what `mod name;` itself emits. A BARE `<mod>` is the 2015-edition
    // spelling of the same thing (`pub use internals::*;` beside `mod internals;` in
    // serde_derive_internals): crate-relative, and a local module with that name shadows any
    // extern crate sharing it, so the local relocation is the only reading. Without this the
    // glob resolved to nothing, the module went dark, and `internals` was accused of being an
    // undeclared dependency.
    let name = specifier.strip_prefix("self::").unwrap_or(specifier);
    if name.contains("::") {
        return None;
    }
    pathed.get(name)
}

/// Names that qualify paths locally — `use` tails/aliases and `mod` names, anywhere in the
/// file. A bare body path rooted at one of these (`fs::read` after `use std::fs`) is already
/// covered by that import's alias; emitting a root import for it would fabricate a phantom
/// dependency.
fn collect_local_qualifiers(root: Node, src: &[u8]) -> std::collections::HashSet<String> {
    let mut out = std::collections::HashSet::new();
    fn walk(node: Node, src: &[u8], out: &mut std::collections::HashSet<String>) {
        match node.kind() {
            "mod_item" => {
                if let Some(name) = node.child_by_field_name("name") {
                    out.insert(text(name, src).to_string());
                }
            }
            "use_as_clause" => {
                if let Some(alias) = node.child_by_field_name("alias") {
                    out.insert(text(alias, src).to_string());
                }
            }
            // The bound tail of a full-path use OR of a scoped item inside a use list
            // (`use a::{doc::version}` binds `version`) — without registering the latter
            // shape, a later `version::…` path fabricates a phantom package reference.
            "scoped_identifier" | "identifier"
                if node
                    .parent()
                    .is_some_and(|p| matches!(p.kind(), "use_declaration" | "use_list")) =>
            {
                let t = text(node, src);
                out.insert(t.rsplit("::").next().unwrap_or(t).to_string());
            }
            "scoped_use_list" => {
                // `use a::{x, y};` — the simple list items are local names too.
                if let Some(list) = node.child_by_field_name("list") {
                    let mut c = list.walk();
                    for el in list.children(&mut c) {
                        if el.kind() == "identifier" {
                            out.insert(text(el, src).to_string());
                        }
                    }
                }
                if let Some(path) = node.child_by_field_name("path") {
                    let t = text(path, src);
                    out.insert(t.rsplit("::").next().unwrap_or(t).to_string());
                }
            }
            _ => {}
        }
        let mut cursor = node.walk();
        for child in node.children(&mut cursor) {
            walk(child, src, out);
        }
    }
    walk(root, src, &mut out);
    out
}

/// The name environment body-path emission resolves against — `locals` (use tails/aliases
/// and mod names: names that already have an import or declaration, so no root import should
/// be fabricated for them) and, separately, the file's *inline* `mod` names (as opposed to
/// file-linking `mod name;`): the flatten model merges an inline module's contents into this
/// same file's declarations, so a path rooted at one names nothing outside the file. A
/// qualified `convert::usize(..)` through an inline mod is really a same-file bare
/// reference — resolving it as a member/package path loses the binding and false-positives
/// the target as `unused`, and left unresolved such a root looks exactly like an unknown
/// external crate to `resolve_bare` (no `name.rs`/`name/mod.rs` file exists to find),
/// fabricating an `undeclared`-dependency finding for what is really a same-file reference.
#[derive(Clone, Copy)]
struct PathEnv<'a> {
    locals: &'a std::collections::HashSet<String>,
    inline_mods: &'a std::collections::HashSet<String>,
    /// Receiver-type environment of the enclosing function ([`TypeEnv`]) — empty outside
    /// function bodies (const initializers, macro templates).
    types: &'a TypeEnv<'a>,
    /// Type-like names DECLARED in this file (pre-pass). A path rooted at one of these is
    /// that type's associated item — a type in scope shadows an extern-prelude crate of the
    /// same name — so it is never evidence of a dependency. The case test alone cannot tell
    /// them apart: `r#type::r#struct` in serde's test suite reads as a lowercase root and
    /// was accused of being an undeclared crate.
    file_types: &'a std::collections::HashSet<String>,
    /// Whether a bare unknown root HERE is evidence of an external crate — see
    /// [`crate_probe_allowed`] for what turns it off, and `import_worthy` for what it gates.
    crate_probe: bool,
    /// Names this file's own imports bind — see [`collect_use_bound_qualifiers`].
    use_bound: &'a std::collections::HashSet<String>,
}

/// Local receiver types, from language FACTS visible in this file: the
/// `impl` owner (`self`/`Self`), typed parameters (fn and closure), annotated `let`s, and
/// initializer shapes that name their type (`T { .. }` struct literals, `T::assoc(…)`
/// calls). A name bound to CONFLICTING types anywhere in the function is dropped outright —
/// ambiguity degrades to the duck-typed fallback, never to a guess. With a known receiver
/// type, `args.matcher()` emits qualifier `HiArgs` instead of the opaque `args`, and the
/// core resolves the member in the type's home file at Certain (the same qualified path
/// `HiArgs::matcher` would take). A wrong inference can only miss (→ duck fallback, today's
/// behavior) or hit a member the type genuinely declares — both degrade toward silence.
type FieldTypes = std::collections::HashMap<(String, String), String>;

struct TypeEnv<'a> {
    /// The enclosing `impl` block's self type — what `self.method()` and `Self::assoc()`
    /// resolve their qualifier to.
    owner: Option<String>,
    /// Simple identifier → base type name OR dotted pointer, conflict-free by construction.
    bindings: std::collections::HashMap<String, String>,
    /// The file's declared field/return types ((owner, member) → base type) — what lets
    /// `self.config` type as `Config` when the struct is declared in this same file.
    file_members: &'a FieldTypes,
}

impl TypeEnv<'_> {
    /// The environment for one function: owner + every conflict-free typed binding in it.
    fn for_function<'a>(
        item: Node,
        src: &[u8],
        owner: Option<&str>,
        file_members: &'a FieldTypes,
    ) -> TypeEnv<'a> {
        let mut bindings = std::collections::HashMap::new();
        let mut conflicted = std::collections::HashSet::new();
        let init = InitCtx {
            owner,
            file_members,
        };
        collect_typed_bindings(item, src, &init, &mut bindings, &mut conflicted);
        for name in &conflicted {
            bindings.remove(name);
        }
        resolve_self_bindings(&mut bindings, owner);
        TypeEnv {
            owner: owner.map(str::to_string),
            bindings,
            file_members,
        }
    }

    fn empty() -> &'static TypeEnv<'static> {
        static EMPTY_MAP: std::sync::OnceLock<FieldTypes> = std::sync::OnceLock::new();
        static EMPTY: std::sync::OnceLock<TypeEnv<'static>> = std::sync::OnceLock::new();
        EMPTY.get_or_init(|| TypeEnv {
            owner: None,
            bindings: std::collections::HashMap::new(),
            file_members: EMPTY_MAP.get_or_init(std::collections::HashMap::new),
        })
    }
}

/// What the binding collector can resolve initializers against: the impl owner and the
/// file's declared member types — both available before any [`TypeEnv`] exists.
#[derive(Clone, Copy)]
struct InitCtx<'a> {
    owner: Option<&'a str>,
    file_members: &'a FieldTypes,
}

/// `let x = Self::new()` / `x: Self` — the alias resolves through the impl owner; with no
/// owner in scope the binding says nothing.
fn resolve_self_bindings(
    bindings: &mut std::collections::HashMap<String, String>,
    owner: Option<&str>,
) {
    match owner {
        Some(owner_name) => {
            for ty in bindings.values_mut() {
                if ty == "Self" {
                    *ty = owner_name.to_string();
                }
            }
        }
        None => bindings.retain(|_, ty| ty != "Self"),
    }
}

/// One binding candidate into the [`TypeEnv`]: same name + same type is idempotent, same
/// name + different type poisons the name (shadowing across branches is not tracked — the
/// reliable answer for a name that isn't consistently one type is "unknown").
fn bind_type(
    name: &str,
    ty: String,
    bindings: &mut std::collections::HashMap<String, String>,
    conflicted: &mut std::collections::HashSet<String>,
) {
    match bindings.get(name) {
        Some(prior) if *prior != ty => {
            conflicted.insert(name.to_string());
        }
        Some(_) => {}
        None => {
            bindings.insert(name.to_string(), ty);
        }
    }
}

/// Every typed simple binding under `node`: fn/closure `parameter`s with a type, annotated
/// `let`s, and un-annotated `let`s whose initializer names its type. Nested functions are
/// not descended into — their bodies build their own environment.
fn collect_typed_bindings(
    node: Node,
    src: &[u8],
    init: &InitCtx<'_>,
    bindings: &mut std::collections::HashMap<String, String>,
    conflicted: &mut std::collections::HashSet<String>,
) {
    let mut cursor = node.walk();
    for child in node.children(&mut cursor) {
        match child.kind() {
            "function_item" if child.id() != node.id() => continue, // own env
            "parameter" | "let_declaration" => {
                record_typed_binding(child, src, init, bindings, conflicted);
                collect_typed_bindings(child, src, init, bindings, conflicted);
            }
            "for_expression" => {
                record_loop_binding(child, src, init, bindings, conflicted);
                collect_typed_bindings(child, src, init, bindings, conflicted);
            }
            _ => collect_typed_bindings(child, src, init, bindings, conflicted),
        }
    }
}

/// `for x in <iterable>` — the loop variable is the iterable's ELEMENT, which the existing
/// projection marker already expresses: parameter 0 of the collection's declared type
/// (`Vec<ContributedRoot>` → `ContributedRoot`). Only iterables whose type is a declared FACT
/// contribute — a member access, chained as far as the pointer machinery reaches. A local
/// annotated `Vec<T>` does not, because a binding stores only its base name and the `T` is
/// already gone by then (`internal/detection-gaps.md` §3's residual).
fn record_loop_binding(
    item: Node,
    src: &[u8],
    init: &InitCtx<'_>,
    bindings: &mut std::collections::HashMap<String, String>,
    conflicted: &mut std::collections::HashSet<String>,
) {
    let Some(name) = item
        .child_by_field_name("pattern")
        .and_then(|pattern| simple_pattern_name(pattern, src))
    else {
        return; // destructuring binds parts of an element, not the element
    };
    let Some(value) = item.child_by_field_name("value") else {
        return;
    };
    // `@element` is a member hop like any other: the adapter's builtin table declares, per
    // container, which argument iterating it yields, so a container that declares none (a map,
    // whose element is a tuple) simply does not type its loop variable instead of typing it
    // wrong. The core never interprets the name — it appears on both sides, here and in the
    // table, and that is all it needs to be.
    if let Some(pointer) = iterable_pointer(value, init, bindings, src) {
        bind_type(name, format!("{pointer}.@element"), bindings, conflicted);
    }
}

/// The pointer naming an iterated expression's type: a member access chained through names
/// already bound in this environment (`root_sink.items` → `RootSink.default.items`), looking
/// through the borrow and parenthesis wrappers that mean nothing to a type.
fn iterable_pointer(
    value: Node,
    init: &InitCtx<'_>,
    bindings: &std::collections::HashMap<String, String>,
    src: &[u8],
) -> Option<String> {
    match value.kind() {
        "reference_expression" | "parenthesized_expression" => {
            iterable_pointer(value.named_child(0)?, init, bindings, src)
        }
        "identifier" => bindings.get(text(value, src)).cloned(),
        "self" => init.owner.map(str::to_string),
        "field_expression" => {
            let base = iterable_pointer(value.child_by_field_name("value")?, init, bindings, src)?;
            let field = value.child_by_field_name("field")?;
            Some(format!("{base}.{}", text(field, src)))
        }
        _ => None,
    }
}

/// A `parameter`/`let_declaration` with a simple identifier pattern: the annotated type
/// wins; an un-annotated `let` falls back to what its initializer names.
fn record_typed_binding(
    item: Node,
    src: &[u8],
    init: &InitCtx<'_>,
    bindings: &mut std::collections::HashMap<String, String>,
    conflicted: &mut std::collections::HashSet<String>,
) {
    let Some(name) = item
        .child_by_field_name("pattern")
        .and_then(|pattern| simple_pattern_name(pattern, src))
    else {
        return; // destructuring binds parts of a type, not the type
    };
    let ty = match item.child_by_field_name("type") {
        Some(ty) => base_type_name(ty, src),
        None => item
            .child_by_field_name("value")
            .and_then(|value| init_qualifier(value, init, src)),
    };
    if let Some(ty) = ty {
        bind_type(name, ty, bindings, conflicted);
    }
}

/// The bound identifier of a simple (possibly `mut`) pattern — destructuring yields none.
fn simple_pattern_name<'a>(pattern: Node, src: &'a [u8]) -> Option<&'a str> {
    let node = match pattern.kind() {
        "identifier" => pattern,
        "mut_pattern" => pattern.named_child(0)?,
        _ => return None,
    };
    (node.kind() == "identifier").then(|| text(node, src))
}

/// The base type a receiver of this declared type dispatches methods on: strips references
/// and the std pointer wrappers that auto-deref (`&`, `&mut`, `Box/Rc/Arc`), takes the
/// bound of `impl Trait`/`dyn Trait`, and the path's last segment. Shapes with no single
/// base (tuples, fn pointers, slices) yield nothing.
fn base_type_name(ty: Node, src: &[u8]) -> Option<String> {
    match ty.kind() {
        "generic_type" => generic_base_type(ty, src),
        "type_identifier" | "scoped_type_identifier" => {
            let t = text(ty, src);
            Some(t.rsplit("::").next().unwrap_or(t).to_string())
        }
        _ => unwrapped_type(ty).and_then(|inner| base_type_name(inner, src)),
    }
}

/// Transparent type wrappers around a dispatch base: references (`&T`, `&mut T`) and
/// `impl Trait` / `dyn Trait` (a single-trait bound IS the dispatch surface).
fn unwrapped_type(ty: Node) -> Option<Node> {
    match ty.kind() {
        "reference_type" => ty.child_by_field_name("type"),
        "abstract_type" | "dynamic_type" => ty.named_child(0),
        _ => None,
    }
}

/// A generic type's dispatch base: `Vec<T>` is `Vec`, but the auto-deref pointer wrappers
/// (`Box/Rc/Arc<T>`) dispatch methods on the pointee.
fn generic_base_type(ty: Node, src: &[u8]) -> Option<String> {
    let base = ty.child_by_field_name("type")?;
    let base_name = text(base, src);
    if matches!(base_name, "Box" | "Rc" | "Arc") {
        let args = ty.child_by_field_name("type_arguments")?;
        base_type_name(args.named_child(0)?, src)
    } else {
        Some(base_name.to_string())
    }
}

/// The QUALIFIER an initializer binds its name to: a plain type for `T { .. }` struct
/// literals, a dotted POINTER for calls (`T::assoc(…)` → `T.assoc`;
/// `self.config.build_many(…)` → `Config.build_many` through the file's member types),
/// `?`-marked when a try expression unwraps the value — `let chir =
/// self.config.build_many(x)?` binds `chir` to `Config.build_many?`, and the core takes
/// the return's payload parameter.
fn init_qualifier(value: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    match value.kind() {
        "struct_expression" => value
            .child_by_field_name("name")
            .and_then(|n| base_type_name(n, src)),
        "call_expression" => value
            .child_by_field_name("function")
            .and_then(|f| init_callee_pointer(f, init, src)),
        _ => init_wrapped_qualifier(value, init, src),
    }
}

/// Wrapper initializers: `expr?` appends the unwrap marker; `&expr` / `(expr)` pass
/// through.
fn init_wrapped_qualifier(value: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    let inner = value.named_child(0)?;
    match value.kind() {
        "try_expression" => init_qualifier(inner, init, src).map(|q| format!("{q}?")),
        "reference_expression" | "parenthesized_expression" => init_qualifier(inner, init, src),
        _ => None,
    }
}

/// A call initializer's pointer: `T::assoc`/`Self::assoc` scoped callees, or a member
/// callee whose base resolves through `self` and the file's declared field types
/// (`self.config.build_many` → `Config.build_many`).
fn init_callee_pointer(function: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    match function.kind() {
        "scoped_identifier" | "generic_function" => init_scoped_pointer(function, init, src),
        "field_expression" => init_field_pointer(function, init, src),
        // A bare callee (`let entry = parse_entry(..)`) binds the FUNCTION's name, not a
        // type: the adapter cannot know what it returns when the function lives in another
        // file, and should not guess when it lives in this one. The core reads the name as
        // a pointer base and hops through the callee's own member-type fact — one rule for
        // both, instead of a same-file special case that drifts from the cross-file one.
        "identifier" => Some(text(function, src).to_string()),
        _ => None,
    }
}

/// `T::assoc` / `Self::assoc` scoped callee → `"T.assoc"` (owner-resolved); a callee reached
/// through a MODULE instead of a type → the pointer that names the free function it is
/// ([`init_module_callee`]).
fn init_scoped_pointer(function: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    let path = scoped_callee_text(function, src)?;
    let Some(root) = scoped_call_type_root(function, src) else {
        return init_module_callee(path);
    };
    let root = if root == "Self" {
        init.owner?.to_string()
    } else {
        root
    };
    let assoc = path.rsplit("::").next().unwrap_or(path);
    Some(format!("{root}.{assoc}"))
}

/// A free function reached through its module (`rollup::directory_rollups(..)`,
/// `crate::analysis::rollup::directory_rollups(..)`): the pointer that lets the core find the
/// FUNCTION, so its declared return type can type the binding. Which pointer depends on what
/// the path's own reconstructed import binds — the two shapes `emit_path` produces:
///
///  * ROOTED at `crate`/`self`/`super`: the import binds the trailing name itself, so the
///    function is in scope and the pointer is just that name;
///  * bare-rooted: the import binds the module under the last module segment, so the pointer
///    is `module.function` and the core resolves the base as a qualifier.
///
/// Nothing here is a guess about what the function returns — only about how to name it. A
/// pointer that resolves to nothing costs a duck-fallback miss, which is where the binding
/// was anyway.
fn init_module_callee(path: &str) -> Option<String> {
    let segments: Vec<&str> = path.split("::").collect();
    let [rest @ .., last] = segments.as_slice() else {
        return None;
    };
    let module = rest.last()?;
    // The path may cross into TYPE space before its last segment
    // (`crate::plugin::RootSink::default`) — `emit_path` splits its synthetic import there
    // for the same reason, and the name that ends up in scope is the type, not the module.
    if let Some(ty) = rest
        .iter()
        .rev()
        .find(|seg| seg.chars().next().is_some_and(char::is_uppercase))
    {
        return Some(format!("{ty}.{last}"));
    }
    if matches!(rest[0], "crate" | "self" | "super") {
        return Some((*last).to_string());
    }
    Some(format!("{module}.{last}"))
}

/// `self.field.method` member callee → `"FieldType.method"`.
fn init_field_pointer(function: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    let base = function.child_by_field_name("value")?;
    let field = function.child_by_field_name("field")?;
    let base_type = init_base_type(base, init, src)?;
    Some(format!("{base_type}.{}", text(field, src)))
}

/// The collector's mini receiver chain: `self` → the impl owner; `self.field` → the file's
/// declared field type. Two levels — enough for the idiomatic `self.field.method(…)` shape.
fn init_base_type(base: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    match base.kind() {
        "self" => init.owner.map(str::to_string),
        "field_expression" => init_field_base(base, init, src),
        // A CALL as the base: `gitutil::ls_tree(..).map_err(..)`. The pointer it produces is
        // the receiver of the method that follows, and the core walks the two hops in one
        // chain. Without this the chain died at the first link and everything the final value
        // is read through looked file-local (`internal/detection-gaps.md` §3).
        "call_expression"
        | "try_expression"
        | "reference_expression"
        | "parenthesized_expression" => init_qualifier(base, init, src),
        _ => None,
    }
}

/// One `base.field` level of the collector's mini chain, through the file's field facts.
fn init_field_base(base: Node, init: &InitCtx<'_>, src: &[u8]) -> Option<String> {
    let inner = base.child_by_field_name("value")?;
    let field = base.child_by_field_name("field")?;
    let owner_type = init_base_type(inner, init, src)?;
    init.file_members
        .get(&(owner_type, text(field, src).to_string()))
        .cloned()
}

/// The textual path of a scoped callee (`T::assoc`, turbofish stripped via the inner
/// function of a `generic_function`).
fn scoped_callee_text<'a>(function: Node, src: &'a [u8]) -> Option<&'a str> {
    match function.kind() {
        "generic_function" => Some(text(function.child_by_field_name("function")?, src)),
        _ => Some(text(function, src)),
    }
}

/// The qualifier for a member access on `value`, fact-first:
/// a one-hop dotted POINTER (`LowArgs.context_separator`, `Builder.new`) that the core
/// resolves through declared member-type facts, else the receiver's directly-pinned TYPE,
/// else nothing (the caller keeps the opaque receiver → duck fallback).
fn receiver_qualifier(value: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    receiver_pointer(value, types, src).or_else(|| receiver_type(value, types, src))
}

/// The one-hop pointer for a member/call receiver whose BASE is typed: `x.field` → `T.field`
/// (the field's declared type is the owner file's fact), `x.m(…)` → `T.m` and `T::assoc(…)`
/// → `T.assoc` (the return type is the fact). One hop only — a deeper chain's base falls
/// back to [`receiver_type`]'s convention flow.
fn receiver_pointer(value: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    match value.kind() {
        "field_expression" => member_pointer(value, types, src),
        "call_expression" => value
            .child_by_field_name("function")
            .and_then(|f| callee_pointer(f, types, src)),
        // `foo()?.method()` — the try operator unwraps: mark the hop so the core takes
        // the payload parameter instead of the wrapper.
        "try_expression" => value
            .named_child(0)
            .and_then(|inner| receiver_pointer(inner, types, src))
            .map(|p| format!("{p}?")),
        _ => None,
    }
}

/// The pointer for a call's callee: `x.m` (member call) or `T::assoc` (scoped call).
fn callee_pointer(function: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    match function.kind() {
        "field_expression" => member_pointer(function, types, src),
        "scoped_identifier" | "generic_function" => scoped_pointer(function, types, src),
        _ => None,
    }
}

/// `base.member` where `base`'s type is pinned → pointer `"Type.member"`. Pointer depth is
/// capped: a base already three hops deep stops extending (duck fallback instead) — chains
/// that long carry too little signal to be worth unbounded strings.
fn member_pointer(field_expr: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    let base = field_expr.child_by_field_name("value")?;
    let field = field_expr.child_by_field_name("field")?;
    let base_type = receiver_type(base, types, src)?;
    if base_type.matches('.').count() >= 3 {
        return None;
    }
    Some(format!("{base_type}.{}", text(field, src)))
}

/// A field access resolved through the file's own declared member types: base type pinned
/// (not a pointer — pointers can't key the local map), field looked up on it.
fn local_field_type(field_expr: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    let base = field_expr.child_by_field_name("value")?;
    let field = field_expr.child_by_field_name("field")?;
    let base_type = receiver_type(base, types, src)?;
    if base_type.contains('.') {
        return None;
    }
    types
        .file_members
        .get(&(base_type, text(field, src).to_string()))
        .cloned()
}

/// `T::assoc` / `Self::assoc` as a callee → pointer `"T.assoc"` (owner-resolved).
fn scoped_pointer(function: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    let root = scoped_call_type_root(function, src).and_then(|r| resolve_self_type(r, types))?;
    let path = match function.kind() {
        "generic_function" => text(function.child_by_field_name("function")?, src),
        _ => text(function, src),
    };
    let assoc = path.rsplit("::").next().unwrap_or(path);
    Some(format!("{root}.{assoc}"))
}

/// The receiver expression's type, when the file's facts pin one ([`TypeEnv`] doc):
/// a typed identifier, `self` (→ owner), or a call chain rooted at a type
/// (`Builder::new().opt(x).build()` — every link's receiver types as the root;
/// a link returning something else can only miss into the duck fallback or hit a member
/// the root genuinely declares, both silence-direction).
fn receiver_type(value: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    match value.kind() {
        "identifier" => types.bindings.get(text(value, src)).cloned(),
        "self" => types.owner.clone(),
        // `self.config` (and deeper) through the file's OWN declared field types — a local
        // fact; cross-file fields go through the pointer machinery instead.
        "field_expression" => local_field_type(value, types, src),
        _ => indirect_receiver_type(value, types, src),
    }
}

/// Call and wrapper receiver shapes, split from [`receiver_type`]'s direct lookups.
fn indirect_receiver_type(value: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    match value.kind() {
        "call_expression" => value
            .child_by_field_name("function")
            .and_then(|f| call_chain_type(f, types, src)),
        _ => unwrapped_receiver(value).and_then(|inner| receiver_type(inner, types, src)),
    }
}

/// Transparent expression wrappers around a receiver (`(&x)`, `&x`) — anything else ends
/// the walk.
fn unwrapped_receiver(value: Node) -> Option<Node> {
    matches!(
        value.kind(),
        "parenthesized_expression" | "reference_expression"
    )
    .then(|| value.named_child(0))
    .flatten()
}

/// A call's result type as a chain link: `T::assoc(…)` / `Self::assoc(…)` name the root
/// type; `x.method(…)` flows the receiver's own type through (hit-gated — see
/// [`receiver_type`]'s reliability note).
fn call_chain_type(function: Node, types: &TypeEnv, src: &[u8]) -> Option<String> {
    match function.kind() {
        "scoped_identifier" | "generic_function" => {
            scoped_call_type_root(function, src).and_then(|root| resolve_self_type(root, types))
        }
        "field_expression" => function
            .child_by_field_name("value")
            .and_then(|v| receiver_type(v, types, src)),
        _ => None,
    }
}

/// `Self` resolves through the impl owner; any other root stands as-is.
fn resolve_self_type(root: String, types: &TypeEnv) -> Option<String> {
    if root != "Self" {
        return Some(root);
    }
    types.owner.clone()
}

/// The uppercase root type of a `T::assoc` / `T::assoc::<X>` callee path, if that is the
/// shape (`Self` resolves through the caller's owner before this is consulted).
fn scoped_call_type_root(function: Node, src: &[u8]) -> Option<String> {
    let path = match function.kind() {
        "scoped_identifier" => text(function, src),
        "generic_function" => text(function.child_by_field_name("function")?, src),
        _ => return None,
    };
    let root = path.split("::").next().unwrap_or("");
    root.chars()
        .next()
        .is_some_and(char::is_uppercase)
        .then(|| root.to_string())
}

/// Type-like names declared anywhere in this file. A path root naming one of them is that
/// type's associated item, never a crate: a type in scope shadows an extern-prelude crate of
/// the same name, and Rust's own raw identifiers (`enum r#type`) make the "lowercase root ⇒
/// crate-shaped" test unreliable on its own.
///
/// Deliberately type-like ONLY — functions, consts and statics are excluded. `foo::bar()`
/// beside a local `fn foo` really can mean the crate `foo` (a value and a crate live in
/// different namespaces and do not shadow each other for a path root), so suppressing the
/// probe there would hide genuine phantom dependencies.
/// Names this file's own `use` statements bind to something ELSE — the tail of a multi-segment
/// path, a brace member, an `as` alias, and the `self` member of a brace list.
///
/// A later `use <name>::…` rooted at one of them re-qualifies that binding, never an extern
/// crate: an import binding shadows a crate of the same name. alacritty writes
/// `use serde::de::{self, …};` at file level and `use de::Error;` inside a function forty
/// lines down, and `de` was accused of being an undeclared dependency of the whole package.
///
/// Deliberately NOT every name in [`collect_local_qualifiers`]: a bare `use serde;` binds
/// `serde` to the crate itself, so a sibling `use serde::Deserialize;` is a genuine crate
/// import and must keep its full strength.
fn collect_use_bound_qualifiers(root: Node, src: &[u8]) -> std::collections::HashSet<String> {
    let mut out = std::collections::HashSet::new();
    fn walk(node: Node, src: &[u8], out: &mut std::collections::HashSet<String>) {
        match node.kind() {
            "use_as_clause" => {
                if let Some(alias) = node.child_by_field_name("alias") {
                    out.insert(text(alias, src).to_string());
                }
            }
            "scoped_use_list" => {
                if let Some(path) = node.child_by_field_name("path") {
                    // `use a::b::{self, X}` binds `b`; the brace members bind their own names.
                    let t = text(path, src);
                    let tail = t.rsplit("::").next().unwrap_or(t);
                    if let Some(list) = node.child_by_field_name("list") {
                        let mut c = list.walk();
                        for el in list.children(&mut c) {
                            match el.kind() {
                                "self" => {
                                    out.insert(tail.to_string());
                                }
                                "identifier" => {
                                    out.insert(text(el, src).to_string());
                                }
                                _ => {}
                            }
                        }
                    }
                }
            }
            "scoped_identifier" if node.parent().is_some_and(|p| p.kind() == "use_declaration") => {
                let t = text(node, src);
                out.insert(t.rsplit("::").next().unwrap_or(t).to_string());
            }
            _ => {}
        }
        let mut cursor = node.walk();
        for child in node.children(&mut cursor) {
            walk(child, src, out);
        }
    }
    walk(root, src, &mut out);
    out
}

fn collect_file_type_names(root: Node, src: &[u8]) -> std::collections::HashSet<String> {
    let mut out = std::collections::HashSet::new();
    fn walk(node: Node, src: &[u8], out: &mut std::collections::HashSet<String>) {
        if matches!(
            node.kind(),
            "struct_item" | "enum_item" | "union_item" | "trait_item" | "type_item"
        ) {
            if let Some(name) = node.child_by_field_name("name") {
                out.insert(text(name, src).to_string());
            }
        }
        let mut cursor = node.walk();
        for child in node.children(&mut cursor) {
            walk(child, src, out);
        }
    }
    walk(root, src, &mut out);
    out
}

/// Whether a bare unknown path root in this file is EVIDENCE of an external crate.
///
/// A glob import (`use crate::lib::*;`, `use super::*;`) binds an open set of names this
/// adapter cannot enumerate without resolving the target — so after one, a root that matches
/// nothing local is not evidence of anything. serde re-exports `mem`, `cmp`, `fmt`, `iter`,
/// `net` and `slice` through exactly that shape and every one of them was accused of being a
/// phantom dependency of `serde_core`. Turning the probe off for the file costs the
/// `undeclared` analysis nothing it could have proven, and RFC 0012 §2 decides the direction
/// when the model cannot prove the accusation.
fn crate_probe_allowed(root: Node) -> bool {
    fn has_glob(node: Node) -> bool {
        if node.kind() == "use_wildcard" {
            return true;
        }
        let mut cursor = node.walk();
        let children: Vec<Node> = node.children(&mut cursor).collect();
        children.into_iter().any(has_glob)
    }
    !has_glob(root)
}

fn collect_inline_mod_names(root: Node, src: &[u8]) -> std::collections::HashSet<String> {
    let mut out = std::collections::HashSet::new();
    fn walk(node: Node, src: &[u8], out: &mut std::collections::HashSet<String>) {
        if node.kind() == "mod_item" && node.child_by_field_name("body").is_some() {
            if let Some(name) = node.child_by_field_name("name") {
                out.insert(text(name, src).to_string());
            }
        }
        let mut cursor = node.walk();
        for child in node.children(&mut cursor) {
            walk(child, src, out);
        }
    }
    walk(root, src, &mut out);
    out
}

/// Item-walk context: the member owner, whether we're under a `#[cfg(test)]` module (its
/// declarations become test roots — inline test infrastructure), and the file's
/// local qualifier names.
struct Ctx<'a> {
    owner: Option<&'a str>,
    in_cfg_test: bool,
    local_qualifiers: &'a std::collections::HashSet<String>,
    inline_mod_names: &'a std::collections::HashSet<String>,
    /// The file's declared field types (pre-pass) — [`TypeEnv`]s resolve `self.field`
    /// through these.
    field_types: &'a FieldTypes,
    /// The file's declared type-like names, and whether the undeclared-crate probe applies
    /// to this file at all — both [`PathEnv`] fields of the same name, hoisted to the file.
    file_type_names: &'a std::collections::HashSet<String>,
    crate_probe: bool,
    /// Names this file's own imports bind — see [`collect_use_bound_qualifiers`]. A `use`
    /// rooted at one of these is re-qualifying a binding, not importing a crate.
    use_bound: &'a std::collections::HashSet<String>,
}

impl<'a> Ctx<'a> {
    /// The context for walking a container's members, with the container's own
    /// `#[cfg(test)]` state folded in.
    fn for_members(&self, container_cfg_test: bool) -> Ctx<'a> {
        Ctx {
            owner: self.owner,
            in_cfg_test: self.in_cfg_test || container_cfg_test,
            local_qualifiers: self.local_qualifiers,
            inline_mod_names: self.inline_mod_names,
            field_types: self.field_types,
            file_type_names: self.file_type_names,
            crate_probe: self.crate_probe,
            use_bound: self.use_bound,
        }
    }
}

/// `(level, exported)` per the ladder [File "private", Package "pub(crate)", Public "pub"].
/// Rungs are relative to the FILE's module (inline mods are flattened):
/// `pub(crate)`/`pub(in …)` map to the crate rung; `pub(self)` is private; `pub(super)`
/// reaches the file's parent module — the crate rung — unless the item sits inside an
/// inline mod, where `super` is a module within this same file and the item is file-scoped.
fn visibility(node: Node) -> (u8, bool) {
    let mut cursor = node.walk();
    let modifier = node
        .children(&mut cursor)
        .find(|child| child.kind() == "visibility_modifier");
    match modifier {
        Some(m) => visibility_of_modifier(m, node),
        None => (0, false),
    }
}

/// One `pub…` modifier mapped to the ladder: bare `pub` is the top rung; `pub(self)` is
/// private everywhere; `pub(super)` is private only when `super` stays inside the file, and
/// otherwise names the PARENT MODULE's subtree — the rung this adapter's ladder gained so it
/// no longer has to widen a real region into `pub(crate)`.
fn visibility_of_modifier(modifier: Node, item: Node) -> (u8, bool) {
    if modifier.child_count() <= 1 {
        return (VIS_PUBLIC, true); // bare `pub`
    }
    let mut cursor = modifier.walk();
    let level = modifier
        .children(&mut cursor)
        .find_map(|c| restriction_level(c, item))
        .unwrap_or(VIS_CRATE); // pub(crate), pub(in …)
    (level, level > 0)
}

/// The ladder's rungs by name, so the numbering lives in one place and the descriptor and the
/// mapping cannot drift apart.
const VIS_PRIVATE: u8 = 0;
const VIS_SUPER: u8 = 1;
const VIS_CRATE: u8 = 2;
const VIS_PUBLIC: u8 = 3;

fn restriction_level(restriction: Node, item: Node) -> Option<u8> {
    match restriction.kind() {
        "self" => Some(VIS_PRIVATE),
        // `super` of an INLINE mod is a module within this same file, so under file ≈ module
        // the item never leaves the file.
        "super" if inside_inline_mod(item) => Some(VIS_PRIVATE),
        // A top-level `pub(super)` names the parent module's subtree — a real region, and the
        // one the four-bucket ladder had nowhere to put.
        "super" => Some(VIS_SUPER),
        // `pub(in path)` names an ancestor this adapter does not resolve to a unit key yet, so
        // it keeps the old conservative widening: `pub(crate)`. Widening only ever silences an
        // `internal-only`, never accuses (7 occurrences across tokio, for scale).
        _ => None,
    }
}

/// Whether an item node sits inside an inline `mod … {}` body (any depth).
fn inside_inline_mod(node: Node) -> bool {
    let mut cur = node.parent();
    while let Some(n) = cur {
        if n.kind() == "mod_item" {
            return true;
        }
        cur = n.parent();
    }
    false
}

/// This file's MODULE, as a unit key. Rust's resolution unit is the module and — under the
/// file ≈ module approximation this adapter is built on (§0) — a module is a file, so every
/// key names exactly one file. That degeneracy is the point twice over: it leaves every
/// unit-keyed table behaving exactly as it did when the key was absent (a file's own
/// declarations are already the tier consulted before its unit's), and it gives the module
/// TREE a name to hang on, which visibility needs and a per-file key alone cannot express.
///
/// The path IS the module path, so the key is the path with the conventional file names
/// folded into the directory they stand for: `src/graph/mod.rs` and `src/graph/assemble.rs`
/// are `…/src/graph` and `…/src/graph/assemble`, and `src/lib.rs` is `…/src` — the crate
/// root, which the next module up. Keys stay project-relative, so two crates with the same
/// internal layout do not collide (RFC 0012 §8's "unique only within a package" holds a
/// fortiori).
///
/// `#[path = "…"]` breaks the convention, and inline `mod x {}` flattens into its file — both
/// are the same standing approximation the rest of the adapter makes.
fn module_unit(path: &str) -> Option<SmolStr> {
    let stem = path.strip_suffix(".rs")?;
    let (dir, name) = match stem.rsplit_once('/') {
        Some((dir, name)) => (dir, name),
        None => ("", stem),
    };
    let key = if matches!(name, "mod" | "lib" | "main") {
        dir
    } else {
        stem
    };
    (!key.is_empty()).then(|| SmolStr::new(key))
}

/// The module CONTAINING a module key — the link that makes the keys a tree. It is the key's
/// containing directory, and `None` at a crate root, which under Cargo's layout is the `src`
/// directory itself: nothing above `src/lib.rs` is a module, and a top-level `pub(super)`
/// there would not compile anyway.
fn module_parent(unit: &str) -> Option<SmolStr> {
    if unit.rsplit('/').next() == Some("src") {
        return None;
    }
    let (parent, _) = unit.rsplit_once('/')?;
    (!parent.is_empty()).then(|| SmolStr::new(parent))
}

/// Item-list walker (source_file, inline-mod bodies — flattened). Attributes are
/// pending state applied to the next item.
fn walk_items(list: Node, src: &[u8], ctx: &Ctx<'_>, out: &mut FileFacts) {
    let mut pending = PendingAttrs::default();
    let mut cursor = list.walk();
    for item in list.children(&mut cursor) {
        match item.kind() {
            "attribute_item" => collect_attr(item, src, &mut pending, out),
            "line_comment" | "block_comment" => {} // attributes survive doc comments
            _ => {
                let pending = std::mem::take(&mut pending);
                record_test_region(&pending, item, ctx, out);
                handle_item(item, src, ctx, pending, out);
            }
        }
    }
}

/// Test-region extents (FileFacts::test_spans): a `#[cfg(test)]` item — inline
/// `mod tests {}` body included — or a `#[test]`/`#[bench]` fn is a test region, attributes
/// included. Applies wherever pending attributes gate an item as test code: top-level items,
/// inline-mod items, and `impl`/`trait` members alike. Outermost extent only: inside a
/// `#[cfg(test)]` container the enclosing region already covers every item.
fn record_test_region(pending: &PendingAttrs, item: Node, ctx: &Ctx<'_>, out: &mut FileFacts) {
    if !ctx.in_cfg_test && (pending.cfg_test || pending.test || pending.bench) {
        let item_span = span(item);
        out.test_spans.push(Span {
            start: pending.attr_start.unwrap_or(item_span.start),
            end: item_span.end,
        });
    }
}

fn collect_attr(item: Node, src: &[u8], pending: &mut PendingAttrs, out: &mut FileFacts) {
    pending.attr_start.get_or_insert(span(item).start);
    let Some(attr) = item.named_child(0) else {
        return;
    };
    let Some(name_node) = attr.child(0) else {
        return;
    };
    let name = text(name_node, src);
    match name {
        "test" => pending.test = true,
        "bench" => pending.bench = true,
        "macro_use" => pending.macro_use = true,
        // Runtime hooks: the language runtime consumes the item directly — no in-graph
        // reference will ever exist, same externally-invoked semantics as `#[no_mangle]`.
        "global_allocator" | "panic_handler" | "alloc_error_handler" => pending.ffi_export = true,
        "no_mangle" | "export_name" | "unsafe" => {
            // `#[unsafe(no_mangle)]` (Rust 2024) nests the real attribute in a token tree —
            // scan the attribute text for the export markers rather than modeling the nesting.
            let full = text(attr, src);
            if full.contains("no_mangle") || full.contains("export_name") {
                pending.ffi_export = true;
            } else if name == "test" {
                pending.test = true;
            }
        }
        "path" => {
            // #[path = "other/loc.rs"] — the string_literal's content child.
            if let Some(value) = attr.child_by_field_name("value") {
                let lit = text(value, src).trim_matches('"');
                pending.mod_path = Some(lit.to_string());
            }
        }
        "derive" => {
            if let Some(args) = attr.child_by_field_name("arguments") {
                let mut c = args.walk();
                for tok in args.children(&mut c) {
                    if tok.kind() == "identifier" {
                        pending
                            .derives
                            .push((SmolStr::new(text(tok, src)), span(tok)));
                    }
                }
                // Path-shaped derives (`serde::Serialize`) also need their crate's import.
                scan_attr_idents(args, src, out);
            }
        }
        "cfg" | "cfg_attr" => {
            // Both branches kept, always — but `#[cfg(test)]` marks the next item
            // (typically `mod tests`) as inline test infrastructure.
            if text(attr, src).contains("test") {
                pending.cfg_test = true;
            }
        }
        _ => {
            // Unknown attributes (`#[rkyv(with = SmolStrAsString)]`, `#[serde(…)]`) may name
            // real items in their arguments — scan for identifier tokens as TypeUse refs so
            // a consumer referenced only from an attribute stays alive.
            scan_unknown_attr(attr, name, src, out);
        }
    }
}

/// Attribute names whose arguments are lint paths, doc text, or config keys — never item
/// paths (`#[allow(clippy::x)]` must not invent a `clippy` dependency).
const NON_ITEM_ATTRS: [&str; 8] = [
    "allow", "warn", "deny", "forbid", "expect", "doc", "cfg", "cfg_attr",
];

fn scan_unknown_attr(attr: Node, name: &str, src: &[u8], out: &mut FileFacts) {
    if NON_ITEM_ATTRS.contains(&name) {
        return;
    }
    if let Some(args) = attr.child_by_field_name("arguments") {
        scan_attr_idents(args, src, out);
    }
}

/// Attribute arguments are token soup, not structured paths — reconstruct `a::b::C`
/// sequences and treat them like body paths: rooted → synthetic import + binding; bare
/// multi-segment → the crate probe; lone uppercase identifiers → TypeUse references. This is
/// what keeps `#[rkyv(with = crate::rkyv_support::SmolStrAsString)]`'s target and
/// `#[derive(serde::Serialize)]`'s crate honestly used.
fn scan_attr_idents(node: Node, src: &[u8], out: &mut FileFacts) {
    // Linear token pass over this level: group ident (:: ident)* runs.
    let mut cursor = node.walk();
    let children: Vec<Node> = node.children(&mut cursor).collect();
    let mut i = 0;
    while i < children.len() {
        let tok = children[i];
        if matches!(tok.kind(), "identifier" | "crate" | "self" | "super") {
            let mut segments = vec![text(tok, src)];
            let mut j = i + 1;
            while j + 1 < children.len()
                && children[j].kind() == "::"
                && matches!(
                    children[j + 1].kind(),
                    "identifier" | "crate" | "self" | "super"
                )
            {
                segments.push(text(children[j + 1], src));
                j += 2;
            }
            emit_attr_path(&segments, span(tok), out);
            i = j;
        } else {
            scan_attr_idents(tok, src, out);
            i += 1;
        }
    }
}

fn emit_attr_path(segments: &[&str], at: Span, out: &mut FileFacts) {
    let [rest @ .., last] = segments else { return };
    if rest.is_empty() {
        if last.chars().next().is_some_and(char::is_uppercase) {
            out.references.push(RawReference {
                name: SmolStr::new(*last),
                scope_context: None,
                span: at,
                within: None,
                kind: RefKind::TypeUse,
            });
        }
        return;
    }
    let root = rest[0];
    let rooted = matches!(root, "crate" | "self" | "super");
    if rooted || !PRIMITIVES.contains(&root) {
        out.imports.push(RawImport {
            specifier: SmolStr::new(rest.join("::")),
            kind: if rooted {
                ImportKind::Relative
            } else {
                ImportKind::Package
            },
            span: at,
            side_effect_only: false,
            type_only: true,
            confidence: Confidence::Probable,
            bindings: vec![ImportBinding {
                local: SmolStr::new(*last),
                imported: Some(SmolStr::new(*last)),
            }],
            reexported: false,
            opaque_namespace_use: false,
            module_names_visible: false,
            local_alias: None,
            // Synthesized from a use SITE: the file writes this path inline and no import
            // statement for it exists, so its binding must not outrank the file's own declarations.
            reconstructed: true,
        });
        out.references.push(RawReference {
            name: SmolStr::new(*last),
            scope_context: None,
            span: at,
            within: None,
            kind: RefKind::TypeUse,
        });
    }
}

fn handle_item(item: Node, src: &[u8], ctx: &Ctx<'_>, pending: PendingAttrs, out: &mut FileFacts) {
    let owner = ctx.owner;
    let decls_before = out.declarations.len();
    // Derive attributes reference their derive macros regardless of what item follows.
    for (name, sp) in &pending.derives {
        out.references.push(RawReference {
            name: name.clone(),
            scope_context: None,
            span: *sp,
            within: None,
            kind: RefKind::TypeUse,
        });
    }

    match item.kind() {
        "function_item" => handle_function(item, src, ctx, owner, &pending, None, out),
        "struct_item" | "union_item" => {
            handle_type_decl(item, src, ctx, SymbolKind::Struct, out);
            push_derived_default_type(item, src, &pending, out);
        }
        "enum_item" => {
            handle_enum(item, src, ctx, out);
            push_derived_default_type(item, src, &pending, out);
        }
        // The container's own #[cfg(test)] folds into the member-walk context so member-level
        // regions stay outermost-only (the container's region, recorded by the item walk,
        // already covers every member).
        "trait_item" => handle_trait(item, src, &ctx.for_members(pending.cfg_test), out),
        "impl_item" => handle_impl(item, src, &ctx.for_members(pending.cfg_test), out),
        "const_item" => handle_simple_decl(item, src, ctx, SymbolKind::Const, owner, &pending, out),
        "static_item" => {
            handle_simple_decl(item, src, ctx, SymbolKind::Static, owner, &pending, out)
        }
        "type_item" => handle_type_decl(item, src, ctx, SymbolKind::TypeAlias, out),
        "macro_definition" => {
            if let Some(name) = item.child_by_field_name("name") {
                let macro_name = text(name, src);
                push_declaration(
                    out,
                    macro_name,
                    SymbolKind::Macro,
                    item,
                    None,
                    None,
                    // macro_rules! has no pub; a #[macro_export] would make it public, but
                    // the common case is crate-visible — Package level, exported.
                    (1, true),
                );
                // The expansion templates reference real code (an `err_message!` whose body
                // calls `crate::messages::set_errored()`): scan each rule's right-hand
                // token tree with the same reconstruction macro *invocations* get, attributed
                // within the macro so a dead macro keeps nothing alive.
                let mut mc = item.walk();
                for rule in item.children(&mut mc).filter(|n| n.kind() == "macro_rule") {
                    if let Some(body) = rule.child_by_field_name("right") {
                        scan_token_tree(
                            body,
                            src,
                            Some(macro_name),
                            PathEnv {
                                locals: ctx.local_qualifiers,
                                inline_mods: ctx.inline_mod_names,
                                file_types: ctx.file_type_names,
                                crate_probe: ctx.crate_probe,
                                use_bound: ctx.use_bound,
                                types: TypeEnv::empty(),
                            },
                            out,
                        );
                    }
                }
            }
        }
        "mod_item" => handle_mod(item, src, ctx, &pending, out),
        "use_declaration" => handle_use(item, src, ctx, out),
        // A macro invoked as an item, not a statement (`wit_bindgen::generate!({ .. });`,
        // `export!(Guest);`) — the same construct `walk_body` already handles inside function
        // bodies via `handle_macro`, just at item position instead of expression position.
        // Without this arm the macro name and every identifier in its token tree (`Guest` in
        // `export!(Guest)`) are silently invisible: no reference to the macro's own crate, no
        // reference to whatever the macro's arguments name — real gaps for WASM-guest code
        // (top-level `generate!`/`export!` is exactly how wit-bindgen is used).
        "macro_invocation" => {
            handle_macro(
                item,
                src,
                None,
                PathEnv {
                    locals: ctx.local_qualifiers,
                    inline_mods: ctx.inline_mod_names,
                    file_types: ctx.file_type_names,
                    crate_probe: ctx.crate_probe,
                    use_bound: ctx.use_bound,
                    types: TypeEnv::empty(),
                },
                out,
            );
        }
        // The grammar always wraps a macro-call-as-item in `expression_statement` (there is
        // no bare item-position `macro_invocation` node in practice) — unwrap one level to
        // reach it. The `"macro_invocation"` arm above stays as a direct-node fallback.
        "expression_statement" => {
            if let Some(inner) = item.named_child(0) {
                if inner.kind() == "macro_invocation" {
                    handle_macro(
                        inner,
                        src,
                        None,
                        PathEnv {
                            locals: ctx.local_qualifiers,
                            inline_mods: ctx.inline_mod_names,
                            file_types: ctx.file_type_names,
                            crate_probe: ctx.crate_probe,
                            use_bound: ctx.use_bound,
                            types: TypeEnv::empty(),
                        },
                        out,
                    );
                }
            }
        }
        // (declaration-count bookkeeping below skips imports — they add no declarations)
        "extern_crate_declaration" => {
            if let Some(name) = item.child_by_field_name("name") {
                out.imports.push(RawImport {
                    specifier: SmolStr::new(text(name, src)),
                    kind: ImportKind::Package,
                    span: span(item),
                    side_effect_only: true,
                    type_only: false,
                    confidence: Confidence::Certain,
                    bindings: Vec::new(),
                    reexported: false,
                    opaque_namespace_use: false,
                    module_names_visible: false,
                    local_alias: None,
                    reconstructed: false,
                });
            }
        }
        _ => {}
    }

    // Inside a `#[cfg(test)]` module, every declaration is test infrastructure — a test
    // root, so reachability colors it (and everything only it reaches) test-side, and the
    // core's root-exemption keeps it out of `test-only`/`untested` findings (the inline
    // analogue of Go's `_test.go` role).
    // No per-declaration Test rooting here: `test_spans` (recorded by `walk_items`) is the
    // single producer-side declaration of test regions, and assembly derives the in-source
    // Test roots for span-contained declarations — one fact, one emitter.
    let _ = decls_before;
}

#[allow(clippy::too_many_arguments)]
fn push_declaration(
    out: &mut FileFacts,
    name: &str,
    kind: SymbolKind,
    item: Node,
    signature_span: Option<Span>,
    member_of: Option<&str>,
    (level, exported): (u8, bool),
) {
    out.declarations.push(kndo_core::adapter::Declaration {
        name: SmolStr::new(name),
        kind,
        span: span(item),
        exported,
        visibility: kndo_core::adapter::VisibilityLevel(level),
        member_of: member_of.map(SmolStr::new),
        implicitly_invoked: false,
        nested_scope: false,
        visibility_inherited: false,
        visible_in_unit: None,
        implements: None,
        markers: Vec::new(),
        signature_span,
    });
}

fn handle_function(
    item: Node,
    src: &[u8],
    ctx: &Ctx<'_>,
    owner: Option<&str>,
    pending: &PendingAttrs,
    vis_override: Option<(u8, bool)>,
    out: &mut FileFacts,
) {
    let Some(name_node) = item.child_by_field_name("name") else {
        return;
    };
    let name = text(name_node, src);
    // Trait items carry no `pub` of their own — they inherit the trait's visibility (the
    // same Rust rule as enum variants), so `handle_trait` passes the override; every other
    // caller reads the item's own modifier.
    let vis = vis_override.unwrap_or_else(|| visibility(item));
    let body = item.child_by_field_name("body");
    // Signature = the item minus its body: what a caller sees.
    let signature_span = body.map(|b| Span {
        start: span(item).start,
        end: span(b).start,
    });
    let (kind, qualified) = match owner {
        Some(owner) => (SymbolKind::Method, format!("{owner}.{name}")),
        None => (SymbolKind::Function, name.to_string()),
    };
    push_declaration(out, name, kind, item, signature_span, owner, vis);
    if vis_override.is_some() {
        // The override IS the inheritance: a trait item carries no `pub` of its own, so
        // no narrowing advice can name a keyword this declaration could take.
        if let Some(d) = out.declarations.last_mut() {
            d.visibility_inherited = true;
        }
    }

    // `#[test]`/`#[bench]` fns emit no root here: their extent is already a recorded test
    // region (`walk_items`), and assembly derives the Test root from span containment.
    // Top-level `fn main`: the bin entry point (same unconditional stance as Go's main/init —
    // Probable because only bin targets actually run it; a library's stray `main` over-lives,
    // the safe direction).
    // Member-type fact for a FREE function: what CALLING it yields. The mirror of the
    // impl-method fact `handle_impl` pushes, minus an owner — `let entry = parse_entry(..);
    // entry.path` has no receiver type to read off anything else, and without this the type
    // `parse_entry` returns looks used only where it is declared
    // (`internal/detection-gaps.md` §3). Only top-level functions: a nested `fn` is not
    // callable from where the binding lives.
    if owner.is_none() {
        if let Some(ret) = item.child_by_field_name("return_type") {
            push_member_type(&mut out.member_types, None, name, ret, src);
        }
    }
    if owner.is_none() && name == "main" {
        out.roots.push(RawRoot {
            kind: RootKind::Production,
            target: RawRootTarget::Declaration(SmolStr::new(&qualified)),
            confidence: Confidence::Probable,
        });
    }
    // FFI export: an attribute says so, or a `pub extern "C" fn` shape does.
    let is_extern_fn = {
        let mut c = item.walk();
        let found = item
            .children(&mut c)
            .any(|n| n.kind() == "function_modifiers" && text(n, src).contains("extern"));
        found
    };
    if pending.ffi_export || (vis.1 && is_extern_fn) {
        out.roots.push(RawRoot {
            kind: RootKind::Production,
            target: RawRootTarget::Declaration(SmolStr::new(&qualified)),
            confidence: Confidence::Probable,
        });
    }

    // Signature types are used-when-the-fn-is-used: within = the fn.
    let mut c = item.walk();
    for child in item.children(&mut c) {
        if child.by_ref_is_body(body) {
            continue;
        }
        walk_type_refs(
            child,
            src,
            Some(&qualified),
            PathEnv {
                locals: ctx.local_qualifiers,
                inline_mods: ctx.inline_mod_names,
                file_types: ctx.file_type_names,
                crate_probe: ctx.crate_probe,
                use_bound: ctx.use_bound,
                types: TypeEnv::empty(),
            },
            out,
        );
    }
    if let Some(body) = body {
        // Receiver-type environment: owner + typed bindings, so member
        // accesses on known receivers emit their TYPE as the qualifier.
        let types = TypeEnv::for_function(item, src, owner, ctx.field_types);
        walk_body(
            body,
            src,
            Some(&qualified),
            PathEnv {
                locals: ctx.local_qualifiers,
                inline_mods: ctx.inline_mod_names,
                file_types: ctx.file_type_names,
                crate_probe: ctx.crate_probe,
                use_bound: ctx.use_bound,
                types: &types,
            },
            out,
        );
        kndo_adapter_toolkit::metrics::push_function_metrics(
            out,
            &qualified,
            span(item),
            body,
            &METRICS_SYNTAX,
            MIN_CLONE_TOKENS,
        );
    }
}

/// Tiny helper: is `self` the body node? (Option comparison without cloning nodes.)
trait IsBody {
    fn by_ref_is_body(&self, body: Option<Node>) -> bool;
}
impl IsBody for Node<'_> {
    fn by_ref_is_body(&self, body: Option<Node>) -> bool {
        body.is_some_and(|b| b.id() == self.id())
    }
}

fn handle_type_decl(item: Node, src: &[u8], ctx: &Ctx<'_>, kind: SymbolKind, out: &mut FileFacts) {
    let Some(name) = item.child_by_field_name("name") else {
        return;
    };
    let vis = visibility(item);
    push_declaration(out, text(name, src), kind, item, None, None, vis);
    // Field/alias types are load-bearing for the type: TypeUse refs, within = the type.
    let type_name = text(name, src).to_string();
    let mut c = item.walk();
    for child in item.children(&mut c) {
        walk_type_refs(
            child,
            src,
            Some(&type_name),
            PathEnv {
                locals: ctx.local_qualifiers,
                inline_mods: ctx.inline_mod_names,
                file_types: ctx.file_type_names,
                crate_probe: ctx.crate_probe,
                use_bound: ctx.use_bound,
                types: TypeEnv::empty(),
            },
            out,
        );
    }
}

/// Member-type facts from a struct/union body: named fields keyed by
/// name, tuple fields by position (`"0"`, `"1"` — `x.0.method()` chains too). Only fields
/// whose annotation reduces to a base type contribute; the rest simply have no fact.
fn collect_field_member_types(
    item: Node,
    src: &[u8],
    owner: &str,
    sink: &mut Vec<kndo_core::adapter::RawMemberType>,
) {
    let Some(body) = item.child_by_field_name("body") else {
        return;
    };
    if body.kind() == "ordered_field_declaration_list" {
        collect_tuple_member_types(body, src, owner, sink);
        return;
    }
    let mut cursor = body.walk();
    for field in body.children(&mut cursor) {
        if field.kind() != "field_declaration" {
            continue;
        }
        if let (Some(n), Some(t)) = (
            field.child_by_field_name("name"),
            field.child_by_field_name("type"),
        ) {
            push_member_type(sink, Some(owner), text(n, src), t, src);
        }
    }
}

/// Pre-pass over the whole file: every struct/union's field facts, collected BEFORE the
/// item walk so [`TypeEnv`]s can resolve `self.field` against them ([`FieldTypes`]).
fn collect_field_facts(root: Node, src: &[u8]) -> Vec<kndo_core::adapter::RawMemberType> {
    let mut sink = Vec::new();
    fn walk(node: Node, src: &[u8], sink: &mut Vec<kndo_core::adapter::RawMemberType>) {
        if matches!(node.kind(), "struct_item" | "union_item") {
            if let Some(name) = node.child_by_field_name("name") {
                collect_field_member_types(node, src, text(name, src), sink);
            }
        }
        let mut cursor = node.walk();
        for child in node.children(&mut cursor) {
            walk(child, src, sink);
        }
    }
    walk(root, src, &mut sink);
    sink
}

/// The [`TypeEnv`] lookup view of the field facts: (owner, member) → base type. Free-function
/// facts (no owner) are not part of this view — a `self.field` chain never walks through one,
/// and the core resolves them at the pointer's base instead.
fn field_type_map(facts: &[kndo_core::adapter::RawMemberType]) -> FieldTypes {
    facts
        .iter()
        .filter_map(|m| {
            let owner = m.owner.as_ref()?;
            // The TypeEnv keys receivers by NAME — it emits a qualifier, not a type tree —
            // so this view keeps the head and drops the arguments. The arguments still live
            // in the fact itself, which is what the core's chain walks.
            Some((
                (owner.to_string(), m.member.to_string()),
                m.yields.name()?.to_string(),
            ))
        })
        .collect()
}

/// Tuple-struct fields, keyed by position.
fn collect_tuple_member_types(
    list: Node,
    src: &[u8],
    owner: &str,
    sink: &mut Vec<kndo_core::adapter::RawMemberType>,
) {
    let mut cursor = list.walk();
    for (position, ty) in list
        .children(&mut cursor)
        .filter(|n| {
            n.is_named() && n.kind() != "visibility_modifier" && n.kind() != "attribute_item"
        })
        .enumerate()
    {
        push_member_type(sink, Some(owner), &position.to_string(), ty, src);
    }
}

/// One member-type fact, when the annotation reduces to a base type. `Self` resolves to
/// the owner — the annotation was written inside the owner's own impl/body. The type
/// parameters (`Result<T, E>` → `[T, E]`) ride along for `?N`-marked pointer hops.
fn push_member_type(
    sink: &mut Vec<kndo_core::adapter::RawMemberType>,
    owner: Option<&str>,
    member: &str,
    ty: Node,
    src: &[u8],
) {
    // `Self` in a free function's signature is not a thing to resolve — there is no impl
    // around it — so with no owner the name stays as written and simply resolves to nothing.
    let resolve_self = |name: String| match (&name[..], owner) {
        ("Self", Some(owner)) => owner.to_string(),
        _ => name,
    };
    if let Some(yields) = type_expr(ty, src, &resolve_self) {
        sink.push(kndo_core::adapter::RawMemberType {
            owner: owner.map(SmolStr::new),
            member: SmolStr::new(member),
            yields,
        });
    }
}

/// An annotation as a TYPE EXPRESSION — the tree, not its base name. Applies the same
/// dispatch reduction [`base_type_name`] always did (references and `impl`/`dyn` looked
/// through, `Box`/`Rc`/`Arc` unwrapped to the pointee, `Self` resolved by the caller), and
/// then keeps going into the arguments instead of stopping at one level. `Result<Vec<T>, E>`
/// used to reduce to `Result` plus the names `["Vec", "E"]`, which lost the `T` for good.
///
/// A slice or array is anonymous in the grammar, so it is named `@slice` — a name only this
/// adapter uses, on both the fact side and the reference side, which lets it carry an
/// `@element` fact like any other container. The core never interprets either string.
fn type_expr(
    ty: Node,
    src: &[u8],
    resolve_self: &impl Fn(String) -> String,
) -> Option<kndo_core::adapter::TypeExpr> {
    use kndo_core::adapter::TypeExpr;
    match ty.kind() {
        "generic_type" => generic_type_expr(ty, src, resolve_self),
        "type_identifier" | "scoped_type_identifier" => {
            let t = text(ty, src);
            let base = t.rsplit("::").next().unwrap_or(t).to_string();
            Some(TypeExpr::named(resolve_self(base)))
        }
        "array_type" | "slice_type" => {
            let element = ty
                .child_by_field_name("element")
                .or_else(|| ty.named_child(0))
                .and_then(|e| type_expr(e, src, resolve_self))?;
            Some(TypeExpr::Named {
                name: SmolStr::new("@slice"),
                args: vec![element],
            })
        }
        _ => unwrapped_type(ty).and_then(|inner| type_expr(inner, src, resolve_self)),
    }
}

/// A generic annotation as a tree: the base plus every argument, recursively. The auto-deref
/// pointer wrappers dispatch on the pointee, so they vanish into it — the same reduction
/// [`generic_base_type`] makes, carried through to the arguments.
fn generic_type_expr(
    ty: Node,
    src: &[u8],
    resolve_self: &impl Fn(String) -> String,
) -> Option<kndo_core::adapter::TypeExpr> {
    use kndo_core::adapter::TypeExpr;
    let base = ty.child_by_field_name("type")?;
    let base_name = text(base, src);
    let base_name = base_name.rsplit("::").next().unwrap_or(base_name);
    let args = ty.child_by_field_name("type_arguments");
    if matches!(base_name, "Box" | "Rc" | "Arc") {
        return args
            .and_then(|a| a.named_child(0))
            .and_then(|inner| type_expr(inner, src, resolve_self));
    }
    let mut collected = Vec::new();
    if let Some(args) = args {
        let mut cursor = args.walk();
        for arg in args.children(&mut cursor).filter(|n| n.is_named()) {
            // A lifetime or a fn type has no expression of its own; `Unknown` holds its
            // POSITION so a `?N` projection still indexes the arguments as written.
            collected.push(type_expr(arg, src, resolve_self).unwrap_or(TypeExpr::Unknown));
        }
    }
    Some(TypeExpr::Named {
        name: SmolStr::new(resolve_self(base_name.to_string())),
        args: collected,
    })
}

/// `#[derive(Default)]` on a type is a DECLARED fact about it: `T::default()` evaluates to
/// `T`. Nothing is inferred here — the derive says the impl exists and the trait's signature
/// says what it returns, the same curated-stdlib knowledge `is_machinery_trait` already
/// carries. Without it a `let sink = Sink::default()` binding points at a member no impl block
/// declares, and every field read off that local resolves nowhere
/// (`internal/detection-gaps.md` §3 — the plugin sinks are exactly this shape).
fn push_derived_default_type(item: Node, src: &[u8], pending: &PendingAttrs, out: &mut FileFacts) {
    let derives_default = pending
        .derives
        .iter()
        .any(|(name, _)| name.rsplit("::").next() == Some("Default"));
    if !derives_default {
        return;
    }
    let Some(name) = item.child_by_field_name("name").map(|n| text(n, src)) else {
        return;
    };
    out.member_types.push(kndo_core::adapter::RawMemberType {
        owner: Some(SmolStr::new(name)),
        member: SmolStr::new("default"),
        yields: kndo_core::adapter::TypeExpr::named(name),
    });
}

/// A member-type fact for an impl item that carries a name field (fn return, const type).
fn push_owner_member_type(out: &mut FileFacts, owner: &str, item: Node, ty: Node, src: &[u8]) {
    if let Some(name) = item.child_by_field_name("name") {
        push_member_type(&mut out.member_types, Some(owner), text(name, src), ty, src);
    }
}

fn handle_enum(item: Node, src: &[u8], ctx: &Ctx<'_>, out: &mut FileFacts) {
    let Some(name_node) = item.child_by_field_name("name") else {
        return;
    };
    let name = text(name_node, src);
    let vis = visibility(item);
    push_declaration(out, name, SymbolKind::Enum, item, None, None, vis);
    if let Some(body) = item.child_by_field_name("body") {
        let mut c = body.walk();
        for variant in body.children(&mut c) {
            if variant.kind() == "enum_variant" {
                if let Some(vname) = variant.child_by_field_name("name") {
                    push_declaration(
                        out,
                        text(vname, src),
                        SymbolKind::EnumMember,
                        variant,
                        None,
                        Some(name),
                        vis, // variants share the enum's visibility (Rust rule)
                    );
                    if let Some(d) = out.declarations.last_mut() {
                        // …and that shared level is inherited, not declarable: no
                        // visibility keyword can ever sit on a variant.
                        d.visibility_inherited = true;
                    }
                }
                walk_type_refs(
                    variant,
                    src,
                    Some(name),
                    PathEnv {
                        locals: ctx.local_qualifiers,
                        inline_mods: ctx.inline_mod_names,
                        file_types: ctx.file_type_names,
                        crate_probe: ctx.crate_probe,
                        use_bound: ctx.use_bound,
                        types: TypeEnv::empty(),
                    },
                    out,
                );
            }
        }
    }
}

fn handle_trait(item: Node, src: &[u8], ctx: &Ctx<'_>, out: &mut FileFacts) {
    let Some(name_node) = item.child_by_field_name("name") else {
        return;
    };
    let name = text(name_node, src);
    let vis = visibility(item);
    push_declaration(out, name, SymbolKind::Interface, item, None, None, vis);
    if let Some(body) = item.child_by_field_name("body") {
        let mut members = body.walk();
        let mut pending = PendingAttrs::default();
        for member in body.children(&mut members) {
            match member.kind() {
                "attribute_item" => collect_attr(member, src, &mut pending, out),
                "function_item" | "function_signature_item" => {
                    let p = std::mem::take(&mut pending);
                    record_test_region(&p, member, ctx, out);
                    handle_function(member, src, ctx, Some(name), &p, Some(vis), out);
                }
                "associated_type" | "const_item" => {
                    let p = std::mem::take(&mut pending);
                    record_test_region(&p, member, ctx, out);
                    if let Some(mname) = member.child_by_field_name("name") {
                        push_declaration(
                            out,
                            text(mname, src),
                            if member.kind() == "const_item" {
                                SymbolKind::Const
                            } else {
                                SymbolKind::TypeAlias
                            },
                            member,
                            None,
                            Some(name),
                            vis,
                        );
                        if let Some(d) = out.declarations.last_mut() {
                            // Trait items inherit the trait's visibility — same
                            // no-keyword-of-its-own rule as the method arm above.
                            d.visibility_inherited = true;
                        }
                    }
                }
                _ => {}
            }
        }
    }
}

/// Stdlib traits whose methods the language machinery invokes **namelessly** — the curated
/// criterion is "the call site never writes the method's name": formatting hooks (`{}`,
/// `{:?}` and the numeric formats), destructors (scope end), comparison and arithmetic
/// operators, indexing/deref sugar, loop and await protocols, `str::parse`'s `from_str`,
/// error-chain reporting, and `Default`'s derive/`unwrap_or_default` machinery. Name-called
/// trait methods (`.clone()`, `.into()`, `.as_ref()`) are deliberately absent — the duck
/// fallback already reaches those from their call sites. Third-party traits (serde et al.)
/// stay unmodeled: the curated fact set covers the stdlib only.
fn is_machinery_trait(name: &str) -> bool {
    matches!(
        name,
        // fmt hooks
        "Display" | "Debug" | "Octal" | "Binary" | "LowerHex" | "UpperHex" | "LowerExp"
            | "UpperExp" | "Pointer"
            // lifecycle
            | "Drop" | "Default"
            // comparison + hashing machinery
            | "PartialEq" | "Eq" | "PartialOrd" | "Ord" | "Hash"
            // operator overloads
            | "Add" | "Sub" | "Mul" | "Div" | "Rem" | "Neg" | "Not" | "BitAnd" | "BitOr"
            | "BitXor" | "Shl" | "Shr" | "AddAssign" | "SubAssign" | "MulAssign"
            | "DivAssign" | "RemAssign" | "BitAndAssign" | "BitOrAssign" | "BitXorAssign"
            | "ShlAssign" | "ShrAssign"
            // sugar + protocols
            | "Index" | "IndexMut" | "Deref" | "DerefMut" | "Iterator" | "IntoIterator"
            | "DoubleEndedIterator" | "ExactSizeIterator" | "Future" | "FromStr" | "Error"
    )
}

/// The member declaration `handle_function`/`push_declaration` just pushed — searched from
/// the end, where they left it. Both facts an impl block knows about its members
/// (`implicitly_invoked`, `implements`) are recorded through this one lookup.
fn last_member_decl<'a>(
    out: &'a mut FileFacts,
    owner: &str,
    name: &str,
) -> Option<&'a mut kndo_core::adapter::Declaration> {
    out.declarations
        .iter_mut()
        .rev()
        .find(|d| d.name == name && d.member_of.as_deref() == Some(owner))
}

/// Flip [`kndo_core::adapter::Declaration::implicitly_invoked`] on the just-pushed member —
/// the language's OWN machinery traits, this adapter's curated verdict.
fn mark_implicitly_invoked(out: &mut FileFacts, owner: &str, name: &str) {
    if let Some(decl) = last_member_decl(out, owner, name) {
        decl.implicitly_invoked = true;
    }
}

/// Record [`kndo_core::adapter::Declaration::implements`] on the just-pushed member: the
/// trait whose `impl` block declares it. A FACT, recorded for every trait impl regardless of
/// whether this adapter considers the trait machinery — because the consumer that knows a
/// third-party trait's meaning is a plugin, and it can only know it if the fact survives
/// extraction. Reducing it to `implicitly_invoked` alone is what once forced `kndo:serde` to
/// re-parse Rust source the adapter had already parsed.
fn record_implements(out: &mut FileFacts, owner: &str, name: &str, trait_name: &str) {
    if let Some(decl) = last_member_decl(out, owner, name) {
        decl.implements = Some(SmolStr::new(trait_name));
    }
}

/// Is `name` one of the impl's OWN type parameters (`impl<'a, M: Matcher> … for &'a M`)?
fn is_impl_type_parameter(item: Node, src: &[u8], name: &str) -> bool {
    let Some(params) = item.child_by_field_name("type_parameters") else {
        return false;
    };
    let mut c = params.walk();
    let found = params
        .children(&mut c)
        .any(|p| type_parameter_named(p, src, name));
    found
}

/// One `type_parameters` child declaring exactly `name` (plain, constrained, or the bare
/// `type_identifier` shape older grammar nodes use).
fn type_parameter_named(p: Node, src: &[u8], name: &str) -> bool {
    if !matches!(
        p.kind(),
        "type_parameter" | "constrained_type_parameter" | "type_identifier"
    ) {
        return false;
    }
    match p.child_by_field_name("name") {
        Some(n) => text(n, src) == name,
        None => p.kind() == "type_identifier" && text(p, src) == name,
    }
}

/// Self sits behind a forwarding wrapper: `&T` / `&mut T` (`reference_type`) or `Box<T>`.
fn is_wrapped_self(type_node: Node) -> bool {
    match type_node.kind() {
        "reference_type" => true,
        "generic_type" => type_node
            .child_by_field_name("type")
            .is_some_and(|t| t.kind() == "type_identifier"),
        _ => false,
    }
}

fn handle_impl(item: Node, src: &[u8], ctx: &Ctx<'_>, out: &mut FileFacts) {
    // The self type's bare name: `impl S`, `impl S<T>`, `impl a::S` all own members under `S`.
    let Some(type_node) = item.child_by_field_name("type") else {
        return;
    };
    let self_type = impl_header_name(type_node, src);
    let Some(self_type) = self_type else { return };
    let trait_name = item
        .child_by_field_name("trait")
        .and_then(|t| impl_header_name(t, src).map(|n| n.to_string()));

    // Blanket forwarding (`impl<'a, M: Matcher> Matcher for &'a M`, `for &mut S`, `for
    // Box<S>`): Self is one of the impl's OWN type parameters behind a reference/Box —
    // there is no nominal type to own the members (the bare parameter name is a phantom no
    // receiver ever unifies with), and the impl executes precisely when the trait is used
    // through that wrapper. Model it as machinery OF THE TRAIT: members attribute to the
    // trait's name and mark implicitly_invoked, so reaching the trait plausibly reaches the
    // forwarding shims (degrade toward silence).
    let forwards_to_trait = trait_name.as_deref().is_some_and(|_| {
        is_impl_type_parameter(item, src, &self_type) && is_wrapped_self(type_node)
    });
    let (self_type, is_forwarding) = if forwards_to_trait {
        (trait_name.clone().unwrap(), true)
    } else {
        (self_type, false)
    };

    // `impl Trait for T` — the Implement reference that keeps dispatch-aware liveness
    // honest: using the trait keeps its implementations alive. A forwarding impl
    // skips it (the trait implementing itself is a no-op loop).
    if !is_forwarding {
        if let (Some(trait_node), Some(trait_name)) =
            (item.child_by_field_name("trait"), trait_name.as_deref())
        {
            out.references.push(RawReference {
                name: SmolStr::new(trait_name),
                scope_context: None,
                span: span(trait_node),
                within: Some(SmolStr::new(&self_type)),
                kind: RefKind::Implement,
            });
        }
    }

    let is_trait_impl = item.child_by_field_name("trait").is_some();
    // Machinery traits (the machinery-dispatch rule): the call site never writes
    // the method's name — an operator, a `{}` hook, a scope end, a `for` loop — so members
    // of these impls are marked `implicitly_invoked` and inherit their owner's colors.
    let is_machinery = is_forwarding
        || item
            .child_by_field_name("trait")
            .and_then(|t| impl_header_name(t, src))
            .is_some_and(|t| is_machinery_trait(&t));
    if let Some(body) = item.child_by_field_name("body") {
        let mut members = body.walk();
        let mut pending = PendingAttrs::default();
        for member in body.children(&mut members) {
            match member.kind() {
                "attribute_item" => collect_attr(member, src, &mut pending, out),
                "function_item" => {
                    let p = std::mem::take(&mut pending);
                    record_test_region(&p, member, ctx, out);
                    handle_function(member, src, ctx, Some(&self_type), &p, None, out);
                    // Member-type fact: what calling this method yields —
                    // its declared return, dispatch-reduced, `Self` resolved to the owner.
                    if let Some(ret) = member.child_by_field_name("return_type") {
                        push_owner_member_type(out, &self_type, member, ret, src);
                    }
                    // Trait-impl methods are called through the trait's dispatch (dyn, generic
                    // bounds, operator/format machinery — `Display::fmt` is never `x.fmt()` in
                    // source), so the name-based member fallback cannot see their call sites:
                    // root them at Probable (the dispatch rule, made concrete —
                    // over-liveness in the safe direction).
                    if is_trait_impl {
                        if let Some(mname) = member.child_by_field_name("name") {
                            out.roots.push(RawRoot {
                                kind: RootKind::Production,
                                target: RawRootTarget::Declaration(SmolStr::new(format!(
                                    "{self_type}.{}",
                                    text(mname, src)
                                ))),
                                confidence: Confidence::Probable,
                            });
                            if let Some(t) = trait_name.as_deref() {
                                record_implements(out, &self_type, text(mname, src), t);
                            }
                            if is_machinery {
                                mark_implicitly_invoked(out, &self_type, text(mname, src));
                            }
                        }
                    }
                }
                "const_item" | "type_item" | "associated_type" => {
                    let p = std::mem::take(&mut pending);
                    record_test_region(&p, member, ctx, out);
                    if member.kind() == "const_item" {
                        if let Some(ty) = member.child_by_field_name("type") {
                            push_owner_member_type(out, &self_type, member, ty, src);
                        }
                    }
                    if let Some(mname) = member.child_by_field_name("name") {
                        push_declaration(
                            out,
                            text(mname, src),
                            if member.kind() == "const_item" {
                                SymbolKind::Const
                            } else {
                                SymbolKind::TypeAlias
                            },
                            member,
                            None,
                            Some(&self_type),
                            visibility(member),
                        );
                        // Same dispatch rule as trait-impl methods: an associated
                        // type/const in `impl Trait for T` (`type Output = …` in an `Add`
                        // impl) is consumed through the trait's machinery, never by name.
                        if is_trait_impl {
                            out.roots.push(RawRoot {
                                kind: RootKind::Production,
                                target: RawRootTarget::Declaration(SmolStr::new(format!(
                                    "{self_type}.{}",
                                    text(mname, src)
                                ))),
                                confidence: Confidence::Probable,
                            });
                            if let Some(t) = trait_name.as_deref() {
                                record_implements(out, &self_type, text(mname, src), t);
                            }
                        }
                    }
                }
                _ => {}
            }
        }
    }
}

/// The rightmost `type_identifier` under a type node — `S`, `S<T>`, `a::b::S` all yield `S`.
/// The nominal name an impl header's type or trait position reduces to: `Serialize`,
/// `serde::ser::Serialize`, `ArchiveWith<SmolStr>` and `&'a mut Wrapper<T>` all give the BASE
/// name — the type being named, never one of its arguments.
///
/// The distinction is load-bearing in both positions. `impl Index<usize> for T` implements
/// `Index`, not `usize`; `impl Serialize for Vec<Token>` owns its members under `Vec`, not
/// `Token`. A walk that simply took the last identifier anywhere in the subtree answered with
/// the argument, which pointed the `Implement` reference at the wrong name and cost every
/// GENERIC machinery trait its members' marks (`Add`, `Index`, `PartialEq` — the non-generic
/// ones, `Display` and `Drop`, worked by accident).
fn impl_header_name(node: Node, src: &[u8]) -> Option<String> {
    if node.kind() == "type_identifier" {
        return Some(text(node, src).to_string());
    }
    // A generic application names its base; the arguments are other types entirely.
    if node.kind() == "generic_type" {
        return node
            .child_by_field_name("type")
            .and_then(|base| impl_header_name(base, src));
    }
    let mut found = None;
    let mut cursor = node.walk();
    for child in node.children(&mut cursor) {
        if let Some(name) = impl_header_name(child, src) {
            found = Some(name);
        }
    }
    found
}

fn handle_simple_decl(
    item: Node,
    src: &[u8],
    ctx: &Ctx<'_>,
    kind: SymbolKind,
    owner: Option<&str>,
    pending: &PendingAttrs,
    out: &mut FileFacts,
) {
    let Some(name) = item.child_by_field_name("name") else {
        return;
    };
    let vis = visibility(item);
    push_declaration(out, text(name, src), kind, item, None, owner, vis);
    // Runtime-consumed item (`#[global_allocator]` — the runtime is the caller, same
    // reasoning as `#[no_mangle]` on a fn): a root, no in-graph reference will ever exist.
    if pending.ffi_export {
        out.roots.push(RawRoot {
            kind: RootKind::Production,
            target: RawRootTarget::Declaration(SmolStr::new(text(name, src))),
            confidence: Confidence::Probable,
        });
    }
    // Initializer expressions run at load: within = None (the load-time rule).
    if let Some(value) = item.child_by_field_name("value") {
        walk_body(
            value,
            src,
            None,
            PathEnv {
                locals: ctx.local_qualifiers,
                inline_mods: ctx.inline_mod_names,
                file_types: ctx.file_type_names,
                crate_probe: ctx.crate_probe,
                use_bound: ctx.use_bound,
                types: TypeEnv::empty(),
            },
            out,
        );
    }
    if let Some(ty) = item.child_by_field_name("type") {
        walk_type_refs(
            ty,
            src,
            None,
            PathEnv {
                locals: ctx.local_qualifiers,
                inline_mods: ctx.inline_mod_names,
                file_types: ctx.file_type_names,
                crate_probe: ctx.crate_probe,
                use_bound: ctx.use_bound,
                types: TypeEnv::empty(),
            },
            out,
        );
    }
}

fn handle_mod(item: Node, src: &[u8], ctx: &Ctx<'_>, pending: &PendingAttrs, out: &mut FileFacts) {
    let Some(name) = item.child_by_field_name("name") else {
        return;
    };
    match item.child_by_field_name("body") {
        // Inline module: flatten (file ≈ module — stated once, leaned on everywhere).
        Some(body) => {
            let first_inner = out.declarations.len();
            walk_items(
                body,
                src,
                &Ctx {
                    owner: None,
                    in_cfg_test: ctx.in_cfg_test || pending.cfg_test,
                    local_qualifiers: ctx.local_qualifiers,
                    inline_mod_names: ctx.inline_mod_names,
                    field_types: ctx.field_types,
                    file_type_names: ctx.file_type_names,
                    crate_probe: ctx.crate_probe,
                    use_bound: ctx.use_bound,
                },
                out,
            );
            // Everything the body walk declared lives in a nested scope unit: its
            // tightest declarable visibility means "this module", strictly narrower
            // than the ladder's file rung — `Declaration::nested_scope`'s contract.
            // Marking the whole range keeps the fact out of every push site's signature.
            for decl in &mut out.declarations[first_inner..] {
                decl.nested_scope = true;
            }
        }
        // `mod foo;` — THE file-linking import. #[path] overrides the location.
        // `pub mod foo;` additionally re-exports the child's whole surface (reexported, no
        // bindings — the shape the library-surface fixpoint expands): a published
        // crate's API lives behind exactly these chains.
        None => {
            let specifier = match &pending.mod_path {
                Some(p) => format!("file:{p}"),
                None => format!("self::{}", text(name, src)),
            };
            let (_, is_pub) = visibility(item);
            out.imports.push(RawImport {
                specifier: SmolStr::new(specifier),
                kind: ImportKind::Relative,
                span: span(item),
                side_effect_only: true,
                type_only: false,
                confidence: Confidence::Certain,
                bindings: Vec::new(),
                reexported: is_pub,
                // The child module's items are addressable through `name::…` qualifiers.
                // `#[macro_use] mod x;` additionally globs the child's macro namespace into
                // crate scope — invocations anywhere reach its `macro_rules!` without an
                // import, which no binding can express (the wildcard rule).
                opaque_namespace_use: pending.macro_use,
                module_names_visible: false,
                local_alias: Some(SmolStr::new(text(name, src))),
                reconstructed: false,
            });
        }
    }
}

// ---------------------------------------------------------------- use declarations

fn handle_use(item: Node, src: &[u8], ctx: &Ctx<'_>, out: &mut FileFacts) {
    let reexported = {
        let mut c = item.walk();
        let found = item
            .children(&mut c)
            .any(|n| n.kind() == "visibility_modifier");
        found
    };
    let Some(argument) = item.child_by_field_name("argument") else {
        return;
    };
    // A path rooted at a same-file inline `mod` names nothing outside this file (see
    // `collect_inline_mod_names`) — there is no cross-file or cross-crate relationship for
    // the import graph to record, so this `use` contributes nothing.
    let root = text(argument, src).split("::").next().unwrap_or("").trim();
    if ctx.inline_mod_names.contains(root) {
        return;
    }
    let before = out.imports.len();
    collect_use(argument, src, "", reexported, span(item), out);
    weaken_rebound_use(root, ctx.use_bound, before, out);
}

/// A `use` rooted at a name this file's own imports already bind re-qualifies that binding
/// (`use serde::de::{self, …};` then `use de::Error;`) — it is not a crate import. The
/// imports it produced are DOWNGRADED, not dropped: `undeclared` ignores the Possible tier so
/// the accusation goes away, while the edges themselves survive, which is what keeps a
/// declared dependency reached only through such a path from reading `unused`.
fn weaken_rebound_use(
    root: &str,
    use_bound: &std::collections::HashSet<String>,
    before: usize,
    out: &mut FileFacts,
) {
    if !use_bound.contains(root) {
        return;
    }
    for imp in &mut out.imports[before..] {
        imp.confidence = imp.confidence.min(Confidence::Possible);
    }
}

fn import_kind(path: &str) -> ImportKind {
    match path.split("::").next() {
        Some("crate" | "self" | "super") => ImportKind::Relative,
        _ => ImportKind::Package,
    }
}

/// The entry-liveness companion: a deep path into a crate traverses its module
/// tree from the entry, so `use crate_name::deep::Item` also imports `crate_name` alone.
fn push_entry_import(specifier: &str, at: Span, out: &mut FileFacts) {
    if import_kind(specifier) != ImportKind::Package {
        return;
    }
    let Some((root, _)) = specifier.split_once("::") else {
        return;
    };
    out.imports.push(RawImport {
        specifier: SmolStr::new(root),
        kind: ImportKind::Package,
        span: at,
        side_effect_only: true,
        type_only: false,
        confidence: Confidence::Certain,
        bindings: Vec::new(),
        reexported: false,
        opaque_namespace_use: false,
        module_names_visible: false,
        local_alias: None,
        reconstructed: false,
    });
}

fn make_import(specifier: &str, kind_span: (ImportKind, Span), reexported: bool) -> RawImport {
    RawImport {
        specifier: SmolStr::new(specifier),
        kind: kind_span.0,
        span: kind_span.1,
        side_effect_only: false,
        type_only: false,
        confidence: Confidence::Certain,
        bindings: Vec::new(),
        reexported,
        opaque_namespace_use: false,
        module_names_visible: false,
        local_alias: None,
        reconstructed: false,
    }
}

/// Recursive over the use-argument shapes verified in `introspect`: `scoped_identifier`,
/// `scoped_use_list`, `use_wildcard`, `use_as_clause`, bare `identifier`/`crate`/`self`.
/// `prefix` is the path accumulated from enclosing lists (`use a::{b::{c}}` reaches `c` with
/// prefix `a::b`).
fn collect_use(
    node: Node,
    src: &[u8],
    prefix: &str,
    reexported: bool,
    at: Span,
    out: &mut FileFacts,
) {
    let join = |tail: &str| {
        if prefix.is_empty() {
            tail.to_string()
        } else {
            format!("{prefix}::{tail}")
        }
    };
    match node.kind() {
        // Full path, no list: `use a::b::X;` — specifier keeps the full path; the resolver's
        // two-step tail rule decides module-vs-item, extraction never guesses.
        "scoped_identifier" | "identifier" | "crate" | "self" | "super" => {
            let full = join(text(node, src));
            let last = full.rsplit("::").next().unwrap_or(&full).to_string();
            let mut imp = make_import(&full, (import_kind(&full), at), reexported);
            if !matches!(last.as_str(), "crate" | "self" | "super") {
                imp.bindings.push(ImportBinding {
                    local: SmolStr::new(&last),
                    imported: Some(SmolStr::new(&last)),
                });
                // A module import (`use crate::a::helpers;`) makes `helpers::…` qualifiers
                // resolvable — the alias is the tail either way; harmless when the tail was
                // an item (nothing qualifies through an item name).
                imp.local_alias = Some(SmolStr::new(&last));
            }
            out.imports.push(imp);
            push_entry_import(&full, at, out);
        }
        "use_as_clause" => {
            let (Some(path), Some(alias)) = (
                node.child_by_field_name("path"),
                node.child_by_field_name("alias"),
            ) else {
                return;
            };
            let full = join(text(path, src));
            let imported = full.rsplit("::").next().unwrap_or(&full).to_string();
            let local = text(alias, src);
            let mut imp = make_import(&full, (import_kind(&full), at), reexported);
            imp.bindings.push(ImportBinding {
                local: SmolStr::new(local),
                imported: Some(SmolStr::new(&imported)),
            });
            imp.local_alias = Some(SmolStr::new(local));
            out.imports.push(imp);
            push_entry_import(&full, at, out);
        }
        "use_wildcard" => {
            // `use p::*` — the truth of a glob is a Wildcard over the target's exports.
            let inner = node
                .named_child(0)
                .map(|n| text(n, src).to_string())
                .unwrap_or_default();
            let full = join(&inner);
            let mut imp = make_import(&full, (import_kind(&full), at), reexported);
            imp.opaque_namespace_use = true;
            out.imports.push(imp);
        }
        "scoped_use_list" => {
            let (Some(path), Some(list)) = (
                node.child_by_field_name("path"),
                node.child_by_field_name("list"),
            ) else {
                return;
            };
            let new_prefix = join(text(path, src));
            collect_use(list, src, &new_prefix, reexported, at, out);
        }
        "use_list" => {
            // Simple identifiers and as-clauses group into ONE import for the prefix; nested
            // shapes recurse into their own imports.
            let mut grouped = make_import(prefix, (import_kind(prefix), at), reexported);
            let mut cursor = node.walk();
            for element in node.children(&mut cursor) {
                match element.kind() {
                    "identifier" => grouped.bindings.push(ImportBinding {
                        local: SmolStr::new(text(element, src)),
                        imported: Some(SmolStr::new(text(element, src))),
                    }),
                    "self" => {
                        // `use a::{self, b}` — the module itself becomes qualifiable.
                        let tail = prefix.rsplit("::").next().unwrap_or(prefix);
                        grouped.local_alias = Some(SmolStr::new(tail));
                    }
                    "use_as_clause" => {
                        let (Some(p), Some(alias)) = (
                            element.child_by_field_name("path"),
                            element.child_by_field_name("alias"),
                        ) else {
                            continue;
                        };
                        if p.kind() == "identifier" || p.kind() == "self" {
                            grouped.bindings.push(ImportBinding {
                                local: SmolStr::new(text(alias, src)),
                                imported: Some(SmolStr::new(text(p, src))),
                            });
                        } else {
                            collect_use(element, src, prefix, reexported, at, out);
                        }
                    }
                    "scoped_identifier" | "scoped_use_list" | "use_wildcard" | "use_list" => {
                        collect_use(element, src, prefix, reexported, at, out);
                    }
                    _ => {}
                }
            }
            if !grouped.bindings.is_empty() || grouped.local_alias.is_some() {
                out.imports.push(grouped);
                push_entry_import(prefix, at, out);
            }
        }
        _ => {}
    }
}

// ---------------------------------------------------------------- references

/// Type positions: every `type_identifier` is a `TypeUse`; scoped type paths rooted at
/// `crate`/`self`/`super` also emit the synthetic import (module doc).
fn walk_type_refs(
    node: Node,
    src: &[u8],
    within: Option<&str>,
    env: PathEnv<'_>,
    out: &mut FileFacts,
) {
    match node.kind() {
        "line_comment" | "block_comment" => {}
        "type_identifier" => out.references.push(RawReference {
            name: SmolStr::new(text(node, src)),
            scope_context: None,
            span: span(node),
            within: within.map(SmolStr::new),
            kind: RefKind::TypeUse,
        }),
        "scoped_type_identifier" => {
            handle_scoped_path(node, src, within, RefKind::TypeUse, env, out);
        }
        // Field/variant attributes (`#[rkyv(with = crate::…::SmolStrAsString)]`, `#[serde(…)]`)
        // are token soup below the type body — same scan as item-level unknown attributes, so
        // attr-only consumers referenced from *fields* stay alive too.
        "attribute_item" => {
            if let Some(attr) = node.named_child(0) {
                if let Some(name_node) = attr.child(0) {
                    scan_unknown_attr(attr, text(name_node, src), src, out);
                }
            }
        }
        _ => {
            let mut cursor = node.walk();
            for child in node.children(&mut cursor) {
                walk_type_refs(child, src, within, env, out);
            }
        }
    }
}

/// Expression bodies: calls, qualified paths, member accesses, macro invocations, plain
/// identifier reads (locals shadowing a top-level name over-approximate ALIVE — the safe
/// direction).
fn walk_body(node: Node, src: &[u8], within: Option<&str>, env: PathEnv<'_>, out: &mut FileFacts) {
    match node.kind() {
        "line_comment" | "block_comment" => return,
        // The RUNTIME spelling of Cargo's bin handshake — `env::var_os("CARGO_BIN_EXE_app")`
        // — carries the same documented literal as the `env!` macro
        // form below in `handle_macro`. Only the documented prefix, only a literal; the name
        // still resolves against the manifest's declared executables or drops.
        "string_literal" | "raw_string_literal" => {
            if let Some(exe) = text(node, src)
                .trim_matches(|c| c == '"' || c == 'r' || c == '#')
                .strip_prefix("CARGO_BIN_EXE_")
                .filter(|exe| {
                    !exe.is_empty()
                        && exe
                            .chars()
                            .all(|c| c.is_alphanumeric() || c == '_' || c == '-')
                })
            {
                out.invoked_executables.push(SmolStr::new(exe));
            }
            return;
        }
        "use_declaration" => {
            // A body-scoped `use` is an import, not an expression: route it through the same
            // extraction item-level uses get. Walking it generically fabricates phantom
            // package references from its intermediate path segments (`use std::{fs::File,
            // os::{fd::AsFd, unix::fs::FileTypeExt}}` → "fs"/"os"/"fd"/"unix" as packages).
            if let Some(argument) = node.child_by_field_name("argument") {
                // Same inline-mod guard `handle_use` applies at item level: `mod desugared
                // { … }` declared inside a function body, then `use desugared::Test as …`
                // right below it, names nothing outside this file — routing it through
                // package resolution invented a dependency named `desugared` (serde's
                // test_annotations.rs). Body-scoped `use` reached `collect_use` directly and
                // so skipped the check.
                let root = text(argument, src).split("::").next().unwrap_or("").trim();
                if env.inline_mods.contains(root) {
                    return;
                }
                let before = out.imports.len();
                collect_use(argument, src, "", false, span(node), out);
                weaken_rebound_use(root, env.use_bound, before, out);
            }
            return;
        }
        "identifier" => {
            if is_reference_position(node) {
                out.references.push(RawReference {
                    name: SmolStr::new(text(node, src)),
                    scope_context: None,
                    span: span(node),
                    within: within.map(SmolStr::new),
                    kind: if node.parent().is_some_and(|p| p.kind() == "call_expression") {
                        RefKind::Call
                    } else {
                        RefKind::Read
                    },
                });
            }
            return;
        }
        "scoped_identifier" => {
            let kind = if node.parent().is_some_and(|p| p.kind() == "call_expression") {
                RefKind::Call
            } else {
                RefKind::Read
            };
            handle_scoped_path(node, src, within, kind, env, out);
            return;
        }
        "field_expression" => {
            // `x.method()` / `x.field` — a member access by construction. With the
            // receiver's TYPE known ([`TypeEnv`]) the qualifier is the
            // type name — the core resolves the member in the type's home file at Certain,
            // exactly like the qualified `Type::member` path. Unknown receivers keep the
            // opaque qualifier and land in the duck-typed fallback.
            let (Some(value), Some(field)) = (
                node.child_by_field_name("value"),
                node.child_by_field_name("field"),
            ) else {
                return;
            };
            let kind = if node.parent().is_some_and(|p| p.kind() == "call_expression") {
                RefKind::Call
            } else {
                RefKind::Read
            };
            let typed = receiver_qualifier(value, env.types, src);
            let qualifier = typed.as_deref().unwrap_or(match value.kind() {
                "identifier" | "self" => text(value, src),
                _ => "<expr>",
            });
            out.references.push(RawReference {
                name: SmolStr::new(text(field, src)),
                scope_context: Some(SmolStr::new(qualifier)),
                span: span(node),
                within: within.map(SmolStr::new),
                kind,
            });
            match value.kind() {
                "identifier" => {
                    // The receiver variable itself is read either way.
                    out.references.push(RawReference {
                        name: SmolStr::new(text(value, src)),
                        scope_context: None,
                        span: span(value),
                        within: within.map(SmolStr::new),
                        kind: RefKind::Read,
                    });
                }
                "self" => {}
                _ => walk_body(value, src, within, env, out),
            }
            return;
        }
        "macro_invocation" => {
            handle_macro(node, src, within, env, out);
            return;
        }
        "type_identifier" => {
            out.references.push(RawReference {
                name: SmolStr::new(text(node, src)),
                scope_context: None,
                span: span(node),
                within: within.map(SmolStr::new),
                kind: RefKind::TypeUse,
            });
            return;
        }
        "scoped_type_identifier" => {
            handle_scoped_path(node, src, within, RefKind::TypeUse, env, out);
            return;
        }
        _ => {}
    }
    let mut cursor = node.walk();
    for child in node.children(&mut cursor) {
        walk_body(child, src, within, env, out);
    }
}

/// Whether a bare identifier here reads a value (vs. binding a new name in a pattern).
fn is_reference_position(node: Node) -> bool {
    let Some(parent) = node.parent() else {
        return false;
    };
    match parent.kind() {
        // Patterns bind, they don't read.
        "parameter"
        | "closure_parameters"
        | "tuple_pattern"
        | "tuple_struct_pattern"
        | "struct_pattern"
        | "field_pattern"
        | "match_pattern"
        | "or_pattern"
        | "captured_pattern"
        | "reference_pattern"
        | "mut_pattern" => false,
        "let_declaration" => {
            // `let NAME = value` — pattern side binds, value side reads.
            parent
                .child_by_field_name("pattern")
                .is_none_or(|p| p.id() != node.id())
        }
        // Struct-literal initializers READ: a `field_initializer`'s identifier child is
        // always the value (the field name is a `field_identifier`, a different node kind),
        // and a shorthand `Foo { x }` reads local `x` — both fall through to `true`.
        _ => true,
    }
}

/// A `::`-path outside a `use`: rooted paths become a synthetic import + a plain binding
/// reference (a fully-qualified use-site IS an import); bare-rooted paths emit a qualified
/// reference resolved through import aliases (module doc).
fn handle_scoped_path(
    node: Node,
    src: &[u8],
    within: Option<&str>,
    kind: RefKind,
    env: PathEnv<'_>,
    out: &mut FileFacts,
) {
    let full = text(node, src);
    // Strip generic turbofish (`Vec::<u8>::new` → segments without the `::<u8>` part).
    let mut segments: Vec<&str> = full
        .split("::")
        .filter(|s| !s.is_empty() && !s.starts_with('<'))
        .collect();
    // `Self::assoc()` inside an impl IS `Owner::assoc()` — the language fact the enclosing
    // impl states; without the substitution the member table has no
    // `Self.assoc` to hit and the reference falls to the duck fallback.
    if segments.first() == Some(&"Self") {
        if let Some(owner) = &env.types.owner {
            segments[0] = owner.as_str();
        }
    }
    emit_path(&segments, span(node), within, kind, env, out);
}

/// The path emissions shared by AST-shaped paths (`handle_scoped_path`) and token-soup paths
/// reconstructed inside macro invocations (`scan_token_tree`) — one rule, two surfaces.
fn emit_path(
    segments: &[&str],
    at: Span,
    within: Option<&str>,
    kind: RefKind,
    env: PathEnv<'_>,
    out: &mut FileFacts,
) {
    let [rest @ .., last] = segments else {
        return;
    };
    if rest.is_empty() {
        return;
    }
    let root = rest[0];
    if matches!(root, "crate" | "self" | "super") {
        // Import resolution maps MODULE paths to files, so the specifier must stop before
        // the path crosses into type space: in `crate::logger::Logger::init()` the module
        // prefix is `crate::logger`, `Logger` is a symbol inside that file, and `init` is
        // that type's associated item. Splitting there lets the type bind through the
        // import and the item reach the member table — an unsplit `crate::logger::Logger`
        // specifier resolves to no file and the whole chain reads as dead.
        let type_pos = rest[1..]
            .iter()
            .position(|s| s.chars().next().is_some_and(char::is_uppercase))
            .map(|p| p + 1);
        let (module_path, bound) = match type_pos {
            Some(i) => (&rest[..i], rest[i]),
            None => (rest, *last),
        };
        out.imports.push(RawImport {
            specifier: SmolStr::new(module_path.join("::")),
            kind: ImportKind::Relative,
            span: at,
            side_effect_only: false,
            type_only: kind == RefKind::TypeUse,
            confidence: Confidence::Certain,
            bindings: vec![ImportBinding {
                local: SmolStr::new(bound),
                imported: Some(SmolStr::new(bound)),
            }],
            reexported: false,
            opaque_namespace_use: false,
            module_names_visible: false,
            local_alias: None,
            // Synthesized from a use SITE: the file writes this path inline and no import
            // statement for it exists, so its binding must not outrank the file's own declarations.
            reconstructed: true,
        });
        if bound != *last {
            // The type itself is used by the traversal, and the trailing item resolves as
            // its member — the same two emissions the bare-root branch below makes for
            // `logger::Logger::init()`.
            out.references.push(RawReference {
                name: SmolStr::new(bound),
                scope_context: None,
                span: at,
                within: within.map(SmolStr::new),
                kind: RefKind::Read,
            });
        }
        out.references.push(RawReference {
            name: SmolStr::new(*last),
            scope_context: (bound != *last).then(|| SmolStr::new(rest[rest.len() - 1])),
            span: at,
            within: within.map(SmolStr::new),
            kind,
        });
    } else if rest.len() == 1 && env.inline_mods.contains(root) {
        // A path through a same-file *inline* mod (`convert::usize(..)` with `mod convert
        // { .. }` right here): extraction flattens inline-mod bodies into the file,
        // so the target is a same-file bare symbol — emit the reference bare. Routing it
        // through qualifier resolution has no alias/member to bind to and false-positives
        // the target as `unused`.
        out.references.push(RawReference {
            name: SmolStr::new(*last),
            scope_context: None,
            span: at,
            within: within.map(SmolStr::new),
            kind,
        });
    } else {
        // Bare root: `helpers::run`, `serde_json::to_string`, `Vec::new`. The immediate
        // qualifier goes to scope_context — the core matches it against import aliases;
        // an uppercase qualifier is a type's associated item, which lands in
        // the member fallback via the qualified table.
        let qualifier = rest.last().copied().unwrap_or(root);
        out.references.push(RawReference {
            name: SmolStr::new(*last),
            scope_context: Some(SmolStr::new(qualifier)),
            span: at,
            within: within.map(SmolStr::new),
            kind,
        });
        // An uppercase qualifier NAMES a type: `logger::Logger::init()` is a use of `Logger`
        // itself, not only of `init` — without this the type reads as file-local to its
        // declaration and `internal-only` advises narrowing it. The extra
        // reference resolves through the segment before it (or bare at path root); an
        // unresolvable one (`Vec` of `Vec::new`) binds nothing and is dropped silently.
        if qualifier.chars().next().is_some_and(char::is_uppercase) {
            let type_scope = (rest.len() >= 2).then(|| rest[rest.len() - 2]);
            out.references.push(RawReference {
                name: SmolStr::new(qualifier),
                scope_context: type_scope.map(SmolStr::new),
                span: at,
                within: within.map(SmolStr::new),
                kind: RefKind::Read,
            });
        }
        // Multi-segment bare paths (`cycles::mod::item`, `serde_json::x::y`): the parent
        // path imports with the tail as its binding (so the item resolves in the deep
        // target), and the bare root imports alone as well — a deep path traverses the
        // crate's module tree from its entry, so the entry stays alive. For an
        // external crate the extra root import just duplicates the dependency edge.
        let import_worthy = !PRIMITIVES.contains(&root) && !env.locals.contains(root);
        // Whether this root is EVIDENCE of an external crate, as opposed to merely importable
        // as one. Two ways to lose it: the name is a type declared in this file, or the
        // context does not support the probe at all (a glob import in scope, a macro
        // template) — see `PathEnv`. Losing it downgrades the imports to Possible rather than
        // dropping them: `undeclared` ignores that tier (it never accuses), while the
        // dependency edge itself survives, so a DECLARED crate reached only through such a
        // path still reads as used. Suppressing the import outright instead cost alacritty
        // exactly that, turning `dirs` and `home` into false `unused` dependencies.
        let probes_crate = env.crate_probe && !env.file_types.contains(root);
        let probe_confidence = if probes_crate {
            Confidence::Probable
        } else {
            Confidence::Possible
        };
        if import_worthy && rest.len() == 1 && !root.chars().next().is_some_and(char::is_uppercase)
        {
            // Single-qualifier bare path (`helpers::run()`, `rand_chacha::x()`): the root
            // alone imports — a local module resolves to its file (resolution's local-retry
            // precedence), an unknown crate becomes the Dependency edge the `undeclared`
            // analysis needs, at `probe_confidence` so it only accuses where the root really
            // is evidence. The qualified reference stays for binding, and `local_alias`
            // carries the name it qualifies BY: the reference this branch emits reads
            // `scope_context: root`, and the adapter is the only side that can say so —
            // splitting the specifier to recover it was the core's one hardcoded path
            // separator. Non-settling by construction: the import is reconstructed, so its
            // confidence is never Certain and a miss keeps falling through the ladder.
            out.imports.push(RawImport {
                specifier: SmolStr::new(root),
                kind: ImportKind::Package,
                span: at,
                side_effect_only: true,
                type_only: false,
                confidence: probe_confidence,
                bindings: Vec::new(),
                reexported: false,
                opaque_namespace_use: false,
                module_names_visible: false,
                local_alias: Some(SmolStr::new(root)),
                // Synthesized from a use SITE: the file writes this path inline and no import
                // statement for it exists, so its binding must not outrank the file's own declarations.
                reconstructed: true,
            });
        }
        // The parent-path MODULE import is emitted regardless of `locals`: that guard
        // exists to stop fabricated ROOT/dependency imports for names a `use` already
        // covers, but a deep path (`kndo_core::discovery::find_files_named`) through a
        // use-covered root still needs ITS OWN module import to resolve — `use
        // kndo_core::{discovery}` binds `discovery`, not this path (a sibling
        // `use aa::{x}` would otherwise silently kill every `aa::y::f()` inline path in
        // the file). The duplicate dependency edge the root would add is exactly what the
        // guard still prevents below.
        let module_worthy = !PRIMITIVES.contains(&root);
        if module_worthy && rest.len() > 1 && !root.chars().next().is_some_and(char::is_uppercase) {
            out.imports.push(RawImport {
                specifier: SmolStr::new(rest.join("::")),
                kind: ImportKind::Package,
                span: at,
                side_effect_only: false,
                type_only: kind == RefKind::TypeUse,
                // A locals-covered root (`io::x::y` after `use std::io`) reconstructs at
                // Possible: the import exists for resolution keep-alive; it is NOT evidence
                // of a crate named `io` (`undeclared` ignores the Possible tier —
                // suppressing these entirely would kill real cross-crate paths). A root that
                // IS import-worthy still only reaches Probable when it probes.
                confidence: if import_worthy {
                    probe_confidence
                } else {
                    Confidence::Possible
                },
                bindings: vec![ImportBinding {
                    local: SmolStr::new(*last),
                    imported: Some(SmolStr::new(*last)),
                }],
                reexported: false,
                opaque_namespace_use: false,
                module_names_visible: false,
                // The segment the use site qualifies by: `kndo_core::discovery::find_files_named(..)`
                // writes `discovery`, and this synthetic import is what reaches that file.
                // Same reason as the shallow branch — the adapter knows the separator, the
                // core must not. Reconstructed, hence never Certain, hence non-settling.
                local_alias: Some(SmolStr::new(rest[rest.len() - 1])),
                // Synthesized from a use SITE: the file writes this path inline and no import
                // statement for it exists, so its binding must not outrank the file's own declarations.
                reconstructed: true,
            });
            if import_worthy {
                // The entry-liveness companion for a DEEP path — and it makes the same claim
                // about the root that the single-qualifier branch does, so it carries the
                // same `probe_confidence`. Hardcoding Probable here is what kept serde's
                // `fmt`, `net`, `_serde` and `fragment` accused after the shallow branch
                // stopped: `fmt::Write::write_fmt(…)` is three segments, so only this branch
                // ever fired for it.
                out.imports.push(RawImport {
                    specifier: SmolStr::new(root),
                    kind: ImportKind::Package,
                    span: at,
                    side_effect_only: true,
                    type_only: false,
                    confidence: probe_confidence,
                    bindings: Vec::new(),
                    reexported: false,
                    opaque_namespace_use: false,
                    module_names_visible: false,
                    local_alias: None,
                    // Synthesized from a use SITE: the file writes this path inline and no import
                    // statement for it exists, so its binding must not outrank the file's own declarations.
                    reconstructed: true,
                });
            }
            // The binding resolves the plain name — no qualifier needed for this one.
            out.references.push(RawReference {
                name: SmolStr::new(*last),
                scope_context: None,
                span: at,
                within: within.map(SmolStr::new),
                kind,
            });
        }
    }
}

fn handle_macro(
    node: Node,
    src: &[u8],
    within: Option<&str>,
    env: PathEnv<'_>,
    out: &mut FileFacts,
) {
    let Some(macro_name) = node.child_by_field_name("macro") else {
        return;
    };
    let name = text(macro_name, src);
    out.references.push(RawReference {
        name: SmolStr::new(name.rsplit("::").next().unwrap_or(name)),
        scope_context: None,
        span: span(macro_name),
        within: within.map(SmolStr::new),
        kind: RefKind::Call,
    });

    // env!("CARGO_BIN_EXE_<name>"): Cargo's own handshake for "this test executes the
    // workspace binary <name>" — the declared subprocess invocation the core resolves
    // through the manifest's named bins (the invoked-program rule). Only the
    // documented prefix, only a literal: never inferred from arbitrary strings.
    if matches!(name, "env" | "option_env") {
        if let Some(exe) = first_string_literal(node, src)
            .and_then(|lit| lit.strip_prefix("CARGO_BIN_EXE_"))
            .filter(|exe| !exe.is_empty())
        {
            out.invoked_executables.push(SmolStr::new(exe));
        }
        // Fall through: the token tree may still name identifiers worth scanning.
    }

    // include!/include_str!/include_bytes! with a literal: a probable file edge.
    if matches!(name, "include" | "include_str" | "include_bytes") {
        if let Some(lit) = first_string_literal(node, src) {
            out.imports.push(RawImport {
                specifier: SmolStr::new(format!("file:{lit}")),
                kind: ImportKind::Relative,
                span: span(node),
                side_effect_only: true,
                type_only: false,
                confidence: Confidence::Probable,
                bindings: Vec::new(),
                reexported: false,
                opaque_namespace_use: false,
                module_names_visible: false,
                local_alias: None,
                reconstructed: false,
            });
            return;
        }
    }

    // Identifier tokens inside the macro's token tree: plain reads (`format!("{}", user)`
    // keeps `user`'s referents alive). No wildcard per macro — the bounded stance.
    scan_token_tree(node, src, within, env, out);
}

fn first_string_literal<'a>(node: Node, src: &'a [u8]) -> Option<&'a str> {
    if node.kind() == "string_content" {
        return Some(text(node, src));
    }
    let mut cursor = node.walk();
    for child in node.children(&mut cursor) {
        if let Some(found) = first_string_literal(child, src) {
            return Some(found);
        }
    }
    None
}

fn scan_token_tree(
    node: Node,
    src: &[u8],
    within: Option<&str>,
    env: PathEnv<'_>,
    out: &mut FileFacts,
) {
    // A macro TEMPLATE describes code that does not exist yet, under names the expansion
    // invents: serde_derive's `quote!` bodies alone name `_serde`, `__S`, `__D`, `__E`, `__A`,
    // `__Field`, `__private` and `clippy::…`, and a `macro_rules!` right-hand side names
    // `$crate::fragment::…` with the metavariable stripped by token reconstruction. None of
    // those is a crate, and every one was reported as a phantom dependency. Identifier reads
    // and module imports still go out — keep-alive is the whole reason this scan exists — but
    // nothing inside a template is evidence for an ACCUSATION.
    //
    // The boundary is the token tree, not the call: `serde_json::json!(…)`'s own path is
    // ordinary code at the call site and must keep probing (an undeclared `serde_json` is a
    // real finding). It is a SIBLING of the token tree under `macro_invocation`, so flipping
    // the flag here — where the node itself is the tree — leaves it alone, and the recursion
    // carries the flag down to everything inside.
    let env = if node.kind() == "token_tree" {
        PathEnv {
            crate_probe: false,
            ..env
        }
    } else {
        env
    };
    // Rust 2021 inline format captures: `format!("v{VERSION}")` reads `VERSION` from inside
    // the string literal — invisible to the identifier-token scan below, so string content
    // in macro token trees is scanned for `{ident}` / `{ident:spec}` shapes (`{{` escapes
    // skipped, non-identifier args like `{}` / `{0}` ignored).
    if node.kind() == "string_content" {
        for name in format_captures(text(node, src)) {
            out.references.push(RawReference {
                name: SmolStr::new(name),
                scope_context: None,
                span: span(node),
                within: within.map(SmolStr::new),
                kind: RefKind::Read,
            });
        }
        return;
    }
    // Linear token pass, one level: expression code inside a macro is token soup, so
    // `render::render_query(x)` arrives as loose `identifier :: identifier` tokens — the
    // same reconstruction as attribute arguments, routed through the body-path rule
    // (`emit_path`) so qualified names bind exactly as they would outside the macro. Lone
    // identifiers stay plain reads. A following sibling `token_tree` is an argument list —
    // that path is a call.
    let mut cursor = node.walk();
    let children: Vec<Node> = node.children(&mut cursor).collect();
    let mut i = 0;
    while i < children.len() {
        let tok = children[i];
        if tok.kind() == "use" {
            // A `use` statement inside a macro body (`harness!(…, { use std::{thread::sleep,
            // time::Duration}; … })`): its inner segments are import structure, not
            // expression paths — reconstructing them as paths fabricates `thread`/`time`
            // phantom packages. Keep the root as a side-effect
            // import (the real dependency edge; stdlib resolves harmlessly) and skip the
            // statement's remaining tokens through its `;`.
            if let Some(root) = children.get(i + 1).filter(|n| n.kind() == "identifier") {
                let name = text(*root, src);
                if !PRIMITIVES.contains(&name) && !env.locals.contains(name) {
                    out.imports.push(RawImport {
                        specifier: SmolStr::new(name),
                        kind: ImportKind::Package,
                        span: span(*root),
                        side_effect_only: true,
                        type_only: false,
                        confidence: Confidence::Probable,
                        bindings: Vec::new(),
                        reexported: false,
                        opaque_namespace_use: false,
                        module_names_visible: false,
                        local_alias: None,
                        // Synthesized from a use SITE: the file writes this path inline and no import
                        // statement for it exists, so its binding must not outrank the file's own declarations.
                        reconstructed: true,
                    });
                }
            }
            let mut j = i + 1;
            while j < children.len() && children[j].kind() != ";" {
                j += 1;
            }
            i = j + 1;
            continue;
        }
        if matches!(tok.kind(), "identifier" | "crate" | "self" | "super") {
            i = scan_identifier_run(&children, i, src, within, env, out);
        } else {
            scan_token_tree(tok, src, within, env, out);
            i += 1;
        }
    }
}

/// One identifier-led token run: a reconstructed `a::b` path (routed through the body-path
/// rule), a `recv.member(…)` chain ([`scan_member_chain`]), or a lone identifier read.
/// Returns the index after the consumed run.
fn scan_identifier_run(
    children: &[Node],
    i: usize,
    src: &[u8],
    within: Option<&str>,
    env: PathEnv<'_>,
    out: &mut FileFacts,
) -> usize {
    let tok = children[i];
    let (segments, j) = collect_path_segments(children, i, src);
    if segments.len() > 1 {
        let kind = if children.get(j).is_some_and(|n| n.kind() == "token_tree") {
            RefKind::Call
        } else {
            RefKind::Read
        };
        emit_path(&segments, span(tok), within, kind, env, out);
        return j;
    }
    if let Some(next) = scan_member_chain(children, tok, j, src, within, env, out) {
        return next;
    }
    if tok.kind() == "identifier" {
        out.references.push(RawReference {
            name: SmolStr::new(segments[0]),
            scope_context: None,
            span: span(tok),
            within: within.map(SmolStr::new),
            kind: RefKind::Read,
        });
    }
    j
}

/// A `::`-joined identifier run starting at `i`: the reconstructed segments plus the index
/// after them.
fn collect_path_segments<'a>(children: &[Node], i: usize, src: &'a [u8]) -> (Vec<&'a str>, usize) {
    let mut segments = vec![text(children[i], src)];
    let mut j = i + 1;
    while j + 1 < children.len()
        && children[j].kind() == "::"
        && matches!(
            children[j + 1].kind(),
            "identifier" | "crate" | "self" | "super"
        )
    {
        segments.push(text(children[j + 1], src));
        j += 2;
    }
    (segments, j)
}

/// A member chain inside a macro token tree — `write!(w, "{}", flag.doc_short())` (a call
/// on a typed receiver) arrives
/// as loose `identifier . identifier token_tree` tokens, the token soup's counterpart of
/// the body's receiver typing. The receiver types through the same [`TypeEnv`] the body
/// uses (`flag: &dyn Flag` → qualifier `Flag`; untyped falls back to the raw receiver name,
/// the duck route, exactly as outside macros); each further hop extends the dotted pointer
/// for the core's member-type chain resolution. Emits the receiver's own read plus one
/// member reference per hop, and returns the index after the consumed chain — `None` when
/// no chain starts at `j` (the caller's plain-read path stands).
/// The chain's starting qualifier: the receiver's TypeEnv type (its raw name when untyped —
/// the duck route), `self` through the impl owner. Emits the receiver's own read.
fn chain_receiver_qualifier(
    receiver: Node,
    src: &[u8],
    within: Option<&str>,
    env: PathEnv<'_>,
    out: &mut FileFacts,
) -> Option<String> {
    match receiver.kind() {
        "identifier" => {
            let name = text(receiver, src);
            out.references.push(RawReference {
                name: SmolStr::new(name),
                scope_context: None,
                span: span(receiver),
                within: within.map(SmolStr::new),
                kind: RefKind::Read,
            });
            Some(
                env.types
                    .bindings
                    .get(name)
                    .cloned()
                    .unwrap_or_else(|| name.to_string()),
            )
        }
        "self" => env.types.owner.clone(),
        _ => None,
    }
}

fn scan_member_chain(
    children: &[Node],
    receiver: Node,
    j: usize,
    src: &[u8],
    within: Option<&str>,
    env: PathEnv<'_>,
    out: &mut FileFacts,
) -> Option<usize> {
    let follows_dot_ident = |at: usize| {
        children.get(at).is_some_and(|n| n.kind() == ".")
            && children
                .get(at + 1)
                .is_some_and(|n| n.kind() == "identifier")
    };
    if !follows_dot_ident(j) {
        return None;
    }
    let qualifier = chain_receiver_qualifier(receiver, src, within, env, out)?;
    Some(walk_chain(children, j, qualifier, src, within, env, out))
}

/// The chain's hops, one member reference each, the qualifier extending per hop; argument
/// token trees are real code — consumed here, so scanned here. Returns the index after the
/// chain.
#[allow(clippy::too_many_arguments)] // the token-scan state, same shape as its callers
fn walk_chain(
    children: &[Node],
    j: usize,
    mut qualifier: String,
    src: &[u8],
    within: Option<&str>,
    env: PathEnv<'_>,
    out: &mut FileFacts,
) -> usize {
    let follows_dot_ident = |at: usize| {
        children.get(at).is_some_and(|n| n.kind() == ".")
            && children
                .get(at + 1)
                .is_some_and(|n| n.kind() == "identifier")
    };
    let mut at = j;
    while follows_dot_ident(at) {
        let member = children[at + 1];
        let name = text(member, src);
        let args = children
            .get(at + 2)
            .filter(|n| n.kind() == "token_tree")
            .copied();
        out.references.push(RawReference {
            name: SmolStr::new(name),
            scope_context: Some(SmolStr::new(&qualifier)),
            span: span(member),
            within: within.map(SmolStr::new),
            kind: if args.is_some() {
                RefKind::Call
            } else {
                RefKind::Read
            },
        });
        qualifier = format!("{qualifier}.{name}");
        at += 2;
        if let Some(args) = args {
            scan_token_tree(args, src, within, env, out);
            at += 1;
        }
    }
    at
}

/// The identifier-shaped inline captures of a format string body: `{name}` and `{name:spec}`,
/// with `{{`/`}}` escapes honored. Positional (`{}`, `{0}`) and anything not a lone identifier
/// contribute nothing.
fn format_captures(s: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let bytes = s.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] != b'{' {
            i += 1;
            continue;
        }
        if bytes.get(i + 1) == Some(&b'{') {
            i += 2; // escaped brace
            continue;
        }
        let start = i + 1;
        let mut j = start;
        while j < bytes.len() && bytes[j] != b'}' && bytes[j] != b':' {
            j += 1;
        }
        let candidate = &s[start..j];
        let is_ident = !candidate.is_empty()
            && candidate
                .chars()
                .next()
                .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
            && candidate
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '_');
        if is_ident {
            out.push(candidate);
        }
        i = j + 1;
    }
    out
}

