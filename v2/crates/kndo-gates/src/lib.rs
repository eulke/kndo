pub fn render_ci() -> String {
    let names: Vec<&str> = GATES.iter().map(|g| g.name).collect();
    let steps: String = GATES
        .iter()
        .map(|g| {
            format!(
                "      - name: gate — {} ({})\n        run: cargo test -p kndo-gates --test gates -- --exact {}\n",
                g.name, g.invariant, g.name
            )
        })
        .collect();
    TEMPLATE
        .replace("@GATE_NAMES@", &names.join(" "))
        .replace("@GATE_STEPS@", &steps)
}
