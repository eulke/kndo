//! The gate registry — the single source the CI workflow is GENERATED from.
//!
//! v1 kept the invariant list in three hand-synced places (a prose list, the workflow
//! steps, and the grep of `--list`), with a recorded incident: a named gate that had
//! never once passed in CI while appearing in the job list. Here the registry is the
//! only spelling: `cargo xtask gen-ci` renders `.github/workflows/v2.yml` from it, the
//! workflow's existence check greps the same names, and the `generated_ci_is_current`
//! gate fails the build when the committed file and the generator drift. Renaming or
//! deleting a gate without regenerating cannot pass.

use std::path::PathBuf;

pub struct Gate {
    /// The `#[test]` function name in `tests/gates.rs` — checked against `--list`.
    pub name: &'static str,
    /// One line of what the gate protects, rendered into the step name.
    pub invariant: &'static str,
}

